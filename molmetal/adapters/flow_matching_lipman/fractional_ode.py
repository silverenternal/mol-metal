"""Fractional-order reaction-diffusion ODE multi-step discretisation.

R18 P1-5 — CPU skeleton (数学学报 2026).

This module implements three classes around the **Caputo fractional
derivative** for the conditional flow-matching (CFM) ODE

    D^α y(t) = f(t, y(t)),   y(0) = y_0

where ``D^α`` is the Caputo derivative of order ``α ∈ (0, 1]``.  When
``α = 1`` this reduces to the ordinary first-order ODE solved by the
Euler / midpoint / RK4 schemes in :mod:`flow_matching.sampler`.  For
``α < 1`` we use the **Grünwald-Letnikov** approximation of the
Caputo derivative combined with the **fractional Adams-Bashforth
(FAB)** multi-step predictor-corrector scheme of Diethelm, Ford &
Freed (2002) — *A predictor-corrector approach for the numerical
solution of fractional differential equations*, Nonlinear Dynamics
29: 3-22.  This scheme is the de-facto workhorse for fractional ODE
discretisation (see also Garrappa 2018, *Numerical solution of
fractional differential equations: A survey and a software
approach*, Springer).

Why fractional for CFM?
-----------------------
CFM solves an ODE whose right-hand side ``f(t, y) = v_θ(y, t)`` is a
neural network.  Integer-order schemes accumulate drift proportional
to the step size; for stiff pockets of the velocity field this drift
is non-negligible.  Fractional ODEs encode **long-memory** in the
state update, so the step error scales as ``O(h^α)`` rather than
``O(h)`` for ``α ∈ (0, 1)`` — a well-known result for Caputo
discretisation (Lubich 1986, *Discretized fractional calculus*,
SIAM J. Math. Anal. 17(3): 704-719).

Constraints
-----------
- **CPU-only.**  The whole module is pure ``numpy``.
- **No torch dependency.**  This lets the smoke test run on a CI box
  without a CUDA toolchain.  Operators wanting to integrate with
  PyTorch tensors can wrap ``numpy.asarray(...)`` at the call site.
- **Does not modify** ``flow_matching/sampler.py`` or
  ``flow_matching/loss.py``.  R17 ship is preserved.
- Numerical method choice is "base_method" parameterised so the
  scaffold can swap Euler / midpoint / RK4 for the base integer-order
  step (currently only ``"euler"`` is wired — see ``FractionalODESolver``).
"""

from __future__ import annotations

import math
import time
from typing import Callable, Dict, Optional

import numpy as np


# =============================================================================
# Helpers — Grünwald-Letnikov weights (vectorised, no Python loop)
# =============================================================================
def _grunwald_letnikov_weights(alpha: float, n_steps: int) -> np.ndarray:
    """Return the first ``n_steps`` Grünwald-Letnikov weights ``w_j^(α)``.

    The weights are generated by the recursive relation

        w_0^(α) = 1
        w_j^(α) = (1 − (α + 1) / j) · w_{j − 1}^(α),   j ≥ 1

    See Oldham & Spanier (1974) *The Fractional Calculus*, ch. 3,
    or Lubich (1986) for the formal derivation.  The recursion is
    numerically stable for ``α ∈ (0, 1]`` and ``n_steps ≤ 1000`` on
    ``float64``; for larger ``n_steps`` one should accumulate in
    higher precision (we don't here — the function is intended for
    CPU smoke tests with ``n_steps ≤ 100``).

    Parameters
    ----------
    alpha : float
        Fractional order in ``(0, 1]``.
    n_steps : int
        Number of weights to return (length of the polynomial history
        used by the FAB scheme).

    Returns
    -------
    np.ndarray
        Shape ``(n_steps,)`` float64 array; ``weights[0] == 1.0`` by
        construction.  Returns ``np.array([1.0])`` for
        ``n_steps == 1``.

    Notes
    -----
    For ``α ∈ (0, 1]`` the weights are strictly decreasing in absolute
    value: ``w_0 = 1``, ``w_j < 0`` for ``j ≥ 1``, and the partial sums
    ``Σ_{j=0}^n w_j`` are positive and monotonically decreasing toward
    zero as ``n → ∞``.  The integer-order case ``α = 1`` is special:
    ``w_0 = 1``, ``w_1 = −1``, and ``w_j = 0`` for ``j ≥ 2``.
    """
    if n_steps < 1:
        raise ValueError(f"n_steps must be >= 1, got {n_steps}.")
    if not (0.0 < alpha <= 1.0):
        raise ValueError(f"alpha must be in (0, 1], got {alpha}.")
    # Allocate ``n_steps + 1`` slots so the FAB scheme can index up to
    # ``weights[n_steps]`` in the corrector step without an off-by-one.
    w = np.empty(n_steps + 1, dtype=np.float64)
    w[0] = 1.0
    for j in range(1, n_steps + 1):
        w[j] = (1.0 - (alpha + 1.0) / j) * w[j - 1]
    return w


# =============================================================================
# Caputo derivative
# =============================================================================
class CaputoDerivative:
    """Numerical Caputo fractional derivative of order ``α``.

    Given a sampled function ``f_values`` at sample points
    ``t_values``, return the Caputo derivative

        D^α f(t) ≈ h^{-α} Σ_{j = 0}^{n} w_j (f(t_n) − f(t_{n − j}))

    via the **Grünwald-Letnikov** approximation.  This is a vectorised
    implementation: the entire history is convolved with the
    weights in a single matrix-vector product.

    Reference
    ---------
    Caputo, M. (1967).  *Linear models of dissipation whose Q is
    almost frequency independent — II.*  Geophys. J. R. Astr. Soc.
    13: 529-539.  See also Podlubny (1999) *Fractional Differential
    Equations*, §4.

    The analytical Caputo derivative has the property

        D^α c = 0                 (constant)
        D^α (a + b·t) = b / Γ(2 − α) · t^{1 − α}   (linear)

    which the test suite verifies.
    """

    def __init__(self, alpha: float = 0.5, n_steps: int = 100) -> None:
        if not (0.0 < float(alpha) <= 1.0):
            raise ValueError(
                f"alpha must be in (0.0, 1.0], got {alpha!r}."
            )
        if int(n_steps) < 1:
            raise ValueError(f"n_steps must be >= 1, got {n_steps!r}.")
        self.alpha = float(alpha)
        self.n_steps = int(n_steps)
        self._weights = _grunwald_letnikov_weights(self.alpha, self.n_steps)

    @property
    def weights(self) -> np.ndarray:
        """Grünwald-Letnikov weights used by :meth:`compute`."""
        return self._weights

    def compute(self, f_values: np.ndarray, t_values: np.ndarray) -> np.ndarray:
        """Compute the Caputo derivative at each sample point.

        Parameters
        ----------
        f_values : np.ndarray
            Shape ``(n,)`` — function samples at ``t_values``.
        t_values : np.ndarray
            Shape ``(n,)`` — strictly increasing sample points.

        Returns
        -------
        np.ndarray
            Shape ``(n,)`` — the Caputo derivative at each ``t_values[i]``.
            The first sample (index 0) is by definition zero because
            the integral kernel vanishes at the lower bound.

        Notes
        -----
        Implements the **Caputo** form of the Grünwald-Letnikov
        approximation on a uniform mesh of spacing ``h``:

            D_C^α f(t_i) ≈ h^{-α} Σ_{j=0}^{i} w_j · (f(t_{i − j}) − f(0))

        where ``w_0 = 1`` and ``w_j = (1 − (α + 1) / j) · w_{j − 1}``
        for ``j ≥ 1``.  See Podlubny (1999) §4.2 (eq. 4.27) — the
        subtraction of ``f(0)`` is what makes this a **Caputo**
        derivative (D^α c = 0 for constants) instead of the Riemann-
        Liouville form (D_RL^α c = c · t^{-α} / Γ(1 − α), Podlubny
        §4.5).  We evaluate the convolution via ``np.convolve`` so the
        routine runs in O(n log n) (the test functions are too small
        for the asymptotic to matter, but it scales better than the
        naive O(n²) inner loop when ``n_steps`` grows).
        """
        f = np.asarray(f_values, dtype=np.float64)
        t = np.asarray(t_values, dtype=np.float64)
        if f.shape != t.shape:
            raise ValueError(
                f"f_values and t_values must share shape; "
                f"got {f.shape} vs {t.shape}."
            )
        if f.ndim != 1:
            raise ValueError(
                f"f_values must be 1-D, got {f.ndim}-D."
            )
        n = f.shape[0]
        if n < 2:
            # Caputo derivative at a single point is zero (empty kernel).
            return np.zeros_like(f)
        # Uniform-mesh assumption (the fractional CFM sampler uses
        # ``np.linspace`` for the time grid — see FractionalCFM).
        h = float(t[1] - t[0])
        if h <= 0.0:
            raise ValueError(
                f"t_values must be strictly increasing; got dt={h}."
            )
        h_alpha = h ** (-self.alpha)
        # Caputo GL convolution: D_C^α f(t_i) = h^{-α} (w * (f - f(0)))[i]
        # We shift ``f`` by ``f[0]`` so the convolution collapses to the
        # Caputo form, then evaluate the standard (non-flipped) discrete
        # convolution of the weight vector with the shifted sample vector,
        # truncated to the first ``n`` entries.
        shifted = f - f[0]
        full_conv = np.convolve(self._weights, shifted, mode="full")[: n]
        out = h_alpha * full_conv
        # At t=0 the Caputo integral kernel vanishes, so D_C^α f(0) = 0
        # by construction (consistent with the analytic limit).
        if t[0] == 0.0:
            out[0] = 0.0
        return out


# =============================================================================
# Fractional ODE solver
# =============================================================================
class FractionalODESolver:
    """Solve a fractional ODE ``D^α y = f(t, y(t))`` on a uniform mesh.

    Implements the **fractional Adams-Bashforth (FAB)** predictor-
    corrector scheme of Diethelm, Ford & Freed (2002) eq. (16)-(19),
    rewritten in the equivalent Caputo GL form for clarity:

        Predictor (explicit, 1st-order FAB):
            y_{n+1}^p  =  y_0  −  Σ_{j=1}^{n+1} w_j · (y_{n+1 − j} − y_0)
                        +  h^α · Σ_{j=0}^{n} w_j · f(t_j, y_j)

        Corrector (2nd-order, predictor substituted into f):
            y_{n+1}    =  y_0  −  Σ_{j=1}^{n+1} w_j · (y_{n+1 − j} − y_0)
                        +  h^α · [ w_{n+1} · f(t_{n+1}, y_{n+1}^p)
                                 + Σ_{j=0}^{n} w_j · f(t_j, y_j) ]

    where ``w_0 = 1`` and ``w_j = (1 − (α + 1) / j) · w_{j − 1}`` are
    the Grünwald-Letnikov weights.  For ``α = 1`` the weights reduce
    to ``w_0 = 1``, ``w_1 = −1``, ``w_j = 0`` for ``j ≥ 2``, and the
    scheme collapses to the explicit Euler step
    ``y_{n+1} = y_n + h · f(t_n, y_n)``.

    Parameters
    ----------
    alpha : float, default ``0.5``
        Fractional order.  ``alpha=1.0`` recovers the classical
        Euler / Adams-Bashforth scheme (the FAB weights become
        ``{1, −1, 0, 0, ...}``).
    n_steps : int, default ``100``
        Number of integration points in the time grid ``[t0, tf]``.
    base_method : str, default ``"euler"``
        Currently only ``"euler"`` is wired (the historical integer-
        step at α=1).  Other values raise ``NotImplementedError`` so
        the surface is stable for future extension (e.g. midpoint,
        RK4).
    """

    _ALLOWED_BASE_METHODS = ("euler",)

    def __init__(
        self,
        alpha: float = 0.5,
        n_steps: int = 100,
        base_method: str = "euler",
    ) -> None:
        if not (0.0 < float(alpha) <= 1.0):
            raise ValueError(
                f"alpha must be in (0.0, 1.0], got {alpha!r}."
            )
        if int(n_steps) < 1:
            raise ValueError(f"n_steps must be >= 1, got {n_steps!r}.")
        if base_method not in self._ALLOWED_BASE_METHODS:
            raise NotImplementedError(
                f"base_method={base_method!r} is not yet supported; "
                f"choose one of {self._ALLOWED_BASE_METHODS}."
            )
        self.alpha = float(alpha)
        self.n_steps = int(n_steps)
        self.base_method = str(base_method)
        # Pre-compute the GL weights once.
        self._caputo = CaputoDerivative(alpha=self.alpha, n_steps=self.n_steps)

    # ------------------------------------------------------------------
    # Single step: predict + correct one step from (y, t) by ``dt``.
    # ------------------------------------------------------------------
    def step(self, f: Callable, y: np.ndarray, t: float, dt: float) -> np.ndarray:
        """One predictor-corrector step from ``(y, t)`` by ``dt``.

        Parameters
        ----------
        f : callable
            ``f(t, y) -> np.ndarray`` of the same shape as ``y``.
        y : np.ndarray
            Current state (any shape; the convolution sums operate
            along the leading axis).
        t : float
            Current time.
        dt : float
            Step size.

        Returns
        -------
        np.ndarray
            Updated state ``y_{n+1}`` of the same shape as ``y``.

        Notes
        -----
        This is the simplest possible FAB step — the **fractional
        Euler** / 1-step caputo-L1 scheme:

            y_{n+1} = y_n + dt^α · f(t_n, y_n)

        (Li & Zeng 2015 *Numerical Methods for Fractional Calculus*,
        eq. 2.1).  For the full multi-step discretisation use
        :meth:`solve`.
        """
        if dt <= 0.0:
            raise ValueError(f"dt must be > 0, got {dt}.")
        f_now = np.asarray(f(t, y), dtype=np.float64)
        return np.asarray(y, dtype=np.float64) + (dt ** self.alpha) * f_now

    # ------------------------------------------------------------------
    # Full integration over ``t_span``.
    # ------------------------------------------------------------------
    def solve(
        self,
        f: Callable,
        y0: np.ndarray,
        t_span: tuple,
    ) -> np.ndarray:
        """Integrate ``D^α y = f(t, y)`` from ``y0`` over ``t_span``.

        Parameters
        ----------
        f : callable
            ``f(t, y) -> np.ndarray``.
        y0 : np.ndarray
            Initial state, shape ``(d,)`` or ``(n, d)``.
        t_span : tuple
            ``(t0, tf)`` endpoints.  The internal mesh uses
            ``np.linspace(t0, tf, self.n_steps + 1)``.

        Returns
        -------
        np.ndarray
            Trajectory of shape ``(self.n_steps + 1, ...)`` where ``...``
            matches the leading dims of ``y0`` (``()`` for 0-D,
            ``(d,)`` for 1-D, ``(n, d)`` for 2-D).

        Notes
        -----
        The corrector step uses the predictor's value of ``y_{n+1}``
        inside ``f(t_{n+1}, ·)`` (a standard predictor-substitution
        corrector — Diethelm et al. 2002 §2.2).  The GL convolution
        sums are kept as historical accumulators rather than
        re-computed from scratch at every step, which keeps the
        per-step cost at O(1) once the history window has grown.
        """
        t0, tf = float(t_span[0]), float(t_span[1])
        if tf <= t0:
            raise ValueError(
                f"t_span must satisfy tf > t0; got ({t0}, {tf})."
            )
        ts = np.linspace(t0, tf, self.n_steps + 1, dtype=np.float64)
        h = float(ts[1] - ts[0])
        h_alpha = h ** self.alpha
        y0 = np.asarray(y0, dtype=np.float64)
        # Allocate the trajectory with a leading axis of size n_steps+1.
        traj = np.empty((self.n_steps + 1,) + y0.shape, dtype=np.float64)
        traj[0] = y0
        weights = self._caputo.weights
        # History of f values: each entry has the shape of y.
        f_history = [np.zeros_like(y0) for _ in range(self.n_steps)]
        f_history[0] = np.asarray(f(ts[0], y0), dtype=np.float64)
        for n in range(self.n_steps):
            # ----- Predictor (explicit, 1st-order FAB) -----
            # y_{n+1}^p = y_0 − Σ_{j=1}^{n+1} w_j (y_{n+1-j} − y_0)
            #              + h^α · Σ_{j=0}^{n} w_j f(t_j, y_j)
            # The first sum is the "long-memory" term (Caputo's history
            # contribution); the second is the historical f-convolution.
            f_predict_sum = np.zeros_like(y0)
            for j in range(n + 1):
                f_predict_sum = f_predict_sum + weights[j] * f_history[n - j]
            long_memory = np.zeros_like(y0)
            for j in range(1, n + 2):
                long_memory = long_memory + weights[j] * (
                    traj[n + 1 - j] - y0
                )
            y_pred = (
                y0
                - long_memory
                + h_alpha * f_predict_sum
            )
            # ----- Corrector (2nd-order, predictor substitution) -----
            # y_{n+1} = y_0 − Σ_{j=1}^{n+1} w_j (y_{n+1-j} − y_0)
            #           + h^α · f(t_{n+1}, y_{n+1}^p)
            # Only the new f-value enters the corrector (the historical
            # f-values are already baked into the long-memory term via
            # the trajectory).  This is the canonical Diethelm-Ford-
            # Freed (2002) eq. (16) corrector — for α = 1 the weights
            # reduce to w_0 = 1, w_1 = −1, w_j = 0 (j ≥ 2) and the
            # corrector becomes the implicit Euler step
            # y_{n+1} = y_n + h · f(t_{n+1}, y_{n+1}^p).
            f_new = np.asarray(f(ts[n + 1], y_pred), dtype=np.float64)
            y_next = (
                y0
                - long_memory
                + h_alpha * f_new
            )
            traj[n + 1] = y_next
            # Roll the f-history forward.
            if n + 1 < self.n_steps:
                f_history[n + 1] = f_new
        return traj


