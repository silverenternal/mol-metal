# Fractional CFM
# =============================================================================
class FractionalCFM:
    """Fractional-order CFM wrapper for comparison vs the integer-order sampler.

    Wraps a *base* CFM (any callable that returns ``z(t)`` for a
    given ``(z0, t)``) and exposes a fractional forward pass.  The
    class is intended for the **skeleton** round (R18 P1-5) — it
    runs on ``numpy`` and does **not** require a real CFM network.
    Operators wanting GPU/CPU parity with the production CFM sampler
    should call ``compare_with_base`` on a real
    :class:`LipmanFlowMatchingAdapter` and report the wall-time +
    accuracy deltas.

    Parameters
    ----------
    base_cfm : callable
        ``base_cfm(z0, t) -> np.ndarray`` returning the integer-order
        flow-matching state at ``t``.  For honest comparison this is
        the base Euler step ``z0 + t * (z1 - z0)`` (linear CFM path).
    alpha : float, default ``0.5``
        Fractional order for the wrapper solver.

    Notes
    -----
    **Honest framing.**  This class is the *CPU skeleton* — it is
    useful for studying the discretisation error of the FAB scheme
    on a known analytic trajectory, but it does NOT call into
    :class:`LipmanFlowMatchingAdapter` (which would require torch +
    a CUDA path).  For end-to-end integration with the production
    adapter, see the planned round R18 P1.6.
    """

    def __init__(
        self,
        base_cfm: Callable,
        alpha: float = 0.5,
    ) -> None:
        self.base_cfm = base_cfm
        self.alpha = float(alpha)
        self._solver = FractionalODESolver(alpha=self.alpha, n_steps=100)

    def forward(self, z0: np.ndarray, t: float) -> np.ndarray:
        """Return ``z(t)`` using the fractional solver.

        For the CPU skeleton we integrate over the full [0, t]
        interval and return the final state.  This is the
        ``z(t) = z(0) + D_t^α [some velocity]`` trajectory under the
        fractional FAB scheme; for a linear base trajectory
        ``v(z, s) = z1 − z0`` it recovers ``z(t) = z0 + t^α / Γ(α+1)
        (z1 - z0)`` (Mittag-Leffler kernel, see Mainardi 2010).
        """
        z0 = np.asarray(z0, dtype=np.float64)
        # Build the linear velocity field f(s, y) = (z1 - z0)/t
        # anchored on z0 (passed via closure).
        # The base_cfm is called at t=1.0 to get the analytic endpoint.
        z1 = np.asarray(self.base_cfm(z0, 1.0), dtype=np.float64)
        v = (z1 - z0) / max(t, 1e-12)
        traj = self._solver.solve(
            f=lambda _s, y: np.full_like(y, v),
            y0=z0,
            t_span=(0.0, float(t)),
        )
        return traj[-1]

    def compare_with_base(
        self,
        z0: np.ndarray,
        t: float,
        n_runs: int = 10,
    ) -> Dict:
        """Compare wall-time and accuracy vs the base (integer-order) CFM.

        Parameters
        ----------
        z0 : np.ndarray
            Initial state.
        t : float
            Time endpoint.
        n_runs : int, default ``10``
            Number of timing runs to average over.

        Returns
        -------
        dict
            ``{
                "fractional": {wall_time, endpoint, endpoint_norm},
                "base": {wall_time, endpoint, endpoint_norm},
                "accuracy": {abs_diff, rel_diff},
                "alpha": float,
                "n_runs": int,
            }``
        """
        if int(n_runs) < 1:
            raise ValueError(f"n_runs must be >= 1, got {n_runs}.")
        z0 = np.asarray(z0, dtype=np.float64)

        def _time_one(fn: Callable) -> float:
            t0 = time.perf_counter()
            out = fn()
            return time.perf_counter() - t0, out

        # Fractional side.
        frac_times = []
        frac_last = None
        for _ in range(int(n_runs)):
            dt, val = _time_one(lambda: self.forward(z0, t))
            frac_times.append(dt)
            frac_last = val
        # Base side.
        base_times = []
        base_last = None
        for _ in range(int(n_runs)):
            dt, val = _time_one(lambda: self.base_cfm(z0, t))
            base_times.append(dt)
            base_last = val
        abs_diff = float(np.linalg.norm(frac_last - base_last))
        base_norm = float(np.linalg.norm(base_last))
        rel_diff = abs_diff / base_norm if base_norm > 0.0 else 0.0
        return {
            "fractional": {
                "wall_time": float(sum(frac_times) / len(frac_times)),
                "endpoint": frac_last,
                "endpoint_norm": float(np.linalg.norm(frac_last)),
            },
            "base": {
                "wall_time": float(sum(base_times) / len(base_times)),
                "endpoint": base_last,
                "endpoint_norm": base_norm,
            },
            "accuracy": {
                "abs_diff": abs_diff,
                "rel_diff": rel_diff,
            },
            "alpha": self.alpha,
            "n_runs": int(n_runs),
        }


# =============================================================================
# Convergence rate (analytical / theoretical)
# =============================================================================
def fractional_convergence_rate(alpha: float, n_iters: int) -> float:
    """Return the expected convergence rate at iteration ``k``.

    The fractional Adams-Bashforth scheme has global order ``α`` for
    ``α ∈ (0, 1]`` (Diethelm et al. 2002 Thm 3.1).  The convergence
    rate per iteration is therefore

        rate(k) = k^{−α}

    For ``α = 1`` this reduces to the integer-order FAB rate
    ``1 / k``; for ``α = 0.5`` it is ``1 / √k``.

    Parameters
    ----------
    alpha : float
        Fractional order.
    n_iters : int
        Number of iterations ``k``.

    Returns
    -------
    float
        ``k^{−α}``.
    """
    if not (0.0 < float(alpha) <= 1.0):
        raise ValueError(f"alpha must be in (0.0, 1.0], got {alpha!r}.")
    if int(n_iters) < 1:
        raise ValueError(f"n_iters must be >= 1, got {n_iters!r}.")
    return float(n_iters) ** (-float(alpha))


