"""Paper §4 Table 2 auto-generator.

================================================================
R18 paper table — auto-format the e2e benchmark JSONs into
LaTeX Table 2 rows (R17 MEASURED + R18 e2e MEASURED + R18 GPU
PROJECTED) for paper/sections/04_results_table2_r18.tex.

The script reads:

* ``molmetal/reports/wf_e2e_pipeline/platinai_e2e.json``  (R18 e2e,
  500-sample PlatinAI 5K end-to-end pipeline benchmark)
* ``molmetal/reports/wf_e2e_pipeline/metalcytotox_e2e.json``
  (R18 e2e, 5-metal x 500-sample MetalCytoToxDB end-to-end)

The script writes:

* ``paper/sections/04_results_table2_r18.tex``  (LaTeX, ~100 lines,
  one row per metric, with MEASURED + PROJECTED columns and the
  responsible mechanism in the verdict column).

The script does NOT modify the existing
``paper/sections/04_results_table2.tex`` — that file is hand-curated
and the autogenerated copy is a side-by-side companion file
suffixed ``_r18.tex``.

Honest framing
--------------
Every MEASURED number is read directly from the e2e JSONs (per-step
status counts, per-sample success rate, per-step wall-time).  The
PROJECTED R18 GPU column is derived from the R17 MEASURED column
plus the structural-fix gap described in
``TODO/02_metrics/METRICS_TARGETS.md`` §2.  No cell is silently
fabricated; if the e2e JSON is missing or empty, the script tags
that row ``PENDING`` and writes a non-empty NaN-safe default.

Usage::

    # Default: read from the canonical e2e JSONs, write to canonical tex.
    uv run --no-sync python molmetal/scripts/paper_table_autogen.py

    # Custom paths / dry-run preview.
    uv run --no-sync python molmetal/scripts/paper_table_autogen.py \\
        --platinai-json <path> --metalcytotox-json <path> \\
        --out-tex <path> --dry-run
"""

