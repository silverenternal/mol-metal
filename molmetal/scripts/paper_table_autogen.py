# ---------------------------------------------------------------------------
# Metric registry — declarative table spec
#
# Each entry names a metric and binds it to:
#   * ``category``    — section header for the table
#   * ``mechanism``   — the responsible module/paper section (§3.x)
#   * ``direction``   — 'higher' (better when larger) or 'lower'
#   * ``r17_value``   — the R17 measured number (string; may include
#                       formatting such as '$\\geq 0.85$').  Used to
#                       fill the R17 column verbatim.
#   * ``target_value`` — the R18 GPU projection (string).
#   * ``verdict_r17`` — the honest framing text shown in the verdict
#                       column (lift / gap relative to baseline).
#   * ``extract``     — callable that takes the e2e JSON and returns
#                       a (r18_e2e_number, r18_e2e_seeds) tuple or
#                       (None, 0) if the metric is not derivable from
#                       the e2e run.
#
# The R17 column is taken verbatim from the existing hand-curated
# table; the R18 e2e column is computed by the ``extract`` callable;
# the R18 GPU column is the R17 target + structural-fix projection.
# ---------------------------------------------------------------------------
@dataclass
class Table2Row:
    """One Table-2 row — all columns populated, ready for LaTeX emit."""

    metric_id: str
    metric_label: str
    category: str
    mechanism: str
    direction: str  # 'higher' / 'lower'
    r17_value: str  # verbatim R17 MEASURED text
    r17_baseline: str  # Tier-1 baseline column
    target_value: str  # R18 GPU projection text
    verdict_r17: str  # honest framing
    r18_e2e_value: str  # computed from e2e JSON
    r18_e2e_seeds: int  # number of seeds / samples used
    responsible_section: str  # §3.x / §3.x.y pointer


# ---------------------------------------------------------------------------
# Extractors — turn the e2e JSONs into (number, samples) pairs
# ---------------------------------------------------------------------------
def _safe_get(d: Dict[str, Any], *keys: str, default: Any = None) -> Any:
    """Recursive safe-get for nested dicts."""
    cur: Any = d
    for k in keys:
        if not isinstance(cur, dict) or k not in cur:
            return default
        cur = cur[k]
    return cur


def _extract_platinai_success_rate(platinai: Dict[str, Any]) -> Tuple[Optional[float], int]:
    """PlatinAI: overall success rate (0-1) over n=500."""
    rate = platinai.get("success_rate")
    n = platinai.get("n_samples", 0) or 0
    if rate is None:
        return (None, 0)
    return (float(rate), int(n))


def _extract_platinai_step3_ok_rate(platinai: Dict[str, Any]) -> Tuple[Optional[float], int]:
    """PlatinAI: step3_multiph ok-rate (the bottleneck step)."""
    counts = _safe_get(platinai, "per_step_status_counts", "step3_multiph", default={})
    ok = counts.get("ok", 0) if isinstance(counts, dict) else 0
    total = sum(int(v) for v in counts.values()) if isinstance(counts, dict) else 0
    if total <= 0:
        return (None, 0)
    return (float(ok) / total, total)


def _extract_platinai_total_wall_time(platinai: Dict[str, Any]) -> Tuple[Optional[float], int]:
    """PlatinAI: total wall-clock seconds for the full pipeline."""
    wall = platinai.get("total_wall_time_s")
    n = platinai.get("n_samples", 0) or 0
    if wall is None:
        return (None, 0)
    return (float(wall), int(n))


def _extract_platinai_per_step_wall(platinai: Dict[str, Any], step: str) -> Tuple[Optional[float], int]:
    """PlatinAI: per-step total wall-clock (seconds)."""
    wall = _safe_get(platinai, "per_step_wall_time_s", step)
    n = platinai.get("n_samples", 0) or 0
    if wall is None:
        return (None, 0)
    return (float(wall), int(n))


def _extract_metalcytotox_overall(metalcytotox: Dict[str, Any]) -> Tuple[Optional[float], int]:
    """MetalCytoTox: aggregate success rate averaged over the 5 metals.

    Returns (mean_rate, total_samples).  If per_metal_success_rate is
    missing the function returns (None, 0).
    """
    rates = _safe_get(metalcytotox, "per_metal_success_rate", default={})
    if not isinstance(rates, dict) or not rates:
        return (None, 0)
    vals = [float(v) for v in rates.values() if isinstance(v, (int, float))]
    if not vals:
        return (None, 0)
    n_per_metal = _safe_get(metalcytotox, "n_samples_per_metal", default=0)
    n_metals = len(vals)
    total = int(n_per_metal) * int(n_metals)
    return (sum(vals) / len(vals), total)


def _extract_metalcytotox_per_metal_rate(metalcytotox: Dict[str, Any], metal: str) -> Tuple[Optional[float], int]:
    """MetalCytoTox: success rate for one specific metal (e.g. 'Ru')."""
    rates = _safe_get(metalcytotox, "per_metal_success_rate", default={})
    if not isinstance(rates, dict) or metal not in rates:
        return (None, 0)
    n_per_metal = _safe_get(metalcytotox, "n_samples_per_metal", default=0)
    return (float(rates[metal]), int(n_per_metal))


def _extract_metalcytotox_step3_error(metalcytotox: Dict[str, Any], metal: str) -> Tuple[Optional[float], int]:
    """MetalCytoTox: step3_multiph error count for one metal."""
    counts = _safe_get(metalcytotox, "per_step_per_metal_status_counts",
                       "step3_multiph", metal, default={})
    if not isinstance(counts, dict):
        return (None, 0)
    err = counts.get("error", 0)
    total = sum(int(v) for v in counts.values())
    if total <= 0:
        return (None, 0)
    return (float(err) / total, total)


