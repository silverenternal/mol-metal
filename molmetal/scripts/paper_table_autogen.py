def _build_argparser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="paper_table_autogen",
        description=(
            "Auto-format the R18 e2e benchmark JSONs into LaTeX Table 2 "
            "rows for paper/sections/04_results_table2_r18.tex."
        ),
    )
    p.add_argument(
        "--platinai-json",
        type=Path,
        default=PLATINAI_E2E_JSON,
        help=f"Path to platinai_e2e.json (default: {PLATINAI_E2E_JSON})",
    )
    p.add_argument(
        "--metalcytotox-json",
        type=Path,
        default=METALCYTOTOX_E2E_JSON,
        help=f"Path to metalcytotox_e2e.json (default: {METALCYTOTOX_E2E_JSON})",
    )
    p.add_argument(
        "--out-tex",
        type=Path,
        default=DEFAULT_OUT_TEX,
        help=f"Path to write the .tex file (default: {DEFAULT_OUT_TEX})",
    )
    p.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the rendered LaTeX to stdout instead of writing a file.",
    )
    p.add_argument(
        "--report-json",
        type=Path,
        default=None,
        help=(
            "Optional: also emit a machine-readable JSON report "
            "(row id, R17, R18 e2e, R18 GPU, mechanism) alongside the tex."
        ),
    )
    return p


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = _build_argparser()
    args = parser.parse_args(argv)

    platinai = _load_json(args.platinai_json)
    metalcytotox = _load_json(args.metalcytotox_json)

    rows = build_table_rows(platinai=platinai, metalcytotox=metalcytotox)

    if args.dry_run:
        sys.stdout.write(render_latex(rows))
        return 0

    out_path = write_table_tex(rows, args.out_tex)
    print(f"[paper_table_autogen] wrote {out_path} ({len(rows)} rows)")

    if args.report_json is not None:
        report = {
            "tool": "paper_table_autogen.py",
            "timestamp_utc": _dt.datetime.now(_dt.timezone.utc).isoformat(),
            "n_rows": len(rows),
            "platinai_json": str(args.platinai_json),
            "platinai_loaded": bool(platinai),
            "metalcytotox_json": str(args.metalcytotox_json),
            "metalcytotox_loaded": bool(metalcytotox),
            "rows": [
                {
                    "metric_id": r.metric_id,
                    "metric_label": r.metric_label,
                    "category": r.category,
                    "r17_value": r.r17_value,
                    "r18_e2e_value": r.r18_e2e_value,
                    "r18_e2e_seeds": r.r18_e2e_seeds,
                    "target_value": r.target_value,
                    "direction": r.direction,
                    "mechanism": r.mechanism,
                }
                for r in rows
            ],
        }
        args.report_json.parent.mkdir(parents=True, exist_ok=True)
        with open(args.report_json, "w", encoding="utf-8") as fh:
            json.dump(report, fh, indent=2)
        print(f"[paper_table_autogen] wrote {args.report_json}")
    return 0


if __name__ == "__main__":
    sys.exit(main())