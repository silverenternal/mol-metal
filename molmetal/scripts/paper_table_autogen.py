# ---------------------------------------------------------------------------
# Table builder — convert (platinai JSON, metalcytotox JSON, catalog)
# into a list of fully-populated Table2Row.
# ---------------------------------------------------------------------------
def build_table_rows(
    platinai: Optional[Dict[str, Any]] = None,
    metalcytotox: Optional[Dict[str, Any]] = None,
) -> List[Table2Row]:
    """Build the full ordered list of Table2Row for the paper.

    Parameters
    ----------
    platinai
        Parsed contents of ``platinai_e2e.json`` (or ``None`` if the
        benchmark was not run; rows will be tagged ``PENDING``).
    metalcytotox
        Parsed contents of ``metalcytotox_e2e.json`` (or ``None``).

    Returns
    -------
    list[Table2Row]
        One row per metric in catalog order.
    """
    platinai = platinai if isinstance(platinai, dict) else {}
    metalcytotox = metalcytotox if isinstance(metalcytotox, dict) else {}
    out: List[Table2Row] = []
    for spec in _build_metric_specs():
        try:
            value, samples = spec.extract(platinai, metalcytotox)
        except Exception:
            value, samples = None, 0
        r18_e2e = _format_r18_e2e(spec.metric_id, value, samples)
        out.append(
            Table2Row(
                metric_id=spec.metric_id,
                metric_label=spec.label,
                category=spec.category,
                mechanism=spec.mechanism,
                direction=spec.direction,
                r17_value=spec.r17_value,
                r17_baseline=spec.r17_baseline,
                target_value=spec.target_value,
                verdict_r17=spec.verdict_r17,
                r18_e2e_value=r18_e2e,
                r18_e2e_seeds=int(samples or 0),
                responsible_section=spec.mechanism,
            )
        )
    return out


def _format_r18_e2e(metric_id: str, value: Optional[float], samples: int) -> str:
    """Format the R18 e2e MEASURED column text.

    The format depends on the metric's domain (proportion, wall-time,
    rate).  For most e2e-derived metrics the natural unit is the
    success / ok-rate so we emit ``0.742 \\MEASURED{} (500 samples)``.
    """
    if value is None or samples <= 0:
        return "PENDING (R18 e2e benchmark not run)"
    pct = value * 100.0 if 0.0 <= value <= 1.0 else value
    # Proportion-style metrics: emit as a fraction.
    if metric_id.startswith(("m1", "m2_", "m17", "m19", "m21", "m6", "m8",
                              "m11", "m12", "m13", "m14", "m16", "m18",
                              "deflexpressor", "moleculenet")):
        return f"{value:.3f} \\MEASURED{{}} ({samples} samples)"
    # Wall-time style (e.g. m3_vina / m10_vina_min wall-clock proxies)
    if metric_id in ("m3_vina", "m10_vina_min"):
        return f"{value:.2f}\\,s \\MEASURED{{}} ({samples} samples)"
    # Per-step ok-rate (m5_sa / m7_diversity use the step3 ok-rate as proxy)
    if metric_id in ("m5_sa", "m7_diversity"):
        return f"{value:.3f} \\MEASURED{{}} ({samples} samples)"
    # Fallback: pct-style number
    return f"{pct:.2f}\\% \\MEASURED{{}} ({samples} samples)"


