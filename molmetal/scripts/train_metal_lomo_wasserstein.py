# Synthetic-row tag predicate (Wf-C1 generalisation of the Wf-A3 Rh fix)
# ---------------------------------------------------------------------------
#: Every generated row is tagged in the ``Cell_line`` column with a value that
#: *starts* with this prefix, followed by the element it was generated for
#: (``SYNTHETIC_RH``, and in future ``SYNTHETIC_Os``, ``SYNTHETIC_Pt``, ...).
#: Wf-A3 hard-coded the exact string ``"SYNTHETIC_RH"``, which meant any second
#: synthetic cohort silently re-introduced the "500 fabricated rows swept into
#: the held-out metal's TEST fold" bug.  Keying off the *prefix* makes the
#: guard total: a row is synthetic if and only if it was fabricated.
SYNTHETIC_CELL_LINE_PREFIX = "SYNTHETIC"


def synthetic_cell_line_tag(metal: str) -> str:
    """Canonical tag for a synthetic cohort generated for ``metal``.

    The element symbol is upper-cased so the on-disk value stays byte-identical
    to the historical ``"SYNTHETIC_RH"`` (other artefacts and prior metrics
    JSONs reference that exact string).
    """
    return f"{SYNTHETIC_CELL_LINE_PREFIX}_{str(metal).upper()}"


def synthetic_row_mask(df: "pd.DataFrame") -> "np.ndarray":
    """Boolean mask of fabricated rows in ``df``.

    Any row whose ``Cell_line`` value begins with ``SYNTHETIC`` (case
    insensitive, leading whitespace tolerated) is synthetic.  A dataframe with
    no ``Cell_line`` column — or one where every value is a real cell line —
    yields an all-False mask, so the guard is safe on every dataset shape.
    """
    n = len(df)
    col = "Cell_line"
    if col not in df.columns:
        return np.zeros(n, dtype=bool)
    vals = df[col].astype(str).str.strip().str.upper()
    return vals.str.startswith(SYNTHETIC_CELL_LINE_PREFIX).to_numpy()


