# ---------------------------------------------------------------------------
# Synthetic-row tag predicate (Wf-C1 generalisation of the Wf-A3 Rh fix)
# ---------------------------------------------------------------------------
#: Every generated row is tagged in the ``Cell_line`` column with a value that
#: *starts* with this prefix, followed by the element it was generated for
#: (``SYNTHETIC_RH``, and in future ``SYNTHETIC_Os``, ``SYNTHETIC_Pt``, ...).
#: Wf-A3 hard-coded the exact string ``"SYNTHETIC_RH"``, which meant any second
#: synthetic cohort silently re-introduced the "500 fabricated rows swept into
#: the held-out metal's TEST fold" bug.  Keying off the *prefix* makes the
#: guard total: a row is synthetic if and only if it was fabricated.
SYNTHETIC_CELL_LINE_PREFIX = "SYNTHETIC"


def synthetic_cell_line_tag(metal: str) -> str:
    """Canonical tag for a synthetic cohort generated for ``metal``.

    The element symbol is upper-cased so the on-disk value stays byte-identical
    to the historical ``"SYNTHETIC_RH"`` (other artefacts and prior metrics
    JSONs reference that exact string).
    """
    return f"{SYNTHETIC_CELL_LINE_PREFIX}_{str(metal).upper()}"


def synthetic_row_mask(df: "pd.DataFrame") -> "np.ndarray":
    """Boolean mask of fabricated rows in ``df``.

    Any row whose ``Cell_line`` value begins with ``SYNTHETIC`` (case
    insensitive, leading whitespace tolerated) is synthetic.  A dataframe with
    no ``Cell_line`` column — or one where every value is a real cell line —
    yields an all-False mask, so the guard is safe on every dataset shape.
    """
    n = len(df)
    col = "Cell_line"
    if col not in df.columns:
        return np.zeros(n, dtype=bool)
    vals = df[col].astype(str).str.strip().str.upper()
    return vals.str.startswith(SYNTHETIC_CELL_LINE_PREFIX).to_numpy()


# ---------------------------------------------------------------------------
# LOMO splitter — same as train_metal_lomo.py but with optional synthetic
# Rh oversample support (the synthetic cohort is appended *after* the
# train/val/test split so it never leaks into the test fold).
# ---------------------------------------------------------------------------
@dataclass
class WassersteinLOMOSplitter:
    held_out_metal: str
    val_fraction: float = 0.10
    seed: int = 42
    # Wf-125 A2: stratify the train-pool -> val split on the binary activity
    # label so val inherits the train pool's positive rate.  With
    # ``stratify=None`` the val fold drew positives at random, so a 0.305
    # train_pool rate could land a ~0.06 val rate and vice-versa; the
    # best-val model selection then tracked noise (val/test AUC gap
    # +0.222 mean, +0.46 on Rh).  The held-out *test* fold is unchanged:
    # it is by-construction the other metal, so there is nothing to stratify.
    stratify_labels: bool = True
    # E2 fix (round-5).  The legacy split above draws ``val`` from
    # ``train_pool`` -- i.e. the OTHER metals only -- while ``test`` is the
    # held-out metal.  On Rh that made val_auc=0.785 an in-distribution
    # Ru/Ir/Re/Os number and test_auc=0.386 the true LOMO transfer number, so
    # the two measured *different distributions* and best-val early stopping
    # was selecting on the wrong signal.  With this flag on (and only for
    # Rh) the held-out metal's REAL rows are halved: one half becomes val,
    # the other half test, so val and test are both drawn from the target
    # domain and val_auc is an honest early-stopping proxy for test_auc.
    rh_loso_validation: bool = False

    def _label_array(self, dataset: MetalCytotoxDataset) -> Optional[np.ndarray]:
        """Binary activity label per row, or None if unavailable."""
        df = dataset.df
        for col in ("active", "Active", "is_active"):
            if col in df.columns:
                lab = df[col].to_numpy()
                if col == "active":
                    return lab.astype(np.int64)
                return lab.astype(bool).astype(np.int64)
        return None

    def _synthetic_mask(self, dataset: MetalCytotoxDataset) -> np.ndarray:
        """True for rows injected by a synthetic oversample cohort.

        Wf-A3 keyed off the exact string ``Cell_line == "SYNTHETIC_RH"``.
        Wf-C1 generalises that to the ``SYNTHETIC*`` prefix via
        :func:`synthetic_row_mask`, so a future ``SYNTHETIC_Os`` / ``SYNTHETIC_Pt``
        cohort is routed identically instead of re-introducing the leak.
        """
        return synthetic_row_mask(dataset.df)

    def __call__(self, dataset: MetalCytotoxDataset) -> SplitResult:
        from sklearn.model_selection import train_test_split

        metals = dataset.df["Metal"].astype(str).to_numpy()
        # Wf-A3 fix: synthetic rows carry ``Metal == held_out_metal`` (that is
        # the point of the oversample), so a plain ``metals == held_out`` test
        # mask swept all 500 of them into the Rh TEST fold -- 82 % of a
        # 608-row test set, every one labelled inactive, none of them ever
        # trained on.  Exclude them from test; they belong in train.
        synth = self._synthetic_mask(dataset)
        test_mask = (metals == self.held_out_metal) & ~synth
        test_idx = np.where(test_mask)[0].astype(np.int64)
        # Synthetic rows join the train pool whatever the held-out metal is:
        # for a non-held-out metal they were already in the pool, and for the
        # held-out metal this is where they are meant to be learned from.
        train_pool = np.where(~test_mask)[0].astype(np.int64)

        # ---- E2 fix: val drawn from the held-out metal's REAL rows ----------
        # Scoped to Rh only (the "fix only Rh" contract): for any other
        # held-out metal this flag is a no-op and the legacy path below runs.
        if self.rh_loso_validation and self.held_out_metal == "Rh":
            labels = self._label_array(dataset) if self.stratify_labels else None
            # sklearn needs >=2 members of every class for a stratified split;
            # fall back to the unstratified draw rather than raising.
            stratify = None
            if labels is not None:
                target_lab = labels[test_idx]
                _, counts = np.unique(target_lab, return_counts=True)
                if counts.size >= 2 and int(counts.min()) >= 2:
                    stratify = target_lab
            if len(test_idx) >= 2:
                # D1 fix (Round 7): row-level halve leaks the ligand-level
                # structure: MEASURED 51 unique ligands across 108 Rh real
                # rows → ~50% of test rows share an exact ligand with val.
                # val_AUC then selects on memorised ligands that are also in
                # test, which inverts the ranking on the Rh fold. Split on
                # canonical stripped ligand groups instead of rows.
                try:
                    from sklearn.model_selection import GroupShuffleSplit
                    smiles_col = (
                        "SMILES_Ligands"
                        if "SMILES_Ligands" in dataset.df.columns
                        else "smiles"
                    )
                    groups = (
                        dataset.df[smiles_col]
                        .astype(str)
                        .map(_strip_metal_atoms)
                        .astype(str)
                        .to_numpy()[test_idx]
                    )
                    gss = GroupShuffleSplit(
                        n_splits=1, test_size=0.5, random_state=self.seed
                    )
                    val_sub, test_sub = next(gss.split(test_idx, groups=groups))
                    val_idx = np.sort(test_idx[val_sub].astype(np.int64))
                    test_idx = np.sort(test_idx[test_sub].astype(np.int64))
                except Exception:
                    # Fallback only when the group-split path is not viable
                    # (no smiles col, sklearn import missing, etc.).
                    val_idx, test_idx = train_test_split(
                        test_idx,
                        test_size=0.5,
                        random_state=self.seed,
                        stratify=stratify,
                    )
                    val_idx = np.sort(val_idx.astype(np.int64))
                    test_idx = np.sort(test_idx.astype(np.int64))
                # Every row of the target metal's real block is now accounted
                # for by val or test; train keeps the whole non-Rh pool
                # (including any synthetic Rh rows, which are the oversample).
                return SplitResult(
                    train_idx=train_pool, val_idx=val_idx, test_idx=test_idx
                )
            # Degenerate: too few target rows to halve. Fall through to the
            # legacy path rather than emitting an empty val fold.

        # Val must stay representative of the *real* distribution, so draw it
        # from the non-synthetic part of the pool only.
        val_source = train_pool[~synth[train_pool]]
        if self.val_fraction > 0 and len(val_source) >= 10:
            labels = self._label_array(dataset) if self.stratify_labels else None
            # sklearn needs >=2 members of every class for a stratified split;
            # fall back to the unstratified draw rather than raising.
            stratify = None
            if labels is not None:
                pool_lab = labels[val_source]
                _, counts = np.unique(pool_lab, return_counts=True)
                if counts.size >= 2 and int(counts.min()) >= 2:
                    stratify = pool_lab
            real_train_idx, val_idx = train_test_split(
                val_source,
                test_size=self.val_fraction,
                random_state=self.seed,
                stratify=stratify,
            )
            # train = (real pool rows not drawn into val) + the synthetic rows.
            train_idx = np.sort(
                np.concatenate([real_train_idx, train_pool[synth[train_pool]]])
            )
        else:
            train_idx = train_pool
            val_idx = np.array([], dtype=np.int64)
        return SplitResult(train_idx=train_idx, val_idx=val_idx, test_idx=test_idx)


