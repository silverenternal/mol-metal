def collapse_ligand_duplicates(
    df: "pd.DataFrame",
    smiles_col: str = "SMILES_Ligands",
    metal_col: str = "Metal",
    label_col: str = "active",
) -> Tuple["pd.DataFrame", Dict[str, Any]]:
    """One row per unique ligand *within each metal*; label = majority.

    Mirrors ``metal_activity_transfer_probe.py::collapse_duplicates`` exactly
    (majority label, ties -> ACTIVE via sum*2>=n) so a D-MPNN number and the probe's
    XGB number are measured on the same cohort. Grouping is per (metal, ligand)
    rather than per ligand because the probe dedups each metal's cohort
    independently before running leave-one-metal-out; the cross-metal
    de-duplication that would otherwise apply is done by the leakage rule
    (``WassersteinLOMOSplitter.drop_leaked_ligands``).

    Raw MetalCytoToxDB rows are 64 % duplicates (one ligand measured up to 15
    times), so on the un-deduplicated cohort a fingerprint can straddle the
    LOMO split on identity alone and inflate cross-metal transfer. Measured on
    ``metal_lomo.csv`` 2026-10-10: Ru 3668 -> 1255, Ir 1242 -> 534,
    Rh 108 -> 51, Os 87 -> 36, Re 166 -> 74 (total 5271 -> 1950).

    The kept row is the group's first row in file order with its ``active``
    column rewritten to the majority label; every other column (pIC50, cell
    line, DOI ...) is left as-is because the splitter only reads the label and
    the metal.
    """

    if smiles_col not in df.columns:
        raise KeyError(
            f"dedup needs column {smiles_col!r}; have {list(df.columns)[:8]}..."
        )

    keys = [metal_col, smiles_col] if metal_col in df.columns else [smiles_col]
    # First row of every (metal, ligand) group. ``duplicated`` is used rather
    # than a groupby-index ``isin`` because this frame's columns are Arrow
    # string arrays, whose scalar equality does not survive a MultiIndex round
    # trip (measured 2026-10-10: isin kept 5271/5271 rows instead of 1950).
    keep_mask = ~df.duplicated(subset=keys, keep="first")

    # Majority label per group: sum*2 >= n, so an exact tie (sum*2 == n) also
    # satisfies the predicate and resolves to ACTIVE. This is the
    # ANTI-conservative direction for an activity claim, and it matches
    # metal_activity_transfer_probe.py exactly -- which is the point of the
    # switch. Do not "fix" it to `>` without re-measuring: the conservative
    # rule moves Ru within-metal 0.8363 -> 0.7929 and drops it below the
    # Krasnov 0.81 reference, so the tie rule is load-bearing for that claim.
    # See metrics/by_metric/metal_activity_transfer_tie_sensitivity.json.
    lab = df[label_col].astype(bool)
    grouper = [df[k] for k in keys]
    pos_sum = lab.groupby(grouper).transform("sum")
    n_grp = lab.groupby(grouper).transform("size")
    majority = (pos_sum * 2 >= n_grp).to_numpy()

    out = df.loc[keep_mask].reset_index(drop=True).copy()
    out[label_col] = majority[keep_mask.to_numpy()].astype(int)

    has_metal = metal_col in df.columns
    per_metal_before = (
        df[metal_col].astype(str).value_counts().to_dict() if has_metal else {}
    )
    per_metal_after = (
        out[metal_col].astype(str).value_counts().to_dict() if has_metal else {}
    )
    stats = {
        "n_rows_before": int(len(df)),
        "n_rows_after": int(len(out)),
        "duplication_rate": float(1.0 - len(out) / max(1, len(df))),
        "pos_rate_before": float(np.asarray(df[label_col]).astype(bool).mean()) if label_col in df.columns else None,
        "pos_rate_after": float(np.asarray(out[label_col]).astype(bool).mean()) if label_col in df.columns else None,
        "per_metal_before": {str(k): int(v) for k, v in per_metal_before.items()},
        "per_metal_after": {str(k): int(v) for k, v in per_metal_after.items()},
        "rule": "one row per unique ligand within a metal; label = majority; ties -> ACTIVE (sum*2>=n, anti-conservative; see metal_activity_transfer_tie_sensitivity.json)",
    }
    return out, stats


# LOMO splitter — same as train_metal_lomo.py but with optional synthetic
# Rh oversample support (the synthetic cohort is appended *after* the
# train/val/test split so it never leaks into the test fold).
# ---------------------------------------------------------------------------
@dataclass
class WassersteinLOMOSplitter:
    held_out_metal: str
    val_fraction: float = 0.10
    seed: int = 42
    # Wf-125 A2: stratify the train-pool -> val split on the binary activity
    # label so val inherits the train pool's positive rate.  With
    # ``stratify=None`` the val fold drew positives at random, so a 0.305
    # train_pool rate could land a ~0.06 val rate and vice-versa; the
    # best-val model selection then tracked noise (val/test AUC gap
    # +0.222 mean, +0.46 on Rh).  The held-out *test* fold is unchanged:
    # it is by-construction the other metal, so there is nothing to stratify.
    stratify_labels: bool = True
    # E2 fix (round-5).  The legacy split above draws ``val`` from
    # ``train_pool`` -- i.e. the OTHER metals only -- while ``test`` is the
    # held-out metal.  On Rh that made val_auc=0.785 an in-distribution
    # Ru/Ir/Re/Os number and test_auc=0.386 the true LOMO transfer number, so
    # the two measured *different distributions* and best-val early stopping
    # was selecting on the wrong signal.  With this flag on (and only for
    # Rh) the held-out metal's REAL rows are halved: one half becomes val,
    # the other half test, so val and test are both drawn from the target
    # domain and val_auc is an honest early-stopping proxy for test_auc.
    rh_loso_validation: bool = False
    # 2026-10-10 (Wf-DMPNN-MATCH) — match ``metal_activity_transfer_probe``'s
    # leakage_rule: "a ligand appearing in ANY other metal is dropped from the
    # LOMO train pool". Off by default so every historical run keeps its exact
    # meaning; the matched rerun turns it on together with ``--dedup-ligands``
    # so the D-MPNN and the XGB probe see the same cohort.
    drop_leaked_ligands: bool = False
    n_leaked_dropped: int = 0
    # UP-35: k rows of the held-out metal are moved from test into train.
    # This models a plate that has already been run on the new metal: the
    # first k compounds are measured, the rest are what the model is asked
    # about.  0 keeps every historical run byte-identical.
    support_k: int = 0

    def _apply_support(
        self,
        train_idx: np.ndarray,
        val_idx: np.ndarray,
        test_idx: np.ndarray,
    ) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        """Move k held-out rows into train, after the leakage rule.

        Drawn after the leak drop on purpose: the k rows are the ones a
        deployment would actually have measured, so they are allowed to carry
        ligands the leak rule removed from the rest of the training pool.  At
        least one test row is always kept, and the draw is seeded by the run
        seed so a (metal, seed, k) triple is reproducible.
        """
        k = int(self.support_k)
        if k <= 0 or len(test_idx) < 2:
            return train_idx, val_idx, test_idx
        k = min(k, len(test_idx) - 1)
        rng = np.random.default_rng(int(self.seed) * 7919 + k)
        pick = rng.choice(len(test_idx), size=k, replace=False)
        moved = np.sort(test_idx[pick])
        keep = np.ones(len(test_idx), dtype=bool)
        keep[pick] = False
        logger.info(
            "support-k: held_out=%s moved %d test rows into train "
            "(train %d -> %d, test %d -> %d)",
            self.held_out_metal, k, len(train_idx),
            len(train_idx) + k, len(test_idx), int(keep.sum()),
        )
        return (
            np.sort(np.concatenate([train_idx, moved])),
            val_idx,
            np.sort(test_idx[keep]),
        )

    def _label_array(self, dataset: MetalCytotoxDataset) -> Optional[np.ndarray]:
        """Binary activity label per row, or None if unavailable."""
        df = dataset.df
        for col in ("active", "Active", "is_active"):
            if col in df.columns:
                lab = df[col].to_numpy()
                if col == "active":
                    return lab.astype(np.int64)
                return lab.astype(bool).astype(np.int64)
        return None

    def _synthetic_mask(self, dataset: MetalCytotoxDataset) -> np.ndarray:
        """True for rows injected by a synthetic oversample cohort.

        Wf-A3 keyed off the exact string ``Cell_line == "SYNTHETIC_RH"``.
        Wf-C1 generalises that to the ``SYNTHETIC*`` prefix via
        :func:`synthetic_row_mask`, so a future ``SYNTHETIC_Os`` / ``SYNTHETIC_Pt``
        cohort is routed identically instead of re-introducing the leak.
        """
        return synthetic_row_mask(dataset.df)

    def __call__(self, dataset: MetalCytotoxDataset) -> SplitResult:
        from sklearn.model_selection import train_test_split

        metals = dataset.df["Metal"].astype(str).to_numpy()
        # Wf-A3 fix: synthetic rows carry ``Metal == held_out_metal`` (that is
        # the point of the oversample), so a plain ``metals == held_out`` test
        # mask swept all 500 of them into the Rh TEST fold -- 82 % of a
        # 608-row test set, every one labelled inactive, none of them ever
        # trained on.  Exclude them from test; they belong in train.
        synth = self._synthetic_mask(dataset)
        test_mask = (metals == self.held_out_metal) & ~synth
        test_idx = np.where(test_mask)[0].astype(np.int64)
        # Synthetic rows join the train pool whatever the held-out metal is:
        # for a non-held-out metal they were already in the pool, and for the
        # held-out metal this is where they are meant to be learned from.
        train_pool = np.where(~test_mask)[0].astype(np.int64)

        # ---- leakage rule (Wf-DMPNN-MATCH) -------------------------------
        # Drop every train-pool row whose ligand also occurs in the held-out
        # metal. Matched against ``metal_activity_transfer_probe.cross_metal``,
        # which builds ``blocked = set(te_s)`` from the held-out metal's
        # deduplicated ligands and skips any training row in that set. Keyed on
        # the raw ``SMILES_Ligands`` string — the same key the probe uses
        # (``MetalCytotoxDataset.smiles``), NOT ``_strip_metal_atoms``, so the
        # two sides block exactly the same ligands. Synthetic oversample rows
        # are exempt: they are generated compounds, never measured ones, so
        # they cannot be the source of a leak.
        self.n_leaked_dropped = 0
        if self.drop_leaked_ligands:
            smiles_col = (
                "SMILES_Ligands"
                if "SMILES_Ligands" in dataset.df.columns
                else "smiles"
            )
            if smiles_col in dataset.df.columns:
                all_smi = dataset.df[smiles_col].astype(str).to_numpy()
                blocked = set(all_smi[test_idx].tolist())
                is_leak = np.array(
                    [s in blocked for s in all_smi[train_pool]], dtype=bool
                )
                is_leak &= ~synth[train_pool]
                self.n_leaked_dropped = int(is_leak.sum())
                train_pool = train_pool[~is_leak]
                logger.info(
                    "leakage rule: held_out=%s dropped %d train rows sharing a "
                    "ligand with the held-out metal (train_pool %d -> %d)",
                    self.held_out_metal,
                    self.n_leaked_dropped,
                    len(train_pool) + self.n_leaked_dropped,
                    len(train_pool),
                )

        # ---- E2 fix: val drawn from the held-out metal's REAL rows ----------
        # Scoped to Rh only (the "fix only Rh" contract): for any other
        # held-out metal this flag is a no-op and the legacy path below runs.
        if self.rh_loso_validation and self.held_out_metal == "Rh":
            labels = self._label_array(dataset) if self.stratify_labels else None
            # sklearn needs >=2 members of every class for a stratified split;
            # fall back to the unstratified draw rather than raising.
            stratify = None
            if labels is not None:
                target_lab = labels[test_idx]
                _, counts = np.unique(target_lab, return_counts=True)
                if counts.size >= 2 and int(counts.min()) >= 2:
                    stratify = target_lab
            if len(test_idx) >= 2:
                # D1 fix (Round 7): row-level halve leaks the ligand-level
                # structure: MEASURED 51 unique ligands across 108 Rh real
                # rows → ~50% of test rows share an exact ligand with val.
                # val_AUC then selects on memorised ligands that are also in
                # test, which inverts the ranking on the Rh fold. Split on
                # canonical stripped ligand groups instead of rows.
                try:
                    from sklearn.model_selection import GroupShuffleSplit
                    smiles_col = (
                        "SMILES_Ligands"
                        if "SMILES_Ligands" in dataset.df.columns
                        else "smiles"
                    )
                    groups = (
                        dataset.df[smiles_col]
                        .astype(str)
                        .map(_strip_metal_atoms)
                        .astype(str)
                        .to_numpy()[test_idx]
                    )
                    gss = GroupShuffleSplit(
                        n_splits=1, test_size=0.5, random_state=self.seed
                    )
                    val_sub, test_sub = next(gss.split(test_idx, groups=groups))
                    val_idx = np.sort(test_idx[val_sub].astype(np.int64))
                    test_idx = np.sort(test_idx[test_sub].astype(np.int64))
                except Exception:
                    # Fallback only when the group-split path is not viable
                    # (no smiles col, sklearn import missing, etc.).
                    val_idx, test_idx = train_test_split(
                        test_idx,
                        test_size=0.5,
                        random_state=self.seed,
                        stratify=stratify,
                    )
                    val_idx = np.sort(val_idx.astype(np.int64))
                    test_idx = np.sort(test_idx.astype(np.int64))
                # Every row of the target metal's real block is now accounted
                # for by val or test; train keeps the whole non-Rh pool
                # (including any synthetic Rh rows, which are the oversample).
                _tr, _va, _te = self._apply_support(train_pool, val_idx, test_idx)
                return SplitResult(train_idx=_tr, val_idx=_va, test_idx=_te)
            # Degenerate: too few target rows to halve. Fall through to the
            # legacy path rather than emitting an empty val fold.

        # Val must stay representative of the *real* distribution, so draw it
        # from the non-synthetic part of the pool only.
        val_source = train_pool[~synth[train_pool]]
        if self.val_fraction > 0 and len(val_source) >= 10:
            labels = self._label_array(dataset) if self.stratify_labels else None
            # sklearn needs >=2 members of every class for a stratified split;
            # fall back to the unstratified draw rather than raising.
            stratify = None
            if labels is not None:
                pool_lab = labels[val_source]
                _, counts = np.unique(pool_lab, return_counts=True)
                if counts.size >= 2 and int(counts.min()) >= 2:
                    stratify = pool_lab
            real_train_idx, val_idx = train_test_split(
                val_source,
                test_size=self.val_fraction,
                random_state=self.seed,
                stratify=stratify,
            )
            # train = (real pool rows not drawn into val) + the synthetic rows.
            train_idx = np.sort(
                np.concatenate([real_train_idx, train_pool[synth[train_pool]]])
            )
        else:
            train_idx = train_pool
            val_idx = np.array([], dtype=np.int64)
        train_idx, val_idx, test_idx = self._apply_support(
            train_idx, val_idx, test_idx)
        return SplitResult(train_idx=train_idx, val_idx=val_idx, test_idx=test_idx)


