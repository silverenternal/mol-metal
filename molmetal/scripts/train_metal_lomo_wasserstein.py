# ---------------------------------------------------------------------------
# LOMO splitter — same as train_metal_lomo.py but with optional synthetic
# Rh oversample support (the synthetic cohort is appended *after* the
# train/val/test split so it never leaks into the test fold).
# ---------------------------------------------------------------------------
@dataclass
class WassersteinLOMOSplitter:
    held_out_metal: str
    val_fraction: float = 0.10
    seed: int = 42

    def __call__(self, dataset: MetalCytotoxDataset) -> SplitResult:
        from sklearn.model_selection import train_test_split

        metals = dataset.df["Metal"].astype(str).to_numpy()
        test_mask = metals == self.held_out_metal
        test_idx = np.where(test_mask)[0].astype(np.int64)
        train_pool = np.where(~test_mask)[0].astype(np.int64)
        if self.val_fraction > 0 and len(train_pool) >= 10:
            train_idx, val_idx = train_test_split(
                train_pool,
                test_size=self.val_fraction,
                random_state=self.seed,
                stratify=None,
            )
        else:
            train_idx = train_pool
            val_idx = np.array([], dtype=np.int64)
        return SplitResult(train_idx=train_idx, val_idx=val_idx, test_idx=test_idx)


# ---------------------------------------------------------------------------
# Synthetic Rh loader — appends the 500-compound cohort as extra Rh rows
# ---------------------------------------------------------------------------
def load_rh_synthetic_smiles(cohort_json: Path) -> List[str]:
    """Return the SMILES of every Catherine 6/6 PASS compound in the cohort.

    The Wf-125 P1 cohort JSON stores one ``per_compound`` entry per kept
    compound, each with a ``smiles`` field.  We filter to the
    Catherine-6/6 PASS compounds (i.e. the entire 500-compound cohort,
    since Wf-125 P1 only kept the PASS compounds).
    """
    cohort_json = Path(cohort_json)
    if not cohort_json.exists():
        raise FileNotFoundError(
            f"Wf-125 P1 Rh synthetic cohort not found at {cohort_json}. "
            "Run scripts/wasserstein_transfer_rh.py first to generate it."
        )
    with cohort_json.open() as fh:
        payload = json.load(fh)
    smis: List[str] = []
    for entry in payload.get("per_compound", []):
        if not entry.get("catherine_6of6_pass", False):
            continue
        s = str(entry.get("smiles", "")).strip()
        if s:
            smis.append(s)
    if not smis:
        raise RuntimeError(
            f"No Catherine-6/6 PASS Rh compounds found in {cohort_json}"
        )
    return smis


def append_synthetic_rh_to_dataset(
    base_ds: MetalCytotoxDataset,
    cohort_json: Path,
    n_target: int = 500,
    active_label: int = 0,
) -> Tuple[MetalCytotoxDataset, int]:
    """Append the synthetic Rh cohort to the train pool (inactive by default).

    Parameters
    ----------
    base_ds
        Existing dataset (5-metal LOMO pool).
    cohort_json
        Path to the Wf-125 P1 synthetic_rh_cohort.json.
    n_target
        Cap on the number of synthetic rows appended (default 500 — full
        cohort).
    active_label
        Default active flag for the synthetic rows.  MetalCytoToxDB Rh is
        ~85 % inactive at the IC50<10 µM gate, so we default to inactive
        (=0).  The exact balance is reported in the synthesis.md.

    Returns
    -------
    Tuple of (augmented_dataset, n_appended).
    """
    import pandas as pd

    smis = load_rh_synthetic_smiles(cohort_json)
    if n_target < len(smis):
        rng = np.random.default_rng(0)
        keep = rng.permutation(len(smis))[:n_target]
        smis = [smis[i] for i in keep]

    # Build a DataFrame matching the base dataset's column schema.
    cols = list(base_ds.df.columns)
    rows = []
    for i, s in enumerate(smis):
        row = {c: None for c in cols}
        row["SMILES_Ligands"] = s
        row["Metal"] = "Rh"
        row["Charge_complex"] = 0
        row["Oxidation_state"] = 3
        row["Atomic_number"] = 45
        row["Valence_e"] = 9
        row["Year"] = 2026  # synthetic
        # IC50 + pIC50: we default to a non-active IC50 (10 µM baseline).
        row["IC50_Dark_value"] = 10.0
        row["IC50_Dark(M*10^-6)"] = 10.0
        row["pIC50"] = 5.0  # = -log10(1e-5 M)
        row["active"] = int(active_label)
        row["Cell_line"] = "SYNTHETIC_RH"
        rows.append(row)
    df_synth = pd.DataFrame(rows, columns=cols)
    df_combined = pd.concat([base_ds.df, df_synth], ignore_index=True)
    return MetalCytotoxDataset(df=df_combined, cache_dir=base_ds.cache_dir), len(smis)


# ---------------------------------------------------------------------------
# Per-metal embedding extraction — runs the D-MPNN backbone once over
# the train pool and returns a {metal: Tensor(n_k, 2H)} dict.
# ---------------------------------------------------------------------------
@torch.no_grad()
def extract_per_metal_embeddings(
    model: DMPNNMultiTaskModel,
    smiles: np.ndarray,
    metals: np.ndarray,
    device: torch.device,
    max_per_metal: int = 200,
    batch_size: int = MT_BATCH_SIZE,
) -> Dict[str, torch.Tensor]:
    """Run the backbone over the train pool and bucket embeddings by metal.

    Parameters
    ----------
    model
        Trained DMPNNMultiTaskModel (we only use the backbone + shared
        trunk, *not* the per-task heads).
    smiles
        SMILES array.
    metals
        Metal label per row.
    max_per_metal
        Cap on the number of embeddings per metal (default 200 — keeps
        the W₂ computation cheap; we sample deterministically).
    """
    model.eval()
    graphs = featurize_smiles_list([str(s) for s in smiles])
    valid_idx = [i for i, g in enumerate(graphs) if g is not None]
    per_metal: Dict[str, List[torch.Tensor]] = {}
    for i in valid_idx:
        m = str(metals[i])
        per_metal.setdefault(m, []).append(i)

    rng = np.random.default_rng(0)
    sampled_idx: List[int] = []
    sampled_metals: List[str] = []
    for m, idx_list in per_metal.items():
        cap = min(max_per_metal, len(idx_list))
        sel = rng.permutation(len(idx_list))[:cap]
        for j in sel:
            sampled_idx.append(idx_list[j])
            sampled_metals.append(m)
    if not sampled_idx:
        return {}

    out_embeds: Dict[str, List[torch.Tensor]] = {}
    for start in range(0, len(sampled_idx), batch_size):
        batch_idx = sampled_idx[start:start + batch_size]
        batch_metas = [sampled_metals[k] for k in range(start, min(start + batch_size, len(sampled_idx)))]
        g_list = [graphs[i] for i in batch_idx]
        bd = collate_graphs(g_list)
        if bd is None:
            continue
        atom_f, bond_f, e_src, e_dst = bd
        atom_f = atom_f.to(device)
        bond_f = bond_f.to(device)
        e_src = e_src.to(device)
        e_dst = e_dst.to(device)
        B_ = atom_f.size(0)
        for b in range(B_):
            V = atom_f.size(1)
            valid_edges = (bond_f[b].abs().sum(dim=-1) > 0)
            E = valid_edges.sum().item()
            if E == 0 or V == 0:
                continue
            pooled = model._forward_one_mol(
                atom_f[b, :V], bond_f[b, :E], e_src[b, :E], e_dst[b, :E]
            )
            out_embeds.setdefault(batch_metas[b], []).append(pooled.detach().cpu())

    return {m: torch.stack(v, dim=0) for m, v in out_embeds.items() if v}


# ---------------------------------------------------------------------------
# Custom training loop — wraps DMPNNMultiTaskBaseline + injects the W₂
# regularisation on per-metal embeddings.
# ---------------------------------------------------------------------------
@dataclass
class WassersteinLOMOResult:
    fold: str
    seed: int
    n_train: int
    n_val: int
    n_test: int
    n_synthetic_rh: int
    pos_rate_train: float
    pos_rate_test: float
    val_auc: float
    test_auc: float
    test_pic50_mae: float
    wasserstein_weight: float
    wasserstein_loss_history: List[float]
    final_per_metal_w2: Dict[str, float]
    elapsed_seconds: float
    use_l2_guard: bool = False
    use_astr_scale_guard: bool = False
    l2_guard_max_norm: float = L2_GUARD_MAX_NORM
    astr_scale_clip_min: float = _ASTR_SCALE_CLIP_MIN
    astr_scale_clip_max: float = _ASTR_SCALE_CLIP_MAX


class WassersteinLOMORunner:
    """Single-fold runner that wires the W₂ regulariser into DMPNN-MT."""

    def __init__(
        self,
        ds: MetalCytotoxDataset,
        held_out_metal: str,
        wasserstein_weight: float = 0.05,
        n_mc: int = 64,
        hidden: int = MT_HIDDEN,
        depth: int = MT_DEPTH,
        dropout: float = MT_DROPOUT,
        lr: float = MT_LR,
        epochs: int = 30,
        batch_size: int = MT_BATCH_SIZE,
        alpha: float = MT_ALPHA,
        seed: int = 42,
        device: Optional[torch.device] = None,
        synthetic_rh_count: int = 0,
        use_l2_guard: bool = False,
        use_astr_scale_guard: bool = False,
        l2_guard_max_norm: float = L2_GUARD_MAX_NORM,
        astr_scale_clip_min: float = _ASTR_SCALE_CLIP_MIN,
        astr_scale_clip_max: float = _ASTR_SCALE_CLIP_MAX,
    ) -> None:
        self.ds = ds
        self.held_out_metal = held_out_metal
        self.wasserstein_weight = float(wasserstein_weight)
        self.n_mc = int(n_mc)
        self.hidden = hidden
        self.depth = depth
        self.dropout = dropout
        self.lr = lr
        self.epochs = epochs
        self.batch_size = batch_size
        self.alpha = float(alpha)
        self.seed = int(seed)
        self.device = device or torch.device(
            "cuda:1" if torch.cuda.is_available() and torch.cuda.device_count() > 1
            else "cuda:0" if torch.cuda.is_available()
            else "cpu"
        )
        self.splitter = WassersteinLOMOSplitter(held_out_metal=held_out_metal, seed=self.seed)
        self.synthetic_rh_count = int(synthetic_rh_count)
        # Wf-127 P2 — grad-norm clip (mirrors D-MPNN multitask trainer).
        self.use_l2_guard = bool(use_l2_guard)
        self.l2_guard_max_norm = float(l2_guard_max_norm)
        # Wf-127 P3 — value-space clip on predicted pIC50 at test time.
        self.use_astr_scale_guard = bool(use_astr_scale_guard)
        self.astr_scale_clip_min = float(astr_scale_clip_min)
        self.astr_scale_clip_max = float(astr_scale_clip_max)
        # We train a fresh DMPNN-MT model directly so we can hook the
        # W₂ penalty into the loss each epoch.
        self.model: Optional[DMPNNMultiTaskModel] = None
        self._wasserstein_loss_history: List[float] = []

    def run(self, verbose: bool = False) -> WassersteinLOMOResult:
        torch.manual_seed(self.seed)
        np.random.seed(self.seed)

        split = self.splitter(self.ds)
        smiles_all = self.ds.smiles
        active_all = self.ds.active.astype(int)
        pic50_all = self.ds.pic50.astype(np.float32)
        metals_all = self.ds.metals

        train_idx, val_idx, test_idx = split.train_idx, split.val_idx, split.test_idx

        graphs_all = featurize_smiles_list([str(s) for s in smiles_all])
        graphs_train = [graphs_all[i] for i in train_idx]
        graphs_val = [graphs_all[i] for i in val_idx] if len(val_idx) else []
        graphs_test = [graphs_all[i] for i in test_idx]
        pic50_train = pic50_all[train_idx]
        pic50_val = pic50_all[val_idx] if len(val_idx) else np.array([], dtype=np.float32)
        active_train = active_all[train_idx]
        active_val = active_all[val_idx] if len(val_idx) else np.array([], dtype=int)
        pic50_test = pic50_all[test_idx]
        active_test = active_all[test_idx]

        model = DMPNNMultiTaskModel(
            hidden=self.hidden,
            depth=self.depth,
            dropout=self.dropout,
        ).to(self.device)
        optimizer = torch.optim.Adam(model.parameters(), lr=self.lr)
        from molmetal.baselines.dmpnn_multitask import MultiTaskLoss
        criterion = MultiTaskLoss(alpha=self.alpha)

        best_val_auc = 0.0
        best_state: Optional[Dict[str, torch.Tensor]] = None
        w2_history: List[float] = []

        for epoch in range(self.epochs):
            t0 = time.time()
            # ---- Pre-compute W₂ penalty once per epoch (when triggered) ----
            # Doing this per-batch was a mistake — extract_per_metal_embeddings
            # runs the model over ~80×4=320 molecules, which when called at
            # every batch dominated the wall-time. We now compute the W₂
            # penalty exactly once per epoch when (epoch % 5 == 0 or last).
            w2_loss_t: Optional[torch.Tensor] = None
            if self.wasserstein_weight > 0 and (
                epoch % 5 == 0 or epoch == self.epochs - 1
            ):
                train_smiles = smiles_all[train_idx]
                train_metals = metals_all[train_idx]
                embeds = extract_per_metal_embeddings(
                    model, train_smiles, train_metals, self.device, max_per_metal=80
                )
                if len(embeds) >= 2:
                    w2_loss_t = self.wasserstein_weight * wasserstein_transfer_loss(
                        embeds, n_mc=self.n_mc, seed=self.seed
                    )

            # ---- train one epoch with W₂ penalty injected once per epoch --
            model.train()
            indices = np.arange(len(graphs_train))
            np.random.shuffle(indices)
            total_loss = 0.0
            total_cls = 0.0
            total_reg = 0.0
            n_batches = 0
            for start in range(0, len(indices), self.batch_size):
                batch_idx = indices[start:start + self.batch_size]
                batch_graphs = [graphs_train[i] for i in batch_idx]
                batch_pic50 = pic50_train[batch_idx]
                batch_active = active_train[batch_idx]
                valid = [
                    (g, p, a) for g, p, a in zip(batch_graphs, batch_pic50, batch_active)
                    if g is not None and not (isinstance(p, float) and np.isnan(p))
                ]
                if not valid:
                    continue
                g_list = [v[0] for v in valid]
                y_pic50 = np.array([v[1] for v in valid], dtype=np.float32)
                y_active = np.array([v[2] for v in valid], dtype=np.int64)
                bd = collate_graphs(g_list)
                if bd is None:
                    continue
                atom_f, bond_f, e_src, e_dst = bd
                atom_f = atom_f.to(self.device)
                bond_f = bond_f.to(self.device)
                e_src = e_src.to(self.device)
                e_dst = e_dst.to(self.device)
                y_pic50_t = torch.from_numpy(y_pic50).to(self.device)
                y_active_t = torch.from_numpy(y_active).to(self.device)

                optimizer.zero_grad()
                pic50_pred, active_logits = model(atom_f, bond_f, e_src, e_dst)
                loss, lc, lr_ = criterion(pic50_pred, active_logits, y_pic50_t, y_active_t)
                if w2_loss_t is not None:
                    # Add the epoch-level W₂ penalty (computed once per
                    # epoch above) to every batch — equivalent to a
                    # constant regulariser since w2_loss_t doesn't depend
                    # on the batch.
                    loss = loss + w2_loss_t
                loss.backward()
                # Wf-127 P2 — grad-norm clip (max_norm=5.0 by default).
                # Engaged by ``--use-l2-guard``; backward-compat default is
                # no-op (off).
                if self.use_l2_guard:
                    torch.nn.utils.clip_grad_norm_(
                        model.parameters(), self.l2_guard_max_norm
                    )
                optimizer.step()

                bs = len(y_active)
                total_loss += loss.item() * bs
                total_cls += lc.item() * bs
                total_reg += lr_.item() * bs
                n_batches += bs

            avg_loss = total_loss / max(n_batches, 1)

            # ---- validation ----
            if len(graphs_val) >= 2:
                _, val_score, val_pic50_pred = predict_mt(
                    model, graphs_val, pic50_val, active_val,
                    batch_size=self.batch_size, device=self.device,
                )
                vm = compute_metrics(active_val, val_score)
                val_auc = float(vm["roc_auc"])
            else:
                val_auc = float("nan")

            # ---- record W₂ every epoch end (cheap; uses cached sample) ----
            # Use the embeddings extracted at epoch start (when W₂ was
            # injected) to record the W₂ history — this avoids the
            # double cost of extracting again at epoch end.
            if self.wasserstein_weight > 0 and (epoch % 5 == 0 or epoch == self.epochs - 1):
                # Cheap re-extraction on a smaller subset keeps the
                # cost bounded while still capturing the decay trend.
                train_embeds = extract_per_metal_embeddings(
                    model, smiles_all[train_idx], metals_all[train_idx],
                    self.device, max_per_metal=80,
                )
                if len(train_embeds) >= 2:
                    with torch.no_grad():
                        w2_val = wasserstein_transfer_loss(
                            train_embeds, n_mc=self.n_mc, seed=self.seed
                        ).item()
                else:
                    w2_val = 0.0
            else:
                w2_val = w2_history[-1] if w2_history else 0.0
            w2_history.append(w2_val)

            if verbose and (epoch % 1 == 0 or epoch == self.epochs - 1):
                logger.info(
                    "fold=%s seed=%d epoch=%d loss=%.4f val_auc=%.4f w2=%.4f "
                    "elapsed=%.1fs",
                    self.held_out_metal, self.seed, epoch, avg_loss, val_auc, w2_val,
                    time.time() - t0,
                )

            if not np.isnan(val_auc) and val_auc > best_val_auc:
                best_val_auc = val_auc
                best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}

        if best_state is not None:
            model.load_state_dict(best_state)

        # ---- final test eval ----
        _, test_score, test_pic50_pred = predict_mt(
            model, graphs_test, pic50_test, active_test,
            batch_size=self.batch_size, device=self.device,
        )
        # Wf-127 P3 — value-space clip on the predicted pIC50 distribution.
        # The classification score (``test_score``) is a sigmoid over the
        # logits *before* the regression head clamp, so the AUC is *not*
        # affected; only the pIC50 MAE is recomputed against the clipped
        # predictions.  Engaged by ``--use-astr-scale-guard``; backward-compat
        # default is no-op (off).
        if self.use_astr_scale_guard:
            test_pic50_pred = clip_astr_signature(
                np.asarray(test_pic50_pred, dtype=float),
                self.astr_scale_clip_min,
                self.astr_scale_clip_max,
            )[0]
        tm = compute_metrics(active_test, test_score)
        test_auc = float(tm["roc_auc"])
        test_mae = float(np.mean(np.abs(test_pic50_pred - pic50_test)))

        # ---- final per-metal W₂ snapshot ----
        train_embeds = extract_per_metal_embeddings(
            model, smiles_all[train_idx], metals_all[train_idx],
            self.device, max_per_metal=80,
        )
        per_metal_w2: Dict[str, float] = {}
        if len(train_embeds) >= 2:
            metals_present = sorted(train_embeds.keys())
            for i, m_a in enumerate(metals_present):
                for m_b in metals_present[i + 1:]:
                    with torch.no_grad():
                        w2 = (
                            wasserstein_transfer_loss(
                                {m_a: train_embeds[m_a], m_b: train_embeds[m_b]},
                                n_mc=self.n_mc, seed=self.seed,
                            ).item()
                        )
                    per_metal_w2[f"{m_a}-{m_b}"] = float(w2)

        return WassersteinLOMOResult(
            fold=self.held_out_metal,
            seed=self.seed,
            n_train=int(len(train_idx)),
            n_val=int(len(val_idx)),
            n_test=int(len(test_idx)),
            n_synthetic_rh=self.synthetic_rh_count,
            pos_rate_train=float(active_train.mean()) if len(active_train) else 0.0,
            pos_rate_test=float(active_test.mean()) if len(active_test) else 0.0,
            val_auc=float(best_val_auc),
            test_auc=test_auc,
            test_pic50_mae=test_mae,
            wasserstein_weight=self.wasserstein_weight,
            wasserstein_loss_history=w2_history,
            final_per_metal_w2=per_metal_w2,
            elapsed_seconds=0.0,  # populated by caller
            use_l2_guard=self.use_l2_guard,
            use_astr_scale_guard=self.use_astr_scale_guard,
            l2_guard_max_norm=self.l2_guard_max_norm,
            astr_scale_clip_min=self.astr_scale_clip_min,
            astr_scale_clip_max=self.astr_scale_clip_max,
        )


