# Synthetic Rh loader — appends the 500-compound cohort as extra Rh rows
# ---------------------------------------------------------------------------
def load_rh_synthetic_smiles(cohort_json: Path) -> List[str]:
    """Return the SMILES of every Catherine 6/6 PASS compound in the cohort.

    The Wf-125 P1 cohort JSON stores one ``per_compound`` entry per kept
    compound, each with a ``smiles`` field.  We filter to the
    Catherine-6/6 PASS compounds (i.e. the entire 500-compound cohort,
    since Wf-125 P1 only kept the PASS compounds).
    """
    cohort_json = Path(cohort_json)
    if not cohort_json.exists():
        raise FileNotFoundError(
            f"Wf-125 P1 Rh synthetic cohort not found at {cohort_json}. "
            "Run scripts/wasserstein_transfer_rh.py first to generate it."
        )
    with cohort_json.open() as fh:
        payload = json.load(fh)
    smis: List[str] = []
    for entry in payload.get("per_compound", []):
        if not (
            entry.get("catherine_6of6_pass", False) or entry.get("is_active", False)
        ):
            continue
        s = str(entry.get("smiles", "")).strip()
        if s:
            smis.append(s)
    if not smis:
        raise RuntimeError(f"No Catherine-6/6 PASS Rh compounds found in {cohort_json}")
    return smis


def append_synthetic_rh_to_dataset(
    base_ds: MetalCytotoxDataset,
    cohort_json: Path,
    n_target: int = 500,
    active_label: int = 0,
    active_cohort_json: Optional[Path] = None,
) -> Tuple[MetalCytotoxDataset, int]:
    """Append the synthetic Rh cohort to the train pool (inactive by default).

    Parameters
    ----------
    base_ds
        Existing dataset (5-metal LOMO pool).
    cohort_json
        Path to the Wf-125 P1 synthetic_rh_cohort.json.
    n_target
        Cap on the number of synthetic rows appended (default 500 — full
        cohort).
    active_label
        Default active flag for the synthetic rows.  MetalCytoToxDB Rh is
        ~85 % inactive at the IC50<10 µM gate, so we default to inactive
        (=0).  The exact balance is reported in the synthesis.md.
    active_cohort_json
        Wf-A3: optional path to the positive-labelled synthetic Rh cohort.
        When given, ``n_target`` is split 50/50 between the inactive cohort
        (labelled ``active_label``) and this one (labelled 1), so the fold no
        longer trains on a single-class "all Rh is inactive" block.  When
        ``None`` the original single-cohort behaviour is preserved.

    Returns
    -------
    Tuple of (augmented_dataset, n_appended).
    """
    import pandas as pd

    smis = load_rh_synthetic_smiles(cohort_json)
    n_inactive_target = n_target
    if active_cohort_json is not None:
        smis = smis[: n_target // 2]
        n_inactive_target = len(smis)
    if n_inactive_target < len(smis):
        rng = np.random.default_rng(0)
        keep = rng.permutation(len(smis))[:n_inactive_target]
        smis = [smis[i] for i in keep]

    labelled: List[Tuple[str, int]] = [(s, active_label) for s in smis]
    if active_cohort_json is not None:
        act_path = Path(active_cohort_json)
        if not act_path.exists():
            raise FileNotFoundError(
                f"Wf-A3 active Rh cohort not found at {act_path}. Run "
                "scripts/rh_active_cohort_generation.py first."
            )
        act_smis = load_rh_synthetic_smiles(act_path)
        n_active_target = n_target - len(labelled)
        if n_active_target < len(act_smis):
            rng = np.random.default_rng(1)
            keep = rng.permutation(len(act_smis))[:n_active_target]
            act_smis = [act_smis[i] for i in keep]
        labelled += [(s, 1) for s in act_smis]

    # Build a DataFrame matching the base dataset's column schema.
    cols = list(base_ds.df.columns)
    rows = []
    for i, (s, lab) in enumerate(labelled):
        row = {c: None for c in cols}
        row["SMILES_Ligands"] = s
        row["Metal"] = "Rh"
        row["Charge_complex"] = 0
        row["Oxidation_state"] = 3
        row["Atomic_number"] = 45
        row["Valence_e"] = 9
        row["Year"] = 2026  # synthetic
        # IC50 + pIC50: neither is measured, so we set the two label
        # archetypes consistently -- active rows get a potent value, inactive
        # rows the 10 µM baseline.  The regression head trains on pIC50 too,
        # so leaving every synthetic row at 5.0 while flipping the
        # classification label would train the two heads against each other.
        if int(lab) == 1:
            row["IC50_Dark_value"] = 0.1
            row["IC50_Dark(M*10^-6)"] = 0.1
            row["pIC50"] = 7.0  # = -log10(1e-7 M)
        else:
            row["IC50_Dark_value"] = 10.0
            row["IC50_Dark(M*10^-6)"] = 10.0
            row["pIC50"] = 5.0  # = -log10(1e-5 M)
        row["active"] = int(lab)
        row["Cell_line"] = synthetic_cell_line_tag("Rh")
        rows.append(row)
    df_synth = pd.DataFrame(rows, columns=cols)
    df_combined = pd.concat([base_ds.df, df_synth], ignore_index=True)
    return MetalCytotoxDataset(df=df_combined, cache_dir=base_ds.cache_dir), len(labelled)


# ---------------------------------------------------------------------------
# Per-metal embedding extraction — runs the D-MPNN backbone once over
# the train pool and returns a {metal: Tensor(n_k, 2H)} dict.
# ---------------------------------------------------------------------------
def extract_per_metal_embeddings(
    model: DMPNNMultiTaskModel,
    smiles: np.ndarray,
    metals: np.ndarray,
    device: torch.device,
    max_per_metal: int = 200,
    batch_size: int = MT_BATCH_SIZE,
    real_grad: bool = False,
) -> Dict[str, torch.Tensor]:
    """Run the backbone over the train pool and bucket embeddings by metal.

    Parameters
    ----------
    model
        Trained DMPNNMultiTaskModel (we only use the backbone + shared
        trunk, *not* the per-task heads).
    smiles
        SMILES array.
    metals
        Metal label per row.
    max_per_metal
        Cap on the number of embeddings per metal (default 200 — keeps
        the W₂ computation cheap; we sample deterministically).
    real_grad
        Wf-E1 (2026-10-05). ``False`` (default, and the only behaviour
        that existed before this flag) returns **detached** CPU tensors,
        so any W₂ built on them is a constant — the Wf-C3 no-op.
        ``True`` keeps the autograd graph and the device placement, so
        the W₂ term actually backpropagates into the backbone. Engaged
        only via ``--wasserstein-real``; see the Wf-E1 note at the
        injection site for the per-epoch staleness caveat.
    """
    grad_ctx = torch.enable_grad() if real_grad else torch.no_grad()
    grad_ctx.__enter__()
    try:
        return _extract_per_metal_embeddings_inner(
            model, smiles, metals, device, max_per_metal, batch_size, real_grad
        )
    finally:
        grad_ctx.__exit__(None, None, None)


def _extract_per_metal_embeddings_inner(
    model: DMPNNMultiTaskModel,
    smiles: np.ndarray,
    metals: np.ndarray,
    device: torch.device,
    max_per_metal: int,
    batch_size: int,
    real_grad: bool,
) -> Dict[str, torch.Tensor]:
    model.eval()
    graphs = featurize_smiles_list([str(s) for s in smiles])
    valid_idx = [i for i, g in enumerate(graphs) if g is not None]
    per_metal: Dict[str, List[torch.Tensor]] = {}
    for i in valid_idx:
        m = str(metals[i])
        per_metal.setdefault(m, []).append(i)

    rng = np.random.default_rng(0)
    sampled_idx: List[int] = []
    sampled_metals: List[str] = []
    for m, idx_list in per_metal.items():
        cap = min(max_per_metal, len(idx_list))
        sel = rng.permutation(len(idx_list))[:cap]
        for j in sel:
            sampled_idx.append(idx_list[j])
            sampled_metals.append(m)
    if not sampled_idx:
        return {}

    out_embeds: Dict[str, List[torch.Tensor]] = {}
    for start in range(0, len(sampled_idx), batch_size):
        batch_idx = sampled_idx[start : start + batch_size]
        batch_metas = [
            sampled_metals[k]
            for k in range(start, min(start + batch_size, len(sampled_idx)))
        ]
        g_list = [graphs[i] for i in batch_idx]
        bd = collate_graphs(g_list)
        if bd is None:
            continue
        atom_f, bond_f, e_src, e_dst = bd
        atom_f = atom_f.to(device)
        bond_f = bond_f.to(device)
        e_src = e_src.to(device)
        e_dst = e_dst.to(device)
        B_ = atom_f.size(0)
        for b in range(B_):
            V = atom_f.size(1)
            valid_edges = bond_f[b].abs().sum(dim=-1) > 0
            E = valid_edges.sum().item()
            if E == 0 or V == 0:
                continue
            pooled = model._forward_one_mol(
                atom_f[b, :V], bond_f[b, :E], e_src[b, :E], e_dst[b, :E]
            )
            # Wf-E1: ``.detach()`` here is what made the W₂ term a no-op
            # (Wf-C3). It is now conditional on ``real_grad``; the default
            # path is byte-identical to the pre-Wf-E1 behaviour.
            out_embeds.setdefault(batch_metas[b], []).append(
                pooled if real_grad else pooled.detach().cpu()
            )

    return {m: torch.stack(v, dim=0) for m, v in out_embeds.items() if v}


