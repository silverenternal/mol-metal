def _build_dataset(args: argparse.Namespace, rh_over: int) -> Tuple[MetalCytotoxDataset, int]:
    csv_path = Path(args.csv)
    if not csv_path.exists():
        raise FileNotFoundError(f"5-metal LOMO CSV not found at {csv_path}")

    # Cache-dir handling: the default ``/mnt/storage/data/molmetal/3d_cache``
    # is not writable on this host; fall back to a project-local cache.
    cache_dir = PROJECT_ROOT / "molmetal" / ".cache" / "3d_cache"
    cache_dir.mkdir(parents=True, exist_ok=True)

    flt = CytotoxFilter(
        time_threshold=24.0,
        ic50_min=0.01,
        metal_whitelist=None,
        compute_pic50=True,
        compute_active=True,
    )

    # Build the dataset directly via the constructor (avoiding
    # ``from_csv`` which always uses the default ``DEFAULT_CACHE_DIR``)
    # so we can point ``cache_dir`` at a writable project-local path.
    import pandas as pd
    from molmetal.data.cytotox import _add_active, _add_pic50, _apply_filters

    df = pd.read_csv(csv_path, low_memory=False)
    df = _apply_filters(df, flt)
    df = _add_pic50(df)
    df = _add_active(df)
    ds = MetalCytotoxDataset(df=df, cache_dir=cache_dir)

    if args.quick and len(ds) > 1000:
        rng = np.random.default_rng(0)
        keep = rng.permutation(len(ds))[:1000]
        df_small = ds.df.iloc[keep].reset_index(drop=True).copy()
        ds = MetalCytotoxDataset(df=df_small, cache_dir=cache_dir)
    n_appended = 0
    if rh_over > 0:
        ds, n_appended = append_synthetic_rh_to_dataset(
            ds, Path(args.rh_cohort_json), n_target=rh_over
        )
    logger.info(
        "dataset loaded: n=%d  metals=%s  n_synthetic_rh_appended=%d",
        len(ds),
        dict(zip(*np.unique(ds.metals, return_counts=True))),
        n_appended,
    )
    return ds, n_appended


def _run_one(
    args: argparse.Namespace,
    ds: MetalCytotoxDataset,
    metal: str,
    seed: int,
    n_synthetic_rh: int,
) -> Dict[str, object]:
    device = None
    if args.device:
        device = torch.device(args.device)
    logger.info(
        "=== fold held_out=%s seed=%d  epochs=%d  wass_w=%.4f  synth_rh=%d  device=%s ===",
        metal, seed, args.epochs, args.wasserstein_weight, n_synthetic_rh,
        str(device) if device else "auto",
    )
    runner = WassersteinLOMORunner(
        ds=ds,
        held_out_metal=metal,
        wasserstein_weight=args.wasserstein_weight,
        n_mc=args.n_mc,
        hidden=args.hidden,
        depth=args.depth,
        dropout=MT_DROPOUT,
        lr=args.lr,
        epochs=args.epochs,
        batch_size=args.batch_size,
        alpha=args.alpha,
        seed=seed,
        device=device,
        synthetic_rh_count=n_synthetic_rh,
        use_l2_guard=bool(getattr(args, "use_l2_guard", False)),
        use_astr_scale_guard=bool(getattr(args, "use_astr_scale_guard", False)),
        l2_guard_max_norm=float(getattr(args, "l2_guard_max_norm", L2_GUARD_MAX_NORM)),
        astr_scale_clip_min=float(getattr(args, "astr_scale_clip_min", _ASTR_SCALE_CLIP_MIN)),
        astr_scale_clip_max=float(getattr(args, "astr_scale_clip_max", _ASTR_SCALE_CLIP_MAX)),
    )
    t0 = time.time()
    res = runner.run(verbose=True)
    elapsed = time.time() - t0
    return {
        "fold": metal,
        "seed": seed,
        "n_train": res.n_train,
        "n_val": res.n_val,
        "n_test": res.n_test,
        "n_synthetic_rh": res.n_synthetic_rh,
        "pos_rate_train": res.pos_rate_train,
        "pos_rate_test": res.pos_rate_test,
        "val_auc": res.val_auc,
        "test_auc": res.test_auc,
        "test_pic50_mae": res.test_pic50_mae,
        "wasserstein_weight": res.wasserstein_weight,
        "wasserstein_loss_history": res.wasserstein_loss_history,
        "final_per_metal_w2": res.final_per_metal_w2,
        "elapsed_seconds": float(elapsed),
        "use_l2_guard": bool(res.use_l2_guard),
        "use_astr_scale_guard": bool(res.use_astr_scale_guard),
        "l2_guard_max_norm": float(res.l2_guard_max_norm),
        "astr_scale_clip_min": float(res.astr_scale_clip_min),
        "astr_scale_clip_max": float(res.astr_scale_clip_max),
    }


def _aggregate(per_run: List[Dict[str, object]]) -> Dict[str, object]:
    aucs = [float(d["test_auc"]) for d in per_run if "test_auc" in d]
    per_fold: Dict[str, List[float]] = {}
    for d in per_run:
        if "test_auc" not in d:
            continue
        per_fold.setdefault(d["fold"], []).append(float(d["test_auc"]))
    return {
        "n_runs": len(aucs),
        "n_folds": len(per_fold),
        "test_auc_mean": float(statistics.mean(aucs)) if aucs else float("nan"),
        "test_auc_std": float(statistics.pstdev(aucs)) if len(aucs) > 1 else 0.0,
        "per_fold_auc_mean": {
            m: float(statistics.mean(v)) if v else float("nan")
            for m, v in per_fold.items()
        },
        "per_fold_auc_std": {
            m: float(statistics.pstdev(v)) if len(v) > 1 else 0.0
            for m, v in per_fold.items()
        },
        "per_run_auc": aucs,
    }


