def resolve_crossdocked_path(
    raw_path: str,
    crossdocked_root: Optional[str] = None,
) -> Tuple[Path, str]:
    """Resolve a manifest ``receptor_path`` / ``ligand_path`` to a real file.

    The manifest stores machine-local absolute paths (they were generated
    on the box where CrossDocked2020 was extracted).  When the original
    mount point is absent, repoint the path at another root by trying
    progressively *shorter* trailing path segments, longest first::

        /mnt/.../crossdocked_pocket10/BSD_ASPTE_1_130_0/x.sdf
          k=3 -> <root>/crossdocked_pocket10/BSD_ASPTE_1_130_0/x.sdf
          k=2 -> <root>/BSD_ASPTE_1_130_0/x.sdf            <-- hit

    Filenames are never rewritten; only the root prefix is swapped.
    Returns ``(resolved_path, source_tag)`` where ``source_tag`` is
    ``"manifest"`` (path was already valid), ``"flag"``, ``"env"``,
    ``"default:<root>"`` or ``"unresolved"``.  On failure the ORIGINAL
    path is returned so callers see a real ``.exists()`` failure rather
    than a fabricated one.
    """
    original = Path(raw_path)
    if original.exists():
        return original, "manifest"

    roots: List[Tuple[str, Path]] = []
    if crossdocked_root:
        roots.append(("flag", Path(crossdocked_root)))
    env_root = os.environ.get(CROSSDOCKED_ROOT_ENV)
    if env_root:
        roots.append(("env", Path(env_root)))
    roots.extend((f"default:{r}", Path(r)) for r in DEFAULT_CROSSDOCKED_ROOTS)

    parts = original.parts[1:] if original.is_absolute() else original.parts
    for tag, root in roots:
        if not root.is_dir():
            continue
        for k in range(len(parts), 0, -1):
            candidate = root.joinpath(*parts[-k:])
            if candidate.exists():
                return candidate, tag
    return original, "unresolved"


# ---------------------------------------------------------------------------
# Cohen's d (lit-grounded)
# ---------------------------------------------------------------------------
def cohens_d(
    treatment: Sequence[float],
    baseline: Sequence[float],
) -> Optional[float]:
    """Compute Cohen's d between two samples (treatment vs baseline).

    Cohen 1988, *Statistical Power Analysis for the Behavioral
    Sciences*, 2nd ed., Lawrence Erlbaum Associates, p. 67.  Eq. 2.3.5
    (pooled-variance form, equal n correction omitted):

        d = (mu_t - mu_b) / s_pooled
        s_pooled = sqrt(((n_t - 1) * s_t^2 + (n_b - 1) * s_b^2)
                        / (n_t + n_b - 2))

    Returns ``None`` when either sample is degenerate (n < 2 or
    pooled variance = 0).  The degeneracy guard is honest framing —
    a d value computed on a single cell or on a zero-variance
    metric is undefined.
    """
    if len(treatment) < 2 or len(baseline) < 2:
        return None
    mu_t = statistics.fmean(treatment)
    mu_b = statistics.fmean(baseline)
    var_t = statistics.variance(treatment)
    var_b = statistics.variance(baseline)
    df = len(treatment) + len(baseline) - 2
    if df <= 0:
        return None
    pooled_sq = ((len(treatment) - 1) * var_t + (len(baseline) - 1) * var_b) / df
    if pooled_sq <= 0:
        return None
    s_pooled = math.sqrt(pooled_sq)
    if s_pooled == 0:
        return None
    return (mu_t - mu_b) / s_pooled


# ---------------------------------------------------------------------------
# Single (pocket, seed, rule) cell.
# ---------------------------------------------------------------------------
def _run_one_rule_cell(
    *,
    r4_lambda_only_run: Any,
    pocket_id: str,
    reference_smiles: Optional[str],
    seed: int,
    n_simulations: int,
    n_top_k: int,
    rule: str,
    metal_seed: Optional[str] = None,
) -> Any:
    """Run a single cell with ``click_rules=[rule]`` (the rule in
    isolation) using :func:`r4_lambda_only_run.run_one_cell`.

    Important: we force ``auto_pt_strict_default=False`` semantics by
    passing the rule explicitly — the per-rule effect we want is the
    *chemistry* of the rule, NOT the scaffold-narrowed subset.  If
    the user did NOT pass a ``--metal-seed``, the seed collapses to
    the pocket reference ligand and the auto-pt-strict gate is moot
    for non-Pt seeds.

    When ``--metal-seed`` IS passed, it is forwarded to
    ``run_one_cell(metal_seed=...)``, which overrides
    ``reference_smiles`` as the MCTS *root* term (r4_lambda_only_run
    lines 2835-2853).  Consequence worth stating: the pocket reference
    ligand then no longer seeds the search, so the run measures
    "rule R starting from [Pt]C#C", not "rule R starting from the
    docked CrossDocked ligand".  The two are different experiments and
    the payload records which one ran (``metal_seed`` in ``config``).
    """
    cell = r4_lambda_only_run.run_one_cell(
        pocket_id=pocket_id,
        reference_smiles=reference_smiles,
        seed=seed,
        n_simulations=n_simulations,
        n_top_k=n_top_k,
        click_rules=[rule],
        metal_seed=metal_seed,
    )
    return cell


# ---------------------------------------------------------------------------
# Study driver
# ---------------------------------------------------------------------------
def run_study(
    *,
    manifest_path: Path,
    n_pockets: int,
    seeds: Sequence[int],
    n_simulations: int,
    n_top_k: int,
    output_dir: Path,
    metal_seed: Optional[str] = None,
    crossdocked_root: Optional[str] = None,
) -> Dict[str, Any]:
    """Run the 5x3 grid (rules x (pockets x seeds)) and return the
    full study payload.  Also writes study.json + study.csv under
    ``output_dir``.
    """
    # Lazy imports so --help works.
    from molmetal.scripts import r4_lambda_only_run

    output_dir.mkdir(parents=True, exist_ok=True)
    rows = r4_lambda_only_run.load_manifest(manifest_path)
    if not rows:
        raise RuntimeError(f"No manifest rows found at {manifest_path}")
    rows = rows[:n_pockets]

    started = time.time()
    # cells[rule] = list of (pocket, seed, CellResult)
    cells_by_rule: Dict[str, List[Dict[str, Any]]] = {r: [] for r in STUDY_RULES}
    # Cohort-resolvability bookkeeping (honest framing: a run with
    # reference_smiles=None on every pocket measures nothing about the
    # pocket chemistry).
    n_reference_smiles: List[int] = []
    resolve_sources: Dict[str, int] = {}
    # Also store elapsed_s per cell.
    for row in rows:
        pid = row.get("pocket_id", "?")
        ligand_path, resolve_tag = resolve_crossdocked_path(
            row.get("ligand_path", "") or "", crossdocked_root
        )
        resolve_sources[resolve_tag] = resolve_sources.get(resolve_tag, 0) + 1
        reference_smiles = r4_lambda_only_run.load_reference_smiles(ligand_path)
        n_reference_smiles.append(0 if reference_smiles is None else 1)
        log.info(
            "pocket=%s ligand=%s resolved_via=%s reference_smiles=%s",
            pid,
            ligand_path,
            resolve_tag,
            "yes" if reference_smiles else "NONE",
        )
        for seed in seeds:
            for rule in STUDY_RULES:
                log.info(
                    "running rule=%s pocket=%s seed=%d n_simulations=%d",
                    rule,
                    pid,
                    seed,
                    n_simulations,
                )
                cell = _run_one_rule_cell(
                    r4_lambda_only_run=r4_lambda_only_run,
                    pocket_id=pid,
                    reference_smiles=reference_smiles,
                    seed=seed,
                    n_simulations=n_simulations,
                    n_top_k=n_top_k,
                    rule=rule,
                    metal_seed=metal_seed,
                )
                cells_by_rule[rule].append(
                    {
                        "pocket_id": pid,
                        "seed": seed,
                        "rule": rule,
                        "metric_values": {
                            m: float(getattr(cell, m, 0.0) or 0.0)
                            for m in STUDY_METRICS
                        },
                        "n_candidates": int(getattr(cell, "n_candidates", 0) or 0),
                        "n_distinct": int(getattr(cell, "n_distinct", 0) or 0),
                        "elapsed_s": float(getattr(cell, "elapsed_s", 0.0) or 0.0),
                    }
                )
    elapsed_total = time.time() - started

    # ----- aggregate panel (5 rules x 4 metrics) -----
    panel: Dict[str, Dict[str, float]] = {}
    panel_std: Dict[str, Dict[str, float]] = {}
    panel_n: Dict[str, Dict[str, int]] = {}
    per_rule_samples: Dict[str, Dict[str, List[float]]] = {}
    for rule in STUDY_RULES:
        panel[rule] = {}
        panel_std[rule] = {}
        panel_n[rule] = {}
        per_rule_samples[rule] = {}
        for metric in STUDY_METRICS:
            vals = [c["metric_values"][metric] for c in cells_by_rule[rule]]
            panel[rule][metric] = statistics.fmean(vals) if vals else 0.0
            panel_std[rule][metric] = statistics.pstdev(vals) if len(vals) > 1 else 0.0
            panel_n[rule][metric] = len(vals)
            per_rule_samples[rule][metric] = vals

    # ----- Cohen's d (rule vs OTHER rules) -----
    effect_sizes: Dict[str, Dict[str, Optional[float]]] = {}
    for rule in STUDY_RULES:
        effect_sizes[rule] = {}
        for metric in STUDY_METRICS:
            # Baseline = all OTHER rules' samples for this metric.
            baseline_samples: List[float] = []
            for other_rule in STUDY_RULES:
                if other_rule == rule:
                    continue
                baseline_samples.extend(per_rule_samples[other_rule][metric])
            effect_sizes[rule][metric] = cohens_d(
                per_rule_samples[rule][metric],
                baseline_samples,
            )

    payload = {
        "rules": list(STUDY_RULES),
        "metrics": list(STUDY_METRICS),
        "rule_citations": RULE_CITATIONS,
        "config": {
            "n_pockets": n_pockets,
            "seeds": list(seeds),
            "n_simulations": n_simulations,
            "n_top_k": n_top_k,
            "metal_seed": metal_seed,
            "manifest_path": str(manifest_path),
            "crossdocked_root": crossdocked_root,
            "path_resolve_sources": resolve_sources,
            "n_pockets_with_reference_smiles": sum(n_reference_smiles),
        },
        "panel_mean": panel,
        "panel_std": panel_std,
        "panel_n": panel_n,
        "effect_sizes": effect_sizes,
        "per_rule_citations": RULE_CITATIONS,
        "cells": cells_by_rule,
        "elapsed_total_s": elapsed_total,
        "n_cells_total": sum(len(cells_by_rule[r]) for r in STUDY_RULES),
    }

    # ---- write JSON (atomic, AGENTS.md §5.6) ----
    json_path = output_dir / "study.json"
    atomic_write_file(json_path, json.dumps(payload, indent=2) + "\n")
    log.info("Wrote %s", json_path)

    # ---- write CSV (flat rows) ----
    csv_path = output_dir / "study.csv"
    buf: List[str] = []
    w = csv.writer(_ListWriter(buf))
    w.writerow(["rule", "metric", "mean", "std", "n", "cohens_d_vs_others"])
    for rule in STUDY_RULES:
        for metric in STUDY_METRICS:
            w.writerow(
                [
                    rule,
                    metric,
                    f"{panel[rule][metric]:.4f}",
                    f"{panel_std[rule][metric]:.4f}",
                    panel_n[rule][metric],
                    (
                        f"{effect_sizes[rule][metric]:.3f}"
                        if effect_sizes[rule][metric] is not None
                        else "NA"
                    ),
                ]
            )
    atomic_write_file(csv_path, "".join(buf))
    log.info("Wrote %s", csv_path)

    # ---- write summary.md ----
    summary_path = output_dir / "summary.md"
    _write_summary(summary_path, payload)
    log.info("Wrote %s", summary_path)

    return payload


class _ListWriter:
    """Minimal file-like sink so ``csv.writer`` can render to a string
    (the atomic writer takes text, not a file object)."""

    def __init__(self, sink: List[str]) -> None:
        self._sink = sink

    def write(self, text: str) -> int:
        self._sink.append(text)
        return len(text)


def _write_summary(path: Path, payload: Dict[str, Any]) -> None:
    """Render the panel + Cohen's-d as a human-readable Markdown."""
    lines: List[str] = []
    lines.append("# Click-Rule Effect-Size Study — Summary")
    lines.append("")
    lines.append("**Protocol:** enable each click rule in isolation via ")
    lines.append("`--click-rules <rule>`, fix `n_simulations` per cell, ")
    lines.append("compute the mean of 4 metrics across the (pockets x seeds) grid. ")
    lines.append("Cohen's d is the standard between-rule pooled-variance form ")
    lines.append("(Cohen 1988, eq. 2.3.5).")
    lines.append("")
    lines.append("## Config")
    cfg = payload["config"]
    lines.append(
        f"- pockets={cfg['n_pockets']}, seeds={cfg['seeds']}, "
        f"n_simulations={cfg['n_simulations']}, n_top_k={cfg['n_top_k']}, "
        f"metal_seed={cfg['metal_seed']!r}"
    )
    lines.append(
        f"- crossdocked_root={cfg.get('crossdocked_root')!r}; "
        f"path_resolve_sources={cfg.get('path_resolve_sources')}; "
        f"pockets with a real reference_smiles = "
        f"{cfg.get('n_pockets_with_reference_smiles')} / {cfg['n_pockets']}"
    )
    lines.append("")
    lines.append("## Panel (mean across cells)")
    lines.append("")
    header = "| rule | " + " | ".join(payload["metrics"]) + " | citation |"
    sep = "| --- | " + " | ".join(["---"] * len(payload["metrics"])) + " | --- |"
    lines.append(header)
    lines.append(sep)
    for rule in payload["rules"]:
        row = [rule]
        for m in payload["metrics"]:
            row.append(f"{payload['panel_mean'][rule][m]:.4f}")
        row.append(payload["rule_citations"][rule])
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")
    lines.append("## Cohen's d (rule vs OTHER rules)")
    lines.append("")
    lines.append(
        "Positive d = rule increases the metric relative to the other rules' average. "
    )
    lines.append(
        "Magnitude convention (Cohen 1988): |d| < 0.2 negligible, < 0.5 small, < 0.8 medium, >= 0.8 large."
    )
    lines.append("")
    lines.append("| rule | " + " | ".join(payload["metrics"]) + " |")
    lines.append("| --- | " + " | ".join(["---"] * len(payload["metrics"])) + " |")
    for rule in payload["rules"]:
        row = [rule]
        for m in payload["metrics"]:
            d = payload["effect_sizes"][rule][m]
            row.append(f"{d:.3f}" if d is not None else "NA")
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")
    lines.append("## Lit anchors")
    lines.append("")
    for rule, cite in payload["rule_citations"].items():
        lines.append(f"- **{rule}** — {cite}")
    lines.append("")
    lines.append("## Honest framing")
    lines.append("")
    lines.append(
        "- Cohen's d is computed *between rules*, not between "
        "rule vs. a hand-picked baseline.  The baseline is "
        "the population of the OTHER four rules' samples."
    )
    lines.append(
        "- With 1 cell per rule (default `--pockets 1 --seeds 42`), "
        "d is computed against an n=4 baseline (other rules) vs. n=1 "
        "treatment (this rule).  The variance term collapses to a "
        "single sample so d is reported as `NA`.  Use `--pockets 5 "
        "--seeds 42 0 1234` for n=15 cells per rule and a meaningful d."
    )
    lines.append(
        "- Effect-size magnitudes are NOT a comment on which rule "
        "is 'best' — they only say which rules shift the metric "
        "panel *more* than the average of the others."
    )
    if cfg.get("metal_seed"):
        lines.append(
            f"- `metal_seed={cfg['metal_seed']!r}` OVERRIDES the pocket "
            "reference ligand as the MCTS root term inside "
            "`r4_lambda_only_run.run_one_cell` (lines ~2835-2853). "
            "This run therefore measures 'rule R from a bare-metal "
            "seed', NOT 'rule R from the docked CrossDocked ligand'."
        )
    lines.append(
        "- The 4 metrics are Lambda-MCTS downstream outcomes. None of "
        "them is a per-reaction chemical yield; a run of this module "
        "cannot answer a yield question."
    )
    lines.append("")
    atomic_write_file(path, "\n".join(lines) + "\n")


