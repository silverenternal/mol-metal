# MetalCytoToxDB has more than 5 metals; map the 5 canonical metals to
# {0..4} and every other metal to -1 so the training loop can mask
# them out. Match the order used by ``V4MultiTaskDMPNN.SUPPORTED_METALS``.
CANONICAL_METALS: Tuple[str, ...] = ("Ru", "Ir", "Rh", "Re", "Os")
_METAL_TO_IDX: Dict[str, int] = {m: i for i, m in enumerate(CANONICAL_METALS)}

# Domain codes (also written into the .pt files for downstream filtering).
#
# CANONICAL mapping — MUST stay in sync with
# ``molmetal/data/four_domain_combined.py`` (DOMAIN_METALCYTOTOX /
# DOMAIN_DRUGOOD / DOMAIN_NCI60 / DOMAIN_BINDINGDB) and the
# ``--domain-id`` help text in ``train_dmpnn_multitask.py``.
#
#   0 = MetalCytoToxDB
#   1 = DrugOOD
#   2 = NCI-60
#   3 = BindingDB
#
# AUDIT (Wf-124 P0 #2, 2026-09-27): the previous version of this dict used
# ``0=metal_cytotox, 1=nci60, 2=binding_db, 3=drugood`` which was a stub
# scratch mapping and contradicted both the data-layer constants and the
# ``train_dmpnn_multitask.py`` docstring. It was corrected to the canonical
# order above. Any pre-featurized .pt files produced BEFORE this commit
# were written with the WRONG mapping and must be re-generated by
# re-running this script — see MIGRATION_NOTES below.
#
# MIGRATION_NOTES
# ---------------
# Existing files in ``molmetal/data/pre_featurized/*.pt`` (and the
# aggregate ``all_pretrain.pt``) were generated on 2026-09-26 with the
# stale mapping:
#
#   file                  | old domain id | canonical domain id
#   --------------------- | ------------- | -------------------
#   metal_cytotox.pt      |       0       |       0  (no change)
#   nci60.pt              |       1       |       2
#   binding_db.pt         |       2       |       3
#   drugood.pt            |       3       |       1
#   all_pretrain.pt       | (mixed)       | (mixed)
#
# To re-featurize with the canonical mapping, run::
#
#     rm -rf molmetal/data/pre_featurized/*.pt
#     /home/hugo/codes/mol-metal/.venv/bin/python \
#         molmetal/scripts/pre_featurize_dmpnn.py
#
# Downstream training (``train_dmpnn_multitask.py --data-config
# four-domain``) reads the ``domain`` tensor directly and assumes the
# canonical mapping. Until the .pt files are regenerated, four-domain
# training will mix labels across domains.
DOMAIN_ID = {
    "metal_cytotox": 0,   # MetalCytoToxDB
    "drugood":       1,   # DrugOOD
    "nci60":         2,   # NCI-60
    "binding_db":    3,   # BindingDB
}


# ---------------------------------------------------------------------------
# Featurize one SMILES → dict of numpy arrays
# ---------------------------------------------------------------------------
def _featurize_one(
    smiles: str,
    featurizer: GraphFeaturizer,
) -> Dict[str, np.ndarray]:
    """Featurize a single SMILES. Returns dummy tensors on parse failure
    so the rest of the corpus is not perturbed by a single bad row.
    """
    af_dim = featurizer.atom_feature_dim
    ed_dim = featurizer.edge_feature_dim
    try:
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            raise ValueError(f"RDKit parse failed for {smiles!r}")
        feat = featurizer(mol)
        return {
            "x": feat["x"],
            "edge_index": feat["edge_index"],
            "edge_attr": feat["edge_attr"],
            "n_atoms": int(feat["n_atoms"]),
        }
    except Exception:
        return {
            "x": np.zeros((1, af_dim), dtype=np.float32),
            "edge_index": np.zeros((2, 0), dtype=np.int64),
            "edge_attr": np.zeros((0, ed_dim), dtype=np.float32),
            "n_atoms": 1,
        }


# ---------------------------------------------------------------------------
# Featurize a list of SMILES → padded tensors + masks
# ---------------------------------------------------------------------------
def featurize_corpus(
    smiles_list: List[str],
    featurizer: GraphFeaturizer,
    N_max_global: int | None = None,
    E_max_global: int | None = None,
) -> Tuple[
    np.ndarray, np.ndarray, np.ndarray, np.ndarray
]:
    """Return padded arrays:

        atom_features (N, N_max, atom_feat_dim) float32
        edge_index    (N, 2, E_max) int64
        edge_attr     (N, E_max, edge_feat_dim) float32
        atom_mask     (N, N_max) bool

    If ``N_max_global`` / ``E_max_global`` are provided, those are used
    as the padding width (so multiple corpora can be concatenated later
    with matching shapes).
    """
    af_dim = featurizer.atom_feature_dim
    ed_dim = featurizer.edge_feature_dim
    N = len(smiles_list)

    # First pass: per-row raw features
    atom_feats = [None] * N
    edge_indices = [None] * N
    edge_attrs = [None] * N
    n_atoms_list = [0] * N
    for i, smi in enumerate(smiles_list):
        feat = _featurize_one(smi, featurizer)
        atom_feats[i] = feat["x"]
        edge_indices[i] = feat["edge_index"]
        edge_attrs[i] = feat["edge_attr"]
        n_atoms_list[i] = feat["n_atoms"]

    N_max = max(max(n_atoms_list), 1) if N_max_global is None else N_max_global
    E_max = (
        max(max(ei.shape[1] for ei in edge_indices), 1)
        if E_max_global is None
        else E_max_global
    )

    atom_features = np.zeros((N, N_max, af_dim), dtype=np.float32)
    edge_index = np.zeros((N, 2, E_max), dtype=np.int64)
    edge_attr = np.zeros((N, E_max, ed_dim), dtype=np.float32)
    atom_mask = np.zeros((N, N_max), dtype=bool)

    for b in range(N):
        af = atom_feats[b]
        n_a = min(af.shape[0], N_max)
        atom_features[b, :n_a] = af[:n_a]
        atom_mask[b, :n_a] = True
        ei = edge_indices[b]
        n_e = min(ei.shape[1], E_max)
        edge_index[b, :, :n_e] = ei[:, :n_e]
        ea = edge_attrs[b]
        n_ea = min(ea.shape[0], E_max)
        edge_attr[b, :n_ea] = ea[:n_ea]

    return atom_features, edge_index, edge_attr, atom_mask


# ---------------------------------------------------------------------------
# Pack a domain into the final tensor dict (still on CPU as numpy)
# ---------------------------------------------------------------------------
def pack_domain(
    df: pd.DataFrame,
    smiles_col: str,
    y_col: str,
    active_col: str | None,
    metal_col: str | None,
    featurizer: GraphFeaturizer,
    domain_name: str,
    N_max_global: int | None = None,
    E_max_global: int | None = None,
    log_every: int = 5000,
) -> Dict[str, object]:
    """Featurize one domain and return the dict that will be saved."""
    smiles_list = df[smiles_col].astype(str).tolist()
    n = len(smiles_list)
    t0 = time.time()
    atom_features, edge_index, edge_attr, atom_mask = featurize_corpus(
        smiles_list,
        featurizer,
        N_max_global=N_max_global,
        E_max_global=E_max_global,
    )
    dt = time.time() - t0
    print(
        f"  [{domain_name}] featurized {n} rows in {dt:.1f}s "
        f"({n / max(dt, 1e-6):.1f} SMILES/sec)  "
        f"shapes: atom={atom_features.shape}, edge={edge_index.shape}",
        flush=True,
    )

    y = df[y_col].astype(np.float32).to_numpy() if y_col in df.columns else np.full(n, np.nan, dtype=np.float32)
    if active_col is not None and active_col in df.columns:
        active = df[active_col].astype(np.float32).to_numpy()
    else:
        active = np.full(n, np.nan, dtype=np.float32)
    if metal_col is not None and metal_col in df.columns:
        metal_idx = np.array(
            [_METAL_TO_IDX.get(str(m), -1) for m in df[metal_col].tolist()],
            dtype=np.int64,
        )
    else:
        metal_idx = np.full(n, -1, dtype=np.int64)
    domain_id = np.full(n, DOMAIN_ID[domain_name], dtype=np.int64)
    return {
        "atom_features": torch.from_numpy(atom_features),
        "edge_index": torch.from_numpy(edge_index),
        "edge_attr": torch.from_numpy(edge_attr),
        "atom_mask": torch.from_numpy(atom_mask),
        "metal_idx": torch.from_numpy(metal_idx),
        "y": torch.from_numpy(y),
        "active": torch.from_numpy(active),
        "domain": torch.from_numpy(domain_id),
        "smiles": smiles_list,
    }


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main() -> int:
    out_dir = Path("molmetal/data/pre_featurized")
    out_dir.mkdir(parents=True, exist_ok=True)
    featurizer = GraphFeaturizer()
    print(f"atom_feat_dim={featurizer.atom_feature_dim}, "
          f"edge_feat_dim={featurizer.edge_feature_dim}", flush=True)

    # ----- Load raw frames ------------------------------------------------
    print("Loading raw dataframes ...", flush=True)
    df_mc = load_metal_cytotox()
    df_nci = load_nci60()
    df_bd = load_binding_db()
    df_do = pd.read_csv("molmetal/data/drugood/train.csv")
    # DrugOOD uses 'y' (binary).  Cast to float32 so it lines up with .y.
    df_do = df_do.rename(columns={"y": "active"})
    # Also expose a dummy y column to keep the tensor schema uniform
    df_do["pIC50"] = np.nan
    print(
        f"  metal_cytotox={len(df_mc)}  nci60={len(df_nci)}  "
        f"binding_db={len(df_bd)}  drugood={len(df_do)}",
        flush=True,
    )

    # ----- One quick scan to determine global N_max / E_max --------------
    # We pre-parse every SMILES once (the cheapest cost) just to learn the
    # biggest molecule / graph; then pad all domains to that same width
    # so the aggregate tensor concatenates cleanly.
    print("Scanning SMILES to determine global N_max / E_max ...", flush=True)
    t0 = time.time()
    all_smis = (
        df_mc["smiles"].astype(str).tolist()
        + df_nci["smiles"].astype(str).tolist()
        + df_bd["smiles"].astype(str).tolist()
        + df_do["smiles"].astype(str).tolist()
    )
    n_atoms_scan: List[int] = []
    n_edges_scan: List[int] = []
    scan_chunk = 20000
    for i in range(0, len(all_smis), scan_chunk):
        chunk = all_smis[i : i + scan_chunk]
        for smi in chunk:
            try:
                m = Chem.MolFromSmiles(smi)
                if m is None:
                    n_atoms_scan.append(1)
                    n_edges_scan.append(0)
                else:
                    n_atoms_scan.append(int(m.GetNumAtoms()))
                    n_edges_scan.append(int(m.GetNumBonds()) * 2)  # bidirectional
            except Exception:
                n_atoms_scan.append(1)
                n_edges_scan.append(0)
        if (i // scan_chunk) % 5 == 0:
            print(
                f"  scan: {i + len(chunk)}/{len(all_smis)} "
                f"({time.time() - t0:.1f}s)",
                flush=True,
            )
    N_max_global = max(max(n_atoms_scan), 1)
    E_max_global = max(max(n_edges_scan), 1)
    print(
        f"  scan done in {time.time() - t0:.1f}s — "
        f"N_max_global={N_max_global}, E_max_global={E_max_global}",
        flush=True,
    )

    # ----- Featurize each domain -----------------------------------------
    print("Featurizing metal_cytotox ...", flush=True)
    t0 = time.time()
    pack_mc = pack_domain(
        df_mc,
        smiles_col="smiles",
        y_col="pIC50",
        active_col="active",
        metal_col="metal",
        featurizer=featurizer,
        domain_name="metal_cytotox",
        N_max_global=N_max_global,
        E_max_global=E_max_global,
    )
    t_mc = time.time() - t0

    print("Featurizing nci60 ...", flush=True)
    t0 = time.time()
    pack_nci = pack_domain(
        df_nci,
        smiles_col="smiles",
        y_col="pIC50",
        active_col="active",
        metal_col=None,            # NCI-60 has no metal id
        featurizer=featurizer,
        domain_name="nci60",
        N_max_global=N_max_global,
        E_max_global=E_max_global,
    )
    t_nci = time.time() - t0

    print("Featurizing binding_db ...", flush=True)
    t0 = time.time()
    pack_bd = pack_domain(
        df_bd,
        smiles_col="smiles",
        y_col="pIC50",
        active_col="active",
        metal_col="metal",
        featurizer=featurizer,
        domain_name="binding_db",
        N_max_global=N_max_global,
        E_max_global=E_max_global,
    )
    t_bd = time.time() - t0

    print("Featurizing drugood ...", flush=True)
    t0 = time.time()
    pack_do = pack_domain(
        df_do,
        smiles_col="smiles",
        y_col="pIC50",             # all-NaN (DrugOOD is classification only)
        active_col="active",       # binary label
        metal_col=None,
        featurizer=featurizer,
        domain_name="drugood",
        N_max_global=N_max_global,
        E_max_global=E_max_global,
    )
    t_do = time.time() - t0

    # ----- Save per-domain files -----------------------------------------
    print("Saving per-domain .pt files ...", flush=True)
    for name, pack in [
        ("metal_cytotox", pack_mc),
        ("nci60", pack_nci),
        ("binding_db", pack_bd),
        ("drugood", pack_do),
    ]:
        path = out_dir / f"{name}.pt"
        torch.save(pack, path)
        print(f"  wrote {path} ({pack['atom_features'].shape})", flush=True)

    # ----- Save aggregate file -------------------------------------------
    print("Concatenating aggregate ...", flush=True)
    keys_tensors = [
        "atom_features", "edge_index", "edge_attr", "atom_mask",
        "metal_idx", "y", "active", "domain",
    ]
    agg: Dict[str, object] = {}
    for k in keys_tensors:
        agg[k] = torch.cat([pack[k] for pack in (pack_mc, pack_nci, pack_bd, pack_do)], dim=0)
    # Concatenate smiles lists
    agg["smiles"] = (
        pack_mc["smiles"] + pack_nci["smiles"] + pack_bd["smiles"] + pack_do["smiles"]
    )
    agg_path = out_dir / "all_pretrain.pt"
    torch.save(agg, agg_path)
    print(f"  wrote {agg_path} ({agg['atom_features'].shape})", flush=True)

    # ----- Summary -------------------------------------------------------
    total = agg["atom_features"].shape[0]
    total_wall = t_mc + t_nci + t_bd + t_do
    print("Done.", flush=True)
    print(f"  metal_cytotox: {pack_mc['atom_features'].shape[0]}  ({t_mc:.1f}s, {pack_mc['atom_features'].shape[0] / max(t_mc, 1e-6):.0f}/s)", flush=True)
    print(f"  nci60:         {pack_nci['atom_features'].shape[0]}  ({t_nci:.1f}s, {pack_nci['atom_features'].shape[0] / max(t_nci, 1e-6):.0f}/s)", flush=True)
    print(f"  binding_db:    {pack_bd['atom_features'].shape[0]}  ({t_bd:.1f}s, {pack_bd['atom_features'].shape[0] / max(t_bd, 1e-6):.0f}/s)", flush=True)
    print(f"  drugood:       {pack_do['atom_features'].shape[0]}  ({t_do:.1f}s, {pack_do['atom_features'].shape[0] / max(t_do, 1e-6):.0f}/s)", flush=True)
    print(f"  total:         {total} rows  ({total_wall:.1f}s, {total / max(total_wall, 1e-6):.0f}/s)", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
