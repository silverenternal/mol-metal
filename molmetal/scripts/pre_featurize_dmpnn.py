"""Pre-featurize all D-MPNN training data ONCE.

Motivation: the per-step ``_featurize_batch`` call in
``V4MultiTaskDMPNN.encoder.forward`` is the bottleneck during training
(~186ms/step on CPU). If we featurize every SMILES in the corpus once
and dump the padded (B, N_max, atom_feat_dim) / (B, 2, E_max) /
(B, E_max, edge_feat_dim) tensors to disk, the training loop can read
the tensors straight from disk (or RAM after the first epoch) and
never call RDKit again.

Outputs
-------
For each domain, a single ``.pt`` file with:

    {
        "atom_features": Tensor (N, N_max, 39)            float32
        "edge_index":     Tensor (N, 2, E_max)             int64
        "edge_attr":      Tensor (N, E_max, 6)             float32
        "atom_mask":      Tensor (N, N_max) bool           True for real atoms
        "metal_idx":      Tensor (N,) int64 (long)         metal-id slot for
                                                           MetalCytoToxDB rows
                                                           (-1 for other
                                                           domains)
        "y":              Tensor (N,) float32              pIC50 target
                                                           (NaN if absent)
        "active":         Tensor (N,) float32              binary label
                                                           (NaN if absent)
        "domain":         Tensor (N,) int64                domain id
                                                           (CANONICAL mapping:
                                                            0=MetalCytoToxDB,
                                                            1=DrugOOD,
                                                            2=NCI-60,
                                                            3=BindingDB)
        "smiles":         list[str]                        canonical SMILES
    }

Plus an aggregate ``molmetal/data/pre_featurized/all_pretrain.pt``
that concatenates every row (336,556 rows total).

Usage
-----
    .venv/bin/python molmetal/scripts/pre_featurize_dmpnn.py
"""

