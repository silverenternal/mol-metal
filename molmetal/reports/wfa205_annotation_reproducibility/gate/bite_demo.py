"""Wf-A205 -- bite the citability gate and print the EXACT failure output.

Runs six scenarios against SHADOW copies of ``registry/metrics.yaml`` written
under a temp directory.  The repo's own registry is never written; the only
read of it is the read the gate itself does.

For each scenario the script:
  1. copies the registry into a temp dir,
  2. applies one mutation,
  3. writes a temp pytest file that imports the SHIPPED gate module and
     asserts the gate is green on that copy,
  4. runs pytest on it and captures the real failure output.

Scenario 6 is the CONTROL: the unmutated copy must PASS.

CPU-only.  No GPU.  Writes only under the temp dir.

Usage:
    CUDA_VISIBLE_DEVICES="" .venv/bin/python \
        molmetal/reports/wfa205_annotation_reproducibility/gate/bite_demo.py
"""
from __future__ import annotations

import copy
import importlib.util
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
from typing import Any, Callable, Dict, List, Tuple

REPO = pathlib.Path(__file__).resolve().parents[4]
GATE_MODULE_PATH = REPO / "molmetal" / "tests" / "test_wfa205_citability_gate.py"
REGISTRY = REPO / "registry" / "metrics.yaml"

if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))


def _load_gate_module():
    spec = importlib.util.spec_from_file_location("wfa205_gate", GATE_MODULE_PATH)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


GATE = _load_gate_module()

#: metric_id used for the "the row loses its caveat" scenarios.
TARGET = "m21_nci60_9cell"

#: a caveat-less artifact-role row, promoted to the paper surface.
PROMOTE_TARGET = "nci60_precious_9cell_auc"


def _blank(metrics: Dict[str, Any]) -> None:
    metrics[TARGET][GATE.KEY_CAVEAT] = ""


def _whitespace(metrics: Dict[str, Any]) -> None:
    metrics[TARGET][GATE.KEY_CAVEAT] = "   \n\t  \r\n "


def _removed(metrics: Dict[str, Any]) -> None:
    metrics[TARGET].pop(GATE.KEY_CAVEAT, None)


def _promoted(metrics: Dict[str, Any]) -> None:
    metrics[PROMOTE_TARGET][GATE.KEY_ROLE] = GATE.ROLE_PAPER_LINE


def _registry_only(metrics: Dict[str, Any]) -> None:
    metrics[TARGET][GATE.KEY_CAVEAT] = (
        "hand-injected registry-only caveat: not in the payload, so a regenerate erases it"
    )


def _control(metrics: Dict[str, Any]) -> None:
    return None


SCENARIOS: List[Tuple[str, str, Callable[[Dict[str, Any]], None]]] = [
    ("bite1_blank_caveat", "the caveat is set to the empty string", _blank),
    ("bite2_whitespace_caveat", "the caveat is whitespace only", _whitespace),
    ("bite3_removed_caveat_key", "the caveat key is deleted from the row", _removed),
    (
        "bite4_promoted_artifact_row",
        "a caveat-less artifact row is promoted to registry_role: paper_line",
        _promoted,
    ),
    (
        "bite5_registry_only_caveat",
        "the caveat lives ONLY in the registry row, not in the payload",
        _registry_only,
    ),
    ("control_unmutated", "the unmutated copy (control -- must PASS)", _control),
]


_PYTEST_TEMPLATE = '''\
"""Generated by wfa205 bite_demo.py -- bites the SHIPPED gate on a shadow copy."""
import importlib.util, pathlib, sys

GATE_PATH = pathlib.Path({gate!r})
SHADOW = pathlib.Path({shadow!r})

spec = importlib.util.spec_from_file_location("wfa205_gate_bite", GATE_PATH)
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)


def test_gate_is_green_on_this_registry():
    doc = module._load_registry(SHADOW)
    violations = module._violations(doc)
    assert not violations, "gate violations:\\n" + "\\n".join(
        f"  {{v['metric_id']}}: {{v['kind']}}: {{v['detail']}}" for v in violations
    )
'''


def _run_one(name: str, description: str, mutate, tmp_root: pathlib.Path) -> Dict[str, Any]:
    work = tmp_root / name
    work.mkdir(parents=True, exist_ok=True)

    doc = copy.deepcopy(GATE._load_registry(REGISTRY))
    mutate(doc.get("metrics") or {})

    shadow = work / "metrics_shadow.yaml"
    shadow.write_text(GATE._yaml_dump(doc), encoding="utf-8")

    test_file = work / "test_bite_shadow.py"
    test_file.write_text(
        _PYTEST_TEMPLATE.format(gate=str(GATE_MODULE_PATH), shadow=str(shadow)),
        encoding="utf-8",
    )

    env = dict(os.environ)
    env["CUDA_VISIBLE_DEVICES"] = ""
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", str(test_file), "-q", "--no-header", "-p", "no:cacheprovider"],
        cwd=str(REPO),
        env=env,
        capture_output=True,
        text=True,
        timeout=600,
        check=False,
    )
    output = proc.stdout + proc.stderr
    # the interesting part: the assertion text, verbatim
    detail_lines = []
    for line in output.splitlines():
        if line.startswith("E ") or "gate violations:" in line:
            detail_lines.append(line)
    return {
        "scenario": name,
        "mutation": description,
        "shadow_registry": str(shadow),
        "shadow_outside_repo": REPO not in shadow.resolve().parents,
        "pytest_returncode": proc.returncode,
        "verdict": "FAIL (gate fired)" if proc.returncode != 0 else "PASS (gate green)",
        "failure_output": "\n".join(detail_lines) or output.strip().splitlines()[-1],
        "raw_tail": "\n".join(output.strip().splitlines()[-14:]),
    }


def main() -> int:
    tmp_root = pathlib.Path(tempfile.mkdtemp(prefix="wfa205_bite_"))
    results = []
    try:
        for name, description, mutate in SCENARIOS:
            res = _run_one(name, description, mutate, tmp_root)
            results.append(res)
            print("=" * 78)
            print(f"SCENARIO : {res['scenario']}")
            print(f"MUTATION : {res['mutation']}")
            print(f"SHADOW   : {res['shadow_registry']}  (outside repo: {res['shadow_outside_repo']})")
            print(f"VERDICT  : {res['verdict']}  (pytest rc={res['pytest_returncode']})")
            print("-" * 78)
            print(res["failure_output"])
            print()
    finally:
        shutil.rmtree(tmp_root, ignore_errors=True)

    out_dir = pathlib.Path(__file__).resolve().parent
    from molmetal.scripts.wf386a3_atomic_write import atomic_write_file

    atomic_write_file(
        out_dir / "bite_results.json",
        json.dumps(results, indent=2, ensure_ascii=False) + "\n",
    )
    print(f"wrote {out_dir / 'bite_results.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
