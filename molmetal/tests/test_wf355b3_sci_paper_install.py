#  Test 2: scienceplots is importable from the project's venv interpreter
# ---------------------------------------------------------------------------


def test_scienceplots_importable() -> None:
    """scienceplots (MIT, Wf-351-A4 PRIMARY recommendation) must be
    installable + importable from the project's CadButEaas venv.

    Per Wf-355-B3 §6d: install via
    ``PYTHONPATH=/home/hugo/codes/mol-metal /home/hugo/codes/CadButEaas/.venv-vlm/bin/python -m pip install scienceplots``
    and verify with ``python -c "import scienceplots"``.

    scienceplots v2.x does NOT expose ``__version__``; verify via a smoke
    attribute that exists in 2.x (e.g. a style preset name list).
    """
    py = Path(CADBUTEAAS_VENV_PYTHON)
    if not py.exists():
        pytest.skip(f"interpreter not found at {py}")

    # Confirm scienceplots is importable from THIS interpreter.
    result = subprocess.run(
        [str(py), "-c",
         "import scienceplots; print('OK', getattr(scienceplots, '__name__', '?'))"],
        capture_output=True, text=True, timeout=15,
    )
    assert result.returncode == 0, (
        f"scienceplots not importable: stdout={result.stdout!r} "
        f"stderr={result.stderr!r}"
    )
    assert "OK" in result.stdout, (
        f"expected 'OK' marker in stdout, got: {result.stdout!r}"
    )

    # Confirm it can be imported under the project's PYTHONPATH (sanity for
    # the 'import scienceplots' pattern in Wf-355-B3 §6d).
    result2 = subprocess.run(
        [str(py), "-c",
         "import sys; sys.path.insert(0, '/home/hugo/codes/mol-metal'); "
         "import scienceplots; print('PATH_OK')"],
        capture_output=True, text=True, timeout=15,
    )
    # Some hosts may have a sibling ``scienceplots`` module under
    # ``molmetal/`` that shadows; allow that, but the CadButEaas site-packages
    # version must succeed under bare -c.
    assert result2.returncode == 0, (
        f"scienceplots not importable with PYTHONPATH prefix: "
        f"stdout={result2.stdout!r} stderr={result2.stderr!r}"
    )


