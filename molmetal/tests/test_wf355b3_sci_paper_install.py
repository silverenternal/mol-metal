_SETUP_REQUIRED_SECTIONS = [
    r"##\s+§1\s+Zotero",
    r"##\s+§2\s+tectonic",
    r"##\s+§3\s+scienceplots",
    r"##\s+§4\s+sn-jnl",
    r"##\s+§5\s+NO",
]


