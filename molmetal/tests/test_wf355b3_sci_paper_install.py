# ---------------------------------------------------------------------------
#  Test 1: sn-jnl.cls exists at the canonical infra path
# ---------------------------------------------------------------------------


def test_sn_jnl_cls_exists() -> None:
    """sn-jnl.cls must be downloaded into .tools/latex/ (per Wf-355-B3 §6a).

    File downloaded from DanySK's Apache-2.0 mirror of the official Springer
    Nature LaTeX class (Wf-351-A1 §2.1 audit verdict — Apache-2.0, 3★,
    pushed 2026-07-21). MEASURED file size at 2026-09-29: 55,331 B.
    """
    assert SN_JNL_CLS.exists(), f"sn-jnl.cls not found at {SN_JNL_CLS}"
    assert SN_JNL_CLS.is_file(), f"{SN_JNL_CLS} is not a regular file"

    size = SN_JNL_CLS.stat().st_size
    # Sn-jnl.cls is ~50-60 KB; flag anything <10 KB or >500 KB as
    # suspiciously truncated / corrupted.
    assert 10_000 < size < 500_000, (
        f"sn-jnl.cls size {size} B outside expected 10K-500K envelope"
    )

    # Spot-check that this is the docstrip-generated Springer Nature class
    # (NOT a stub / placeholder / unrelated cls file).
    text = SN_JNL_CLS.read_text(encoding="utf-8", errors="replace")
    text_lower = text.lower()
    assert "sn-jnl" in text_lower, (
        f"expected 'sn-jnl' in cls header, got: {text[:200]!r}"
    )
    # A real .cls file generated by docstrip includes the standard
    # docstrip header banner ("This is file `sn-jnl.cls'," + "docstrip
    # utility" + "classes.dtx") AND a LaTeX class provision macro
    # (typically `\ProvidesClass` or `\LoadClass` or the parent class
    # reference). `documentclass` itself is NOT in the .cls body — it's
    # used by .tex files to load the class.
    assert "docstrip utility" in text_lower, (
        "expected docstrip header banner in cls file"
    )
    assert "classes.dtx" in text_lower, (
        "expected docstrip source-file reference 'classes.dtx' in cls header"
    )
    assert (
        "\\ProvidesClass" in text
        or "\\LoadClass" in text
        or "\\NeedsTeXFormat" in text
    ), "expected LaTeX class provision / load macros in cls body"
    # LPPL or Apache header should be present (audit declared Apache-2.0 mirror;
    # the underlying cls itself is LPPL-1.3c per the docstrip header).
    assert "LPPL" in text or "Apache" in text or "License" in text, (
        f"expected license header in cls file (LPPL or Apache)"
    )


