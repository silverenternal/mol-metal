def test_scienceplots_importable() -> None:
    """scienceplots (MIT, Wf-351-A4 PRIMARY recommendation) must be
    installable + importable from the project's CadButEaas venv.

    Per Wf-355-B3 §6d + Wf-356-A3 retry: install via
    ``PYTHONPATH=/home/hugo/codes/mol-metal /home/hugo/codes/CadButEaas/.venv-vlm/bin/python -m pip install scienceplots``
    and verify with ``python -c "import scienceplots"``.

    scienceplots v2.x does NOT expose ``__version__``; verify via
    ``importlib.metadata.version('scienceplots')`` to pin a known-good
    version (2.2.2 per Wf-355-B3 closeout).
    """
    py = Path(CADBUTEAAS_VENV_PYTHON)
    if not py.exists():
        pytest.skip(f"interpreter not found at {py}")

    # Confirm scienceplots is importable from THIS interpreter.
    result = subprocess.run(
        [str(py), "-c",
         "import scienceplots; print('OK', getattr(scienceplots, '__name__', '?'))"],
        capture_output=True, text=True, timeout=15,
    )
    assert result.returncode == 0, (
        f"scienceplots not importable: stdout={result.stdout!r} "
        f"stderr={result.stderr!r}"
    )
    assert "OK" in result.stdout, (
        f"expected 'OK' marker in stdout, got: {result.stdout!r}"
    )

    # Confirm version pinning via importlib.metadata (since scienceplots 2.x
    # does NOT expose __version__ attribute).
    ver_result = subprocess.run(
        [str(py), "-c",
         "import importlib.metadata as m; print('VER', m.version('scienceplots'))"],
        capture_output=True, text=True, timeout=15,
    )
    assert ver_result.returncode == 0, (
        f"scienceplots version probe failed: stdout={ver_result.stdout!r} "
        f"stderr={ver_result.stderr!r}"
    )
    assert "VER" in ver_result.stdout, (
        f"expected VER marker in version stdout, got: {ver_result.stdout!r}"
    )
    # Expected: 2.2.2 (per Wf-355-B3 closeout)
    assert "2.2.2" in ver_result.stdout, (
        f"expected scienceplots version 2.2.2 per Wf-355-B3 closeout, "
        f"got: {ver_result.stdout!r}"
    )


