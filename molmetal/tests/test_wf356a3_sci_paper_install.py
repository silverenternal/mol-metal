_SETUP_REQUIRED_SECTIONS = [
    r"##\s+§1\s+Zotero",
    r"##\s+§2\s+tectonic",
    r"##\s+§3\s+scienceplots",
    r"##\s+§4\s+sn-jnl",
    r"##\s+§5\s+NO",
]


def test_install_instructions_documented() -> None:
    """docs/SCI_PAPER_SETUP.md must exist with the 4 mandatory install
    sections + the §5 NO-paper-touches discipline.

    Per Wf-355-B3 §7 the install instructions must cover:
      §1 Zotero install steps
      §2 tectonic install steps
      §3 scienceplots install steps
      §4 sn-jnl .cls verification
      §5 NO paper/* touches per TODO-84
    """
    assert SETUP_MD.exists(), f"setup doc not found at {SETUP_MD}"
    assert SETUP_MD.is_file()

    text = SETUP_MD.read_text(encoding="utf-8")

    # All 5 required sections must be present (regex above allows §1 / §2 / ...
    # §5.3 numbering prefix variants).
    for pat in _SETUP_REQUIRED_SECTIONS:
        assert re.search(pat, text), (
            f"expected section matching {pat!r} in {SETUP_MD.name}"
        )

    # §5 must explicitly reference TODO-84 + AGENTS.md §5.3 — these are the
    # standing directives that prohibit paper/* touches without user OK.
    sec5_match = re.search(
        r"##\s+§5[\s\S]+?(?=\n##\s+§|\Z)", text,
    )
    assert sec5_match is not None, "could not locate §5 section"
    sec5 = sec5_match.group(0)
    assert "TODO-84" in sec5, "§5 must reference TODO-84 (paper auth rule)"
    assert "AGENTS.md" in sec5, "§5 must reference AGENTS.md"

    # The doc must NOT claim installs were performed when this build host
    # does not have the binaries (zotero, tectonic) on PATH. Verify with
    # shell probes.
    for binary in ("zotero", "tectonic"):
        probe = subprocess.run(
            ["which", binary],
            capture_output=True, text=True, timeout=5,
        )
        if probe.returncode != 0:
            # binary NOT installed — doc must flag it as INSTALL-REQUIRED.
            assert "INSTALL-REQUIRED" in text, (
                f"setup doc must flag '{binary}' as INSTALL-REQUIRED when not on PATH"
            )
        else:
            # Binary present — doc should NOT flag it as install-required.
            # (we don't strictly enforce the negative, but log for context)
            pass


