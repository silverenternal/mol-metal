#!/usr/bin/env python
"""test_wrapper_python_path.py — verifies wrappers reference molmetal/.venv/bin/python
(per AGENTS.md §5.9 hardcoded-PY rule + Wf-431-A1 fix).

Accepts both `PY=...` assignment form AND inline `${PROJECT_ROOT}/.venv/bin/python`
form. Generated by Wf-A2 wrapper test coverage analysis (2026-10-02).
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

REPO_ROOT = Path("/home/hugo/codes/mol-metal")
SCRIPTS_DIR = REPO_ROOT / "scripts"
EXPECTED_PY_SUFFIX = "/.venv/bin/python"

# 5 of the 8 CANONICAL REAL wrappers — fast scan; does not require execution.
PY_PATH_TEST_WRAPPERS = [
    "launch_wf299_cfm_main.sh",
    "launch_wf310e_r20_p4_bindingdb_1.07M.sh",
    "launch_wf310e_r20_p5_tmqm_plat_joint_retrain.sh",
    "launch_wf125_p1_controlled_pair.sh",
    "launch_wf388_a1_metal_coord_retrain.sh",
]


@pytest.mark.parametrize("wrapper_name", PY_PATH_TEST_WRAPPERS)
def test_wrapper_references_molmetal_venv_python(wrapper_name: str) -> None:
    """Wrapper should reference molmetal/.venv/bin/python somewhere (either
    via PY= variable OR inline `${PROJECT_ROOT}/.venv/bin/python` exec)."""
    wrapper = SCRIPTS_DIR / wrapper_name
    assert wrapper.exists(), f"{wrapper_name} not on disk"
    content = wrapper.read_text(encoding="utf-8")
    # Match either PY=/path assignment OR inline path reference.
    has_py_var = bool(
        re.search(r'PY\s*=\s*["\']?([^"\'\s]+)', content)
    )
    has_inline = "/.venv/bin/python" in content
    assert has_py_var or has_inline, (
        f"{wrapper_name} does NOT reference molmetal/.venv/bin/python\n"
        f"(no PY= assignment AND no inline path)"
    )

    # If PY= form is used, verify the path suffix.
    m = re.search(r'PY\s*=\s*["\']?([^"\'\s]+)', content)
    if m:
        py_val = m.group(1)
        # Accept either direct hardcoded path OR ${VAR:-default} expansion.
        if "${" in py_val:
            # shell parameter expansion — extract the default value if present.
            dm = re.search(r':-\s*([^}]+)\}', py_val)
            if dm:
                py_val = dm.group(1)
        assert py_val.endswith(EXPECTED_PY_SUFFIX), (
            f"{wrapper_name} PY mismatch:\n"
            f"  expected suffix: {EXPECTED_PY_SUFFIX}\n  got:            {py_val}"
        )
