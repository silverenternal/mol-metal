def test_hash_match_passes_with_digest_prefix(tmp_path):
    csv = _csv(tmp_path / "ok.csv", "a,b\n1,2\n3,4\n")
    man = _manifest(
        tmp_path / "m.json",
        {csv.name: {"sha256": _sha(csv), "n_lines": 3, "frozen_at": "x"}},
    )
    res = gate_csv_hash("t", *P0, [(csv, 2)], manifest_path=man)
    assert res.status == "PASS"
    assert _sha(csv)[:12] in res.evidence


def test_hash_mismatch_BLOCKS_by_default(tmp_path, monkeypatch):
    """Digest mismatch FAILS by default.

    Contract changed 2026-10-03 (Wf-A13 follow-up). This test previously
    asserted the opposite — PASS with a loud warning — i.e. it pinned a gate
    that detected tampering and then let it through. Detection without
    consequence is the defect class this audit removed, so the switch was
    flipped and the test moved with it.

    Blocking is safe because the tree was green at flip time (5/5 verified)
    and the failure message names its own remedy (--freeze-csv-hashes). The
    hyperparameter-resolution switch stays OFF for the opposite reason: ~528
    unresolved keys would fail every commit.
    """
    csv = _csv(tmp_path / "tampered.csv", "a,b\n1,2\n3,4\n")
    frozen = _sha(csv)
    csv.write_text("a,b\n1,2\n3,9\n", encoding="utf-8")  # cell edit, 3 rows kept
    man = _manifest(
        tmp_path / "m.json",
        {csv.name: {"sha256": frozen, "n_lines": 3, "frozen_at": "x"}},
    )
    monkeypatch.delenv(CSV_HASH_STRICT_ENV, raising=False)
    res = gate_csv_hash("t", *P0, [(csv, 3)], manifest_path=man)
    assert res.status == "FAIL"  # blocking ON by default
    assert "SHA-256 MISMATCH" in res.evidence


def test_hash_mismatch_downgradable_via_env(tmp_path, monkeypatch):
    """The escape hatch must work in BOTH directions.

    Regression guard for the bug this fix introduced and then caught: the
    original resolution was ``DEFAULT or (env in {truthy})`` — an OR — so once
    the default became True the env var could only turn it ON, and the
    documented ``=0`` downgrade silently did nothing.
    """
    csv = _csv(tmp_path / "tampered.csv", "a,b\n1,2\n3,4\n")
    frozen = _sha(csv)
    csv.write_text("a,b\n1,2\n3,9\n", encoding="utf-8")
    man = _manifest(
        tmp_path / "m.json",
        {csv.name: {"sha256": frozen, "n_lines": 3, "frozen_at": "x"}},
    )
    monkeypatch.setenv(CSV_HASH_STRICT_ENV, "0")
    res = gate_csv_hash("t", *P0, [(csv, 3)], manifest_path=man)
    assert res.status == "PASS"  # explicitly downgraded
    assert "SHA-256 MISMATCH" in res.evidence


def test_hash_mismatch_fails_in_strict_mode(tmp_path, monkeypatch):
    csv = _csv(tmp_path / "tampered.csv", "a,b\n1,2\n3,4\n")
    frozen = _sha(csv)
    csv.write_text("a,b\n1,2\n3,9\n", encoding="utf-8")
    man = _manifest(
        tmp_path / "m.json",
        {csv.name: {"sha256": frozen, "n_lines": 3, "frozen_at": "x"}},
    )
    monkeypatch.setenv(CSV_HASH_STRICT_ENV, "1")
    res = gate_csv_hash("t", *P0, [(csv, 3)], manifest_path=man)
    assert res.status == "FAIL"
    assert "SHA-256 MISMATCH" in res.evidence


def test_manifest_absent_skips_with_linecount_fallback(tmp_path):
    csv = _csv(tmp_path / "ok.csv", "a,b\n1,2\n3,4\n")
    res = gate_csv_hash("t", *P0, [(csv, 2)], manifest_path=tmp_path / "none.json")
    assert res.status == "SKIP"
