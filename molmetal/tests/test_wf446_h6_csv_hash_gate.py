"""Wf-446 HOLE-6 — ``gate_csv_hash`` real SHA-256 verification tests.

Before the HOLE-6 fix, ``gate_csv_hash`` only ran ``wc -l``: a cell edit
that preserves the row count was invisible.  It now also compares each
gated CSV's full-file SHA-256 against the frozen, git-tracked manifest
``configs/data_checksums.json`` (generated by
``python -m molmetal.scripts.pre_flight_check --freeze-csv-hashes``).

Covered here (CPU-only, no network, no GPU):

  1. the shipped manifest verifies the shipped gated CSVs (healthy tree);
  2. the frozen v2 digest equals the independently documented value
     (``cc3ea247...``, TODO/completed/207_unified_pre_flight_checklist_v2.md);
  3. digest match -> PASS with digest prefix;
  4. digest MISMATCH -> loud non-blocking PASS by default, FAIL only with
     ``PREFLIGHT_CSV_HASH_STRICT=1`` (the OFF-switch contract);
  5. manifest absent / unusable -> SKIP with line-count fallback result;
  6. legacy blocking behaviour preserved (missing file / short file FAIL);
  7. gate spec list and manifest keys cannot drift apart.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pytest

from molmetal.scripts.pre_flight_check import (
    CSV_HASH_MANIFEST_DEFAULT,
    CSV_HASH_STRICT_ENV,
    REPO_ROOT,  # noqa: F401  (kept for parity with sibling test modules)
    _csv_manifest_keys,
    gate_csv_hash,
    gated_csv_specs,
)

P0 = ("P0", "data")


def _csv(path: Path, text: str) -> Path:
    path.write_text(text, encoding="utf-8")
    return path


def _manifest(path: Path, entries: dict) -> Path:
    path.write_text(
        json.dumps({"schema": "test", "files": entries}, indent=2),
        encoding="utf-8",
    )
    return path


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


# ---------------------------------------------------------------------------
# 1-2. Healthy tree: shipped manifest verifies shipped CSVs
# ---------------------------------------------------------------------------


def test_real_manifest_verifies_real_csvs():
    """The shipped configs/data_checksums.json must verify every gated CSV."""
    if not CSV_HASH_MANIFEST_DEFAULT.is_file():
        pytest.skip("frozen manifest not present in this checkout")
    specs = gated_csv_specs()
    missing = [str(p) for p, _ in specs if not p.is_file()]
    if missing:
        pytest.skip(f"gated CSVs absent (fresh clone without .data/): {missing}")
    res = gate_csv_hash("t_csv_hash_real", *P0, specs)
    assert res.status == "PASS", res.evidence
    assert "SHA-256-verified" in res.evidence
    assert f"{len(specs)}/{len(specs)}" in res.evidence


def test_frozen_v2_digest_matches_documented_value():
    """Cross-check: the frozen v2 digest is the value recorded since Wf-261."""
    if not CSV_HASH_MANIFEST_DEFAULT.is_file():
        pytest.skip("frozen manifest not present in this checkout")
    man = json.loads(CSV_HASH_MANIFEST_DEFAULT.read_text(encoding="utf-8"))
    key = None
    for k in man["files"]:
        if k.endswith("metalcytotox_5metal_multitask_v2.csv"):
            key = k
    assert key is not None, "v2 CSV missing from frozen manifest"
    assert (
        man["files"][key]["sha256"]
        == "cc3ea24755f1b14a69c8c3acd827db0bc1dd123301479c9ca490920725adf063"
    )


def test_manifest_keys_cover_gated_specs():
    """Anti-drift: every gated spec has a frozen entry (and vice versa)."""
    if not CSV_HASH_MANIFEST_DEFAULT.is_file():
        pytest.skip("frozen manifest not present in this checkout")
    man = json.loads(CSV_HASH_MANIFEST_DEFAULT.read_text(encoding="utf-8"))
    spec_keys = {_csv_manifest_keys(p)[0] for p, _ in gated_csv_specs()}
    assert spec_keys == set(man["files"]), (
        "gate spec list and frozen manifest drifted — re-run "
        "`python -m molmetal.scripts.pre_flight_check --freeze-csv-hashes`"
    )


