"""Wf-A190 -- THE LINE-NUMBER LOCATOR CLASS (the CONSUMER side).

A line-number locator into an artefact that GROWS or is REGENERATED is stale
BY CONSTRUCTION: the next wave inserts a line and the locator points at the
wrong content.  The rule this file enforces:

    the LIVE locator is a JSON PATH (into a JSON artefact) or a SECTION ANCHOR
    (into a Markdown artefact).  A line number may only appear inside a DATED
    historical record that says, in the same place, that it is a dated
    historical snapshot (AGENTS.md 5.5 rule #6 -- append-only + dated).

These tests read the PUBLISHED artefacts and assert:

  T1  no LIVE key presents a line number as a current locator into a growing
      artefact;
  T2  every dated demotion preserves its superseded string VERBATIM, and the
      preservation is corroborated by a second, independent copy in the
      corpus (so a paraphrase on either side is caught);
  T3  every dated demotion actually REPLACED the live value it names (so a
      reverted repair is caught);
  T4  every durable locator this wave published actually RESOLVES in its
      target (a demotion to a wrong path is caught);
  T5  both producers still regenerate their artefacts BYTE-IDENTICALLY into a
      temp dir (producer <-> artefact parity; a fix a producer re-run would
      erase is not a fix).

CPU-only.  No GPU.  No network.  No `os.walk` (the repo is 201 GB).
"""
from __future__ import annotations

import importlib.util
import json
import pathlib
import re
import runpy

import pytest

REPO = pathlib.Path(__file__).resolve().parents[2]

A175 = REPO / "molmetal/reports/wfa175_band_provenance"
A186 = REPO / "molmetal/reports/wfa186_frontier_primary_source"

# ---------------------------------------------------------------------------
# The GROWING TARGETS.  A `file:line` into any of these is perishable:
#   * the catalogue is APPEND-ONLY and grows every wave;
#   * the three metric artefacts are REGENERATED by their producers;
#   * the record is regenerated and keeps growing;
#   * the two branch reports grow when a wave appends a section.
# `report.md` is ambiguous across the repo, so for the two report targets only
# the FULL repo-relative path counts as an unambiguous locator.
# ---------------------------------------------------------------------------
GROWING_TARGETS = (
    "docs/HONEST_NEGATIVE_CATALOG.md",
    "metrics/by_metric/wfa155_ligand_connected_rate.json",
    "metrics/by_metric/wfa155_metal_coordination_sphere.json",
    "metrics/by_metric/wfa155_posebusters_validity.json",
    "molmetal/reports/wfa158_frontier_postproc_matrix/frontier_matrix.json",
    "molmetal/reports/wfa175_band_provenance/report.md",
    "molmetal/reports/wfa175_band_provenance/sites.json",
    "molmetal/reports/wfa186_frontier_primary_source/report.md",
    "molmetal/reports/wfa186_frontier_primary_source/primary_source_verification.json",
)

_AMBIGUOUS_BASENAMES = {"report.md"}
_BASENAMES = sorted(
    {t.rsplit("/", 1)[-1] for t in GROWING_TARGETS} - _AMBIGUOUS_BASENAMES
)
_FULLPATHS = sorted(t for t in GROWING_TARGETS if t.rsplit("/", 1)[-1] in _AMBIGUOUS_BASENAMES)

LOCATOR_RE = re.compile(
    r"(?P<file>" + "|".join(re.escape(b) for b in _BASENAMES + _FULLPATHS) + r"):(?P<line>\d+)"
)

# A JSON subtree under any of these keys is a DATED historical record.
DATED_KEY_RE = re.compile(
    r"superseded|demotion|stale_by_construction|why_superseded"
    r"|verification_records_left_verbatim|left_alone_and_why"
    r"|census_line_datum_drift|what_the_superseded"
)
# Rule 14: these hold VERIFICATION RECORDS and REFUTATION QUOTES -- they are
# not live claims and must not be "repaired"; fixing them destroys the
# evidence that the defect was found.
RULE14_KEYS = frozenset({"what_i_checked", "counter_evidence"})

# A Markdown line under a heading that says it is a dated record is exempt.
DATED_HEADING_RE = re.compile(
    r"CORRECTION|DEMOTION|DEMOTED|SUPERSEDED|DRIFTED|VERBATIM", re.IGNORECASE
)

# The artefacts this wave OWNS and therefore scans.
SCANNED_JSON = (
    "molmetal/reports/wfa175_band_provenance/refutation/refutation.json",
    "molmetal/reports/wfa175_band_provenance/coverage_gap_sites.json",
    "molmetal/reports/wfa186_frontier_primary_source/primary_source_verification.json",
)
SCANNED_MD = (
    "molmetal/reports/wfa175_band_provenance/report.md",
    "molmetal/reports/wfa175_band_provenance/refutation/refutation.md",
    "molmetal/reports/wfa186_frontier_primary_source/report.md",
)

DASH_CHARS = "‐‑‒–—―−-"


def _norm(text: str) -> str:
    """Normalise a Markdown rendering so a durable anchor can be checked
    against the file it points into: strip emphasis, fold every dash variant
    onto ASCII `-`, fold `==>` onto `=>`, drop the section sign, collapse
    horizontal whitespace.  Newlines are KEPT (headings are line-scoped)."""
    text = text.replace("**", "").replace("`", "").replace("*", "")
    text = text.replace("⇒", "=>").replace("§", "")
    for ch in DASH_CHARS:
        text = text.replace(ch, "-")
    text = re.sub(r"-{2,}", "-", text)
    text = re.sub(r"[ \t]+", " ", text)
    return text.strip().lower()


# ---------------------------------------------------------------------------
# T1 -- scan for LIVE line-number locators
# ---------------------------------------------------------------------------
def scan_json_for_live_locators(obj, path="", dated=False):
    """Return [(json_path, matched_locator, snippet)] for every LIVE string
    that presents a line number as a current locator into a growing artefact."""
    hits = []
    if isinstance(obj, dict):
        for key, val in obj.items():
            child_dated = dated or bool(DATED_KEY_RE.search(key)) or key in RULE14_KEYS
            hits.extend(scan_json_for_live_locators(val, f"{path}/{key}", child_dated))
    elif isinstance(obj, list):
        for idx, val in enumerate(obj):
            hits.extend(scan_json_for_live_locators(val, f"{path}[{idx}]", dated))
    elif isinstance(obj, str) and not dated:
        match = LOCATOR_RE.search(obj)
        if match:
            lo = max(0, match.start() - 50)
            hits.append((path, match.group(0), obj[lo:match.end() + 50]))
    return hits


def scan_md_for_live_locators(text):
    """Return [(line_no, matched_locator, snippet)] for every LIVE Markdown
    line that presents a line number as a current locator."""
    hits = []
    stack = []  # (level, heading text)
    for lineno, line in enumerate(text.split("\n"), 1):
        if line.lstrip().startswith("#"):
            level = len(line) - len(line.lstrip("#"))
            while stack and stack[-1][0] >= level:
                stack.pop()
            stack.append((level, line))
        if any(DATED_HEADING_RE.search(h[1]) for h in stack):
            continue
        for match in LOCATOR_RE.finditer(line):
            lo = max(0, match.start() - 50)
            hits.append((lineno, match.group(0), line[lo:match.end() + 50]))
    return hits


def test_t1_no_live_line_number_locator_into_a_growing_artefact():
    """T1: no LIVE key may present a line number as a current locator."""
    offenders = []
    for rel in SCANNED_JSON:
        obj = json.loads((REPO / rel).read_text(encoding="utf-8"))
        for jpath, loc, snip in scan_json_for_live_locators(obj):
            offenders.append(f"{rel} {jpath}: {loc!r}  in  ...{snip}...")
    for rel in SCANNED_MD:
        text = (REPO / rel).read_text(encoding="utf-8")
        for lineno, loc, snip in scan_md_for_live_locators(text):
            offenders.append(f"{rel}:{lineno}: {loc!r}  in  ...{snip}...")
    assert not offenders, (
        "LIVE line-number locators into a growing artefact "
        f"({len(offenders)} found):\n  " + "\n  ".join(offenders)
    )


# ---------------------------------------------------------------------------
# T2 / T3 -- the dated demotions
# ---------------------------------------------------------------------------
DATED_BLOCKS = {
    "molmetal/reports/wfa175_band_provenance/refutation/refutation.json": (
        "locator_demotion_2026_11_01_stale_by_construction",
        "locator_demotion_2026_11_02_stale_by_construction",
    ),
    "molmetal/reports/wfa175_band_provenance/coverage_gap_sites.json": (
        "locator_demotion_2026_11_01_stale_by_construction",
        "locator_demotion_2026_11_02_stale_by_construction",
    ),
    "molmetal/reports/wfa186_frontier_primary_source/primary_source_verification.json": (
        "locator_demotion_2026_11_02_stale_by_construction",
    ),
}
# Every list inside a dated block that holds a superseded rendering.
SUPERSEDED_LISTS = (
    "superseded_strings_verbatim",
    "superseded_numeric_locators_verbatim",
    "superseded_key_names_verbatim",
)
# The corpus the preservation is checked against.  A superseded rendering that
# exists in exactly ONE place is not verifiable: a paraphrase there passes
# unnoticed.  `report.md` -> section 10 is the corpus-wide ledger that holds
# the SECOND copy.
CORPUS = (
    "molmetal/reports/wfa175_band_provenance/report.md",
    "molmetal/reports/wfa175_band_provenance/sites.json",
    "molmetal/reports/wfa175_band_provenance/coverage_gap_sites.json",
    "molmetal/reports/wfa175_band_provenance/refutation/refutation.json",
    "molmetal/reports/wfa175_band_provenance/refutation/refutation.md",
    "molmetal/reports/wfa175_band_provenance/refutation/_recheck.json",
    "molmetal/reports/wfa186_frontier_primary_source/report.md",
    "molmetal/reports/wfa186_frontier_primary_source/primary_source_verification.json",
)


def _demotion_entries(rel):
    obj = json.loads((REPO / rel).read_text(encoding="utf-8"))
    for block in DATED_BLOCKS[rel]:
        node = obj.get(block)
        assert node is not None, f"{rel}: missing dated block {block!r}"
        for list_name in SUPERSEDED_LISTS:
            for entry in node.get(list_name) or []:
                yield block, list_name, entry


def _present(text, corpus_rel):
    """Is `text` present VERBATIM in the corpus artefact?  A JSON artefact
    stores the JSON-escaped rendering; a Markdown artefact stores the raw
    one."""
    raw = (REPO / corpus_rel).read_text(encoding="utf-8")
    if corpus_rel.endswith(".json"):
        return json.dumps(text, ensure_ascii=False)[1:-1] in raw
    return text in raw


def test_t2_dated_demotions_preserve_their_superseded_strings_verbatim():
    """T2: every dated demotion keeps its superseded rendering VERBATIM --
    not paraphrased, not re-typed, not silently dropped (AGENTS.md §5.5
    rule #6) -- and the preservation is CORROBORATED by a second, independent
    copy elsewhere in the corpus, so a paraphrase on either side is caught."""
    problems = []
    for rel in DATED_BLOCKS:
        for block, list_name, entry in _demotion_entries(rel):
            text = entry.get("text") if isinstance(entry, dict) else entry
            where = entry.get("where") if isinstance(entry, dict) else None
            if not isinstance(text, str) or not text.strip():
                problems.append(f"{rel} {block} {list_name}: entry has no `text`: {entry!r}")
                continue
            if not _present(text, rel):
                problems.append(
                    f"{rel} {block} {list_name} -> {where}: the superseded string "
                    f"is NOT present VERBATIM in its own artefact: {text!r}"
                )
                continue
            others = [c for c in CORPUS if c != rel and _present(text, c)]
            if not others:
                problems.append(
                    f"{rel} {block} {list_name} -> {where}: the superseded rendering "
                    f"exists in NO second place in the corpus (single-copy "
                    f"preservation is unverifiable): {text!r}"
                )
    assert not problems, "verbatim preservation failures:\n  " + "\n  ".join(problems)


def _resolve_where(obj, where):
    """Resolve a `where` of the form `claims[2].evidence_paths[0]` (or
    `sites[3].note`, `retrieval[1].authors_note`) to the live value it
    names.  Returns None when the `where` is not machine-resolvable (e.g.
    'refutation.md, per-claim table row 6' or 'top level')."""
    where = (where or "").strip()
    m = re.match(r"^(?P<base>[A-Za-z_][A-Za-z0-9_]*)", where)
    if not m:
        return None
    base = m.group("base")
    if base not in obj:
        return None
    node = obj[base]
    for tok in re.findall(r"[^.\[\]]+|\[\d+\]", where[len(base):]):
        try:
            node = node[int(tok[1:-1])] if tok.startswith("[") else node[tok]
        except (KeyError, IndexError, TypeError):
            return None
    return node


def test_t3_dated_demotion_actually_replaced_the_live_value():
    """T3: a dated demotion must have REPLACED the live value it names.  If a
    repair is reverted -- the old line number put back into the live key --
    this fails."""
    problems = []
    for rel in DATED_BLOCKS:
        obj = json.loads((REPO / rel).read_text(encoding="utf-8"))
        for block, list_name, entry in _demotion_entries(rel):
            if not isinstance(entry, dict):
                continue
            where = entry.get("where", "")
            live = _resolve_where(obj, where)
            if live is None:
                continue  # not machine-resolvable; not a live claim
            if not isinstance(live, str):
                continue
            superseded = entry.get("text", "")
            if superseded and superseded in live:
                problems.append(
                    f"{rel} {block} {list_name} -> {where}: the LIVE value still "
                    f"carries the superseded rendering {superseded!r}; the demotion "
                    f"was REVERTED (live = {live!r})"
                )
    assert not problems, "reverted demotions:\n  " + "\n  ".join(problems)


# ---------------------------------------------------------------------------
# T4 -- every durable locator RESOLVES
# ---------------------------------------------------------------------------
def _resolve_json_path(target_rel, jpath):
    cur = json.loads((REPO / target_rel).read_text(encoding="utf-8"))
    for tok in re.findall(r"[^.\[\]]+|\[\d+\]", jpath):
        cur = cur[int(tok[1:-1])] if tok.startswith("[") else cur[tok]
        if cur is None:
            return None
    return cur


def _check_md_anchor(target_rel, anchor):
    """Return a list of failing segment descriptions for a SECTION ANCHOR."""
    problems = []
    norm_text = _norm((REPO / target_rel).read_text(encoding="utf-8"))
    for seg in anchor:
        if seg.startswith("the emitter of"):
            continue
        if seg.startswith("section "):
            num = seg.split()[1]
            ok = bool(re.search(r"^#+\s*" + re.escape(num) + r"\b", norm_text, re.M))
        elif seg.startswith("subsection '") and seg.endswith("'"):
            ok = _norm(seg[len("subsection '"):-1]) in norm_text
        elif seg.startswith("the '") and seg.endswith("' line"):
            ok = _norm(seg[len("the '"):-len("' line")]) in norm_text
        elif seg.startswith("the ") and seg.endswith((" row", " table", " block")):
            ok = _norm(seg[len("the "):-seg.rfind(" ")]) in norm_text
        else:
            ok = _norm(seg) in norm_text
        if not ok:
            problems.append(f"{target_rel}: segment {seg!r} does not resolve")
    return problems


def test_t4_every_durable_locator_resolves():
    """T4: each durable locator published by the demotion must resolve in its
    target -- a demotion to a wrong JSON path or a wrong section number is
    caught."""
    rel = "molmetal/reports/wfa175_band_provenance/coverage_gap_sites.json"
    obj = json.loads((REPO / rel).read_text(encoding="utf-8"))
    problems = []
    checked = 0
    for site in obj["sites"]:
        locator = site.get("durable_locator")
        if not locator:
            problems.append(f"{rel}: a site has no `durable_locator`: {site.get('site')!r}")
            continue
        parts = [p.strip() for p in locator.split("->")]
        checked += 1
        if parts[0].endswith(".json"):
            try:
                if _resolve_json_path(parts[0], parts[-1]) is None:
                    problems.append(f"{rel}: {locator!r} resolves to None")
            except (KeyError, IndexError, TypeError) as exc:
                problems.append(f"{rel}: {locator!r} does not resolve ({exc!r})")
        elif parts[0].endswith(".py"):
            artefact = parts[1].replace("the emitter of ", "", 1)
            try:
                if _resolve_json_path(artefact, parts[-1]) is None:
                    problems.append(f"{rel}: {locator!r} resolves to None")
            except (KeyError, IndexError, TypeError) as exc:
                problems.append(f"{rel}: {locator!r} does not resolve ({exc!r})")
        else:
            problems.extend(_check_md_anchor(parts[0], parts[1:]))
    assert checked == len(obj["sites"]), (
        f"{rel}: only {checked} of {len(obj['sites'])} sites carry a durable_locator"
    )
    assert not problems, "unresolvable durable locators:\n  " + "\n  ".join(problems)


# ---------------------------------------------------------------------------
# T5 -- producer <-> artefact parity (byte-identical regeneration)
# ---------------------------------------------------------------------------
def _load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_t5a_refutation_producer_regenerates_byte_identically(tmp_path, monkeypatch):
    """T5a: `refutation/_write_refutation.py` must regenerate
    `refutation.json` + `refutation.md` byte-identically into a temp dir.

    The producer redirects its output with the `WFA175_REFUTATION_OUT` env var
    (the redirect that Wf-A190 added for exactly this temp-dir diff)."""
    monkeypatch.setenv("WFA175_REFUTATION_OUT", str(tmp_path))
    runpy.run_path(str(A175 / "refutation/_write_refutation.py"), run_name="__main__")
    for name in ("refutation.json", "refutation.md"):
        rebuilt = (tmp_path / name).read_bytes()
        published = (A175 / "refutation" / name).read_bytes()
        assert rebuilt == published, (
            f"{name}: the producer's output differs from the published artefact "
            f"(rebuilt {len(rebuilt)} B, published {len(published)} B) -- the "
            "published file was hand-patched, or the producer drifted"
        )


def test_t5b_a186_build_regenerates_byte_identically(tmp_path):
    """T5b: the A186 `tools/build.py` must regenerate
    `primary_source_verification.json` + `report.md` byte-identically into a
    temp dir.  The build reads ONLY the cached receipts under `cache/`; it
    does NOT re-fetch the network."""
    mod = _load_module("wfa190_a186_build", A186 / "tools/build.py")
    mod.BASE = str(tmp_path)  # write into the temp dir; CACHE/REPO stay real
    assert mod.main() == 0, "the A186 build's own narrative self-consistency check FAILED"
    for name in ("primary_source_verification.json", "report.md"):
        rebuilt = (tmp_path / name).read_bytes()
        published = (A186 / name).read_bytes()
        assert rebuilt == published, (
            f"{name}: the A186 build's output differs from the published artefact "
            f"(rebuilt {len(rebuilt)} B, published {len(published)} B)"
        )


