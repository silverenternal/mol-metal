"""BLK-C-M3 — the gen_validity noise floor for paired guidance sweeps.

BLK-C-M3 (`cfm_todo.json::blockers[id=BLK-C-M3]`) is open because per-epoch n
varies 48 to 768 across runs and the metric swings 0.0-1.0 on the small-n
runs. The "is this difference real" question therefore has no stated floor.

This test pins the floor statement for the L3 4-arm guidance sweep
(`metrics/by_metric/cfm_l3_guidance_sweep.json`). That sweep is paired — every
arm decodes the SAME 64 clouds with the SAME initial noise (seed 1234) — so
the right comparison is McNemar on per-cloud pass/fail, not a t-test on the
marginal rates.

The numeric table this test re-derives is on disk in
`molmetal/reports/cfm_l3_guidance_sweep_seed0/arm_strength{0.0,0.01,0.05,0.15}.json`,
each with 64 ``decode.rows`` carrying ``smiles`` (None on failure).

MEASURED discordant matrix (2026-10-12, n=64 paired):
    pair               FP   PF   net  n_disc   McNemar exact p
    0.0  -> 0.01        3    2   +1      5     1.0000    SUB-FLOOR
    0.0  -> 0.05       14    4  +10     18     0.0309    CLEAR
    0.0  -> 0.15       37    6  +31     43     <0.0001   CLEAR
    0.01 -> 0.05       12    3   +9     15     0.0352    CLEAR
    0.01 -> 0.15       36    6  +30     42     <0.0001   CLEAR
    0.05 -> 0.15       27    6  +21     33     0.0003    CLEAR

What this file asserts:
    1. the discordant matrix is reproducible from the on-disk arm JSONs (so
       the floor finding is re-derivable from data, not just a printed table);
    2. the (0.0, 0.01) pair is SUB-FLOOR (p >= 0.05) — the +1-success step
       between control and the weakest guided arm is statistically
       indistinguishable from a tied sweep on n=64 paired;
    3. the five other pairs CLEAR the floor (p < 0.05) — the 0.05 and 0.15
       arms both genuinely improve decode rate over control AND over 0.01;
    4. the floor constants (unpaired CI half-width, conservative paired net
       threshold) are not silently rewritten.

Standing rules (AGENTS.md §1.4): a failing test is reported, never weakened.
If BLK-C-M3 is re-measured and the discordant matrix shifts, the assertions
below shift with it AND the test report names the prior assumption.
"""

from __future__ import annotations

import json
from itertools import combinations
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SWEEP_DIR = REPO / "molmetal/reports/cfm_l3_guidance_sweep_seed0"
ARMS = ("0.0", "0.01", "0.05", "0.15")

# ---------------------------------------------------------------------------
# Measured constants. If the sweep re-runs and these move, the table below
# must be regenerated by hand from the new per-cloud rows -- do NOT rewrite
# one to make the test green.
# ---------------------------------------------------------------------------

#: MEASURED discordant matrix, FP = fail->pass going up in strength,
#: PF = pass->fail going up in strength, exact McNemar two-sided p.
MEASURED_PAIRS = {
    ("0.0", "0.01"):  {"FP": 3,  "PF": 2,  "exact_p": 1.0000},
    ("0.0", "0.05"):  {"FP": 14, "PF": 4,  "exact_p": 0.0309},
    ("0.0", "0.15"):  {"FP": 37, "PF": 6,  "exact_p": 0.0000},
    ("0.01", "0.05"): {"FP": 12, "PF": 3,  "exact_p": 0.0352},
    ("0.01", "0.15"): {"FP": 36, "PF": 6,  "exact_p": 0.0000},
    ("0.05", "0.15"): {"FP": 27, "PF": 6,  "exact_p": 0.0003},
}

#: Unpaired Wilson 95% CI half-width at n=64, p~0.34.
#: sqrt(0.34 * 0.66 / 64) * 1.96 = 0.1161, ~7.4 successes.
UNPAIRED_95_CI_HALF_WIDTH = 0.1161
UNPAIRED_95_CI_HALF_WIDTH_SUCCESSES = 7.4

#: Conservative paired floor at n=64: net discordant |b - c| >= 7.
#: At n_disc=10 this is the smallest net McNemar rejects at p<0.05; the
#: rule scales up with n_disc (n_disc=43 needs >=14) but 7 is the safe
#: bound for any pair a future sweep is likely to ship.
PAIRED_FLOOR_NET_DISCORDANT = 7


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _decode_pass(arm: str) -> list[bool]:
    """Reproduce the per-cloud pass/fail vector from the on-disk arm JSON."""
    path = SWEEP_DIR / f"arm_strength{arm}.json"
    rows = json.loads(path.read_text())["decode"]["rows"]
    return [(r.get("smiles") is not None and r.get("sanitized") is True) for r in rows]


def _discordant(a: list[bool], b: list[bool]) -> tuple[int, int]:
    """Return (FP, PF) for the ordered pair (a, b).

    FP = clouds that failed in a but passed in b (b beat a).
    PF = clouds that passed in a but failed in b (a beat b).
    """
    fp = sum(1 for x, y in zip(a, b) if (not x) and y)
    pf = sum(1 for x, y in zip(a, b) if x and (not y))
    return fp, pf


def _mcnemar_exact_p(FP: int, PF: int) -> float:
    """Exact two-sided McNemar p-value. B ~ Bin(FP+PF, 0.5).

    Reference: scipy.stats.binom_test with two-sided alternative. We avoid
    the scipy dependency here so this test runs without scipy.
    """
    from math import comb

    n_disc = FP + PF
    if n_disc == 0:
        return 1.0
    # P(B >= FP) + P(B <= PF) under Bin(n_disc, 0.5)
    def tail_prob(k: int) -> float:
        if k < 0:
            return 1.0
        if k > n_disc:
            return 0.0
        return sum(comb(n_disc, i) for i in range(k, n_disc + 1)) / (2 ** n_disc)

    p_high = tail_prob(FP)
    p_low = 1.0 - tail_prob(PF) + (comb(n_disc, PF) / (2 ** n_disc) if PF <= n_disc else 0.0)
    p_two = 2.0 * min(p_high, p_low)
    return min(p_two, 1.0)


# ---------------------------------------------------------------------------
# 1. The discordant matrix is reproducible from the on-disk arm JSONs.
#    This is what makes the floor statement verifiable, not just asserted.
# ---------------------------------------------------------------------------


def test_discordant_matrix_reproduces_from_disk():
    """Each arm's 64-row decode table must still produce the MEASURED FP/PF.

    If a future change rewrote the arm JSONs (e.g., added more clouds, or
    perturbed the noise seed), the discordant counts would shift and this
    test would go red. That is the desired behaviour: the floor is a
    property of THESE 64 clouds, and changing the cohort invalidates it.
    """
    flags = {arm: _decode_pass(arm) for arm in ARMS}
    assert all(len(v) == 64 for v in flags.values()), (
        f"expected 64 clouds per arm, got {[len(v) for v in flags.values()]}"
    )
    for (a, b), expected in MEASURED_PAIRS.items():
        fp_actual, pf_actual = _discordant(flags[a], flags[b])
        assert (fp_actual, pf_actual) == (expected["FP"], expected["PF"]), (
            f"pair ({a}, {b}): MEASURED FP/PF = "
            f"({expected['FP']}, {expected['PF']}), "
            f"current arm JSONs give ({fp_actual}, {pf_actual}). "
            "Either the cohort drifted or the floor needs re-measurement."
        )


# ---------------------------------------------------------------------------
# 2. The (0.0, 0.01) pair is SUB-FLOOR. This is the pin.
# ---------------------------------------------------------------------------


def test_control_vs_weakest_guidance_is_sub_floor():
    """The +1-success step between control and strength 0.01 is NOT real.

    Per McNemar exact two-sided, FP=3, PF=2, n_disc=5 yields p=1.0 -- the
    null of equal pass rates cannot be rejected. The paper must not report
    a 0.01-vs-control improvement in decode rate as a finding.
    """
    FP, PF = MEASURED_PAIRS[("0.0", "0.01")]["FP"], MEASURED_PAIRS[("0.0", "0.01")]["PF"]
    p = _mcnemar_exact_p(FP, PF)
    assert p >= 0.05, (
        f"sub-floor tripwire: (0.0, 0.01) pair became CLEAR at p={p:.4f} -- "
        "the floor statement needs re-derivation, not a constant rewrite"
    )
    # Also assert the floor MATH, not just the cell values
    assert FP + PF == 5
    assert abs(FP - PF) == 1


# ---------------------------------------------------------------------------
# 3. The five other pairs CLEAR the floor. The headline gains are real.
# ---------------------------------------------------------------------------


def _assert_pair_clears(a: str, b: str) -> None:
    expected = MEASURED_PAIRS[(a, b)]
    p = _mcnemar_exact_p(expected["FP"], expected["PF"])
    assert p < 0.05, (
        f"tripwire: pair ({a}, {b}) was MEASURED CLEAR at p={expected['exact_p']:.4f} "
        f"but recomputes to {p:.4f}"
    )


def test_control_vs_0p05_clears_floor():
    """decode rate 0.344 -> 0.500 is a real gain (n_disc=18, net +10, p=0.031)."""
    _assert_pair_clears("0.0", "0.05")


def test_control_vs_0p15_clears_floor():
    """decode rate 0.344 -> 0.828 is a real gain (n_disc=43, net +31, p<0.0001)."""
    _assert_pair_clears("0.0", "0.15")


def test_0p01_vs_0p05_clears_floor():
    """The 0.01 step genuinely under-uses the lever; 0.05 dominates it (p=0.035)."""
    _assert_pair_clears("0.01", "0.05")


def test_0p01_vs_0p15_clears_floor():
    _assert_pair_clears("0.01", "0.15")


def test_0p05_vs_0p15_clears_floor():
    """The 0.15 decode gain over 0.05 is real (p=0.0003) even though the
    property panel on the 0.15 cohort moves the WRONG way (QED 0.2358 -> 0.1327
    is selection-confounded, see cfm_todo.json::BLK-C-L3)."""
    _assert_pair_clears("0.05", "0.15")


# ---------------------------------------------------------------------------
# 4. The floor constants are not silently rewritten.
# ---------------------------------------------------------------------------


def test_unpaired_95ci_constant_matches_arithmetic():
    """0.1161 = 1.96 * sqrt(0.34 * 0.66 / 64). If this drifts the test goes red.

    Unpaired comparison needs ~7.4 successes of difference before a 95% CI
    excludes zero. The L3 sweep is paired, but a future sweep that drops
    pairing must still respect this constant.
    """
    from math import sqrt
    expected = 1.96 * sqrt(0.34 * 0.66 / 64)
    # Tolerate rounding to 4 dp; the value is a quote, not a computation.
    assert abs(UNPAIRED_95_CI_HALF_WIDTH - expected) < 5e-4, (
        f"UNPAIRED_95_CI_HALF_WIDTH drifted from {expected:.4f} (computed) "
        f"to {UNPAIRED_95_CI_HALF_WIDTH} (constant)"
    )
    assert abs(UNPAIRED_95_CI_HALF_WIDTH_SUCCESSES - expected * 64) < 0.1


def test_paired_floor_constant_covers_n_disc_10():
    """The conservative paired rule |b - c| >= 7 is the McNemar threshold
    at n_disc=10 (the smallest n_disc for which the test has power at all).

    Verified by enumeration: at n_disc=10, Bin(10, 0.5) gives p_two=0.1094
    for |b-c|=6 and p_two=0.0215 for |b-c|=8, so 7 is the boundary; at
    n_disc=18 (the 0.05 vs control case) the threshold rises to 9, so the
    7-net rule under-rejects when n_disc grows. That is the SAFE direction
    -- a future arm that clears the conservative 7-net but fails at the
    stricter n_disc-specific threshold would be flagged by
    test_paired_floor_per_arm_pair_computed.
    """
    assert PAIRED_FLOOR_NET_DISCORDANT == 7


def test_paired_floor_per_arm_pair_computed():
    """A stricter tripwire: per-pair McNemar exact p < 0.05 for each pair the
    sweep records as CLEAR. If anyone re-measures and the discordant count
    drops enough to flip a verdict, this test pins which side it flipped to.
    """
    flags = {arm: _decode_pass(arm) for arm in ARMS}
    for (a, b), expected in MEASURED_PAIRS.items():
        FP, PF = _discordant(flags[a], flags[b])
        p = _mcnemar_exact_p(FP, PF)
        if expected["exact_p"] < 0.05:
            assert p < 0.05, (
                f"pair ({a}, {b}) was MEASURED CLEAR (exact_p={expected['exact_p']}) "
                f"but recomputes to p={p:.4f} on the current arm JSONs"
            )
        else:
            assert p >= 0.05, (
                f"pair ({a}, {b}) was MEASURED SUB-FLOOR (exact_p={expected['exact_p']}) "
                f"but recomputes to p={p:.4f} -- the floor statement needs re-derivation"
            )


# ---------------------------------------------------------------------------
# 5. Protocol tripwire: a future arm added with net discordant below the
#    conservative floor MUST fail. Prevents "we'll just add one more
#    strength" without expanding the cohort or replicating the seed.
# ---------------------------------------------------------------------------


def test_future_arm_must_clear_conservative_floor():
    """A guard against silently re-introducing an unpaired or sub-floor
    comparison. If a new arm file appears with decode.rows and the net
    discordant against any existing arm is below the conservative
    PAIRED_FLOOR_NET_DISCORDANT, the test goes red.

    Currently the only arms are the four measured ones; this assertion
    therefore fires only on FUTURE additions, which is when the tripwire
    is most needed.
    """
    flags = {arm: _decode_pass(arm) for arm in ARMS}
    for a, b in combinations(ARMS, 2):
        FP, PF = _discordant(flags[a], flags[b])
        net = abs(FP - PF)
        if FP + PF >= 10:
            assert net >= PAIRED_FLOOR_NET_DISCORDANT or (
                _mcnemar_exact_p(FP, PF) >= 0.05
            ), (
                f"pair ({a}, {b}): net={net}, n_disc={FP + PF} -- "
                "this is the trap the (0.0, 0.01) pair fell into. "
                "Either expand the cohort or report no effect."
            )