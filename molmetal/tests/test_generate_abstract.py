"""Behavioral tests for molmetal/scripts/generate_abstract.py.

Four tests verify the abstract auto-generator end-to-end:

1. ``--dry-run`` exits 0 and prints a draft that contains the four
   paragraph markers (motivation / method / results / conclusion).
2. The default write target produces ``paper/abstract_draft.tex`` with
   a ``\\begin{abstract} ... \\end{abstract}`` block.
3. The emitted draft cites the actual measured numbers from the
   snapshot (defends against JSON-key drift --- e.g. dropping
   ``value`` or ``gate_target`` must surface as ``\\textit{pending}``
   rather than a fabricated number).
4. The draft is marked EDITABLE --- the header banner + at least one
   ``% TODO: human-refine`` marker are present in the output.

All tests are deterministic and exercise the public CLI; no GPU is
involved.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path("/home/hugo/codes/mol-metal")
SCRIPT = REPO_ROOT / "molmetal" / "scripts" / "generate_abstract.py"
METRICS_DIR = REPO_ROOT / "metrics" / "by_metric"


def _run_generator(*args: str, env_extra: dict | None = None) -> subprocess.CompletedProcess:
    env = None
    if env_extra:
        import os
        env = {**os.environ, **env_extra}
    return subprocess.run(
        [sys.executable, str(SCRIPT), *args],
        capture_output=True, text=True, timeout=60, env=env,
    )


# ---------------------------------------------------------------------------
# 1) --dry-run exits 0 and the draft contains four paragraph markers
# ---------------------------------------------------------------------------
@pytest.mark.parametrize(
    "marker",
    (
        "Precious-metal coordination complexes",  # motivation
        "Molecular Lambda Calculus",  # method
        "MetalCytoToxDB Ru subset",  # results
        "first generative framework",  # conclusion
    ),
)
def test_dry_run_has_four_paragraphs(marker):
    proc = _run_generator("--dry-run")
    assert proc.returncode == 0, proc.stderr
    assert "\\begin{abstract}" in proc.stdout
    assert "\\end{abstract}" in proc.stdout
    assert marker in proc.stdout, f"--dry-run output missing paragraph marker {marker!r}"


# ---------------------------------------------------------------------------
# 2) Default write target writes paper/abstract_draft.tex with abstract block
# ---------------------------------------------------------------------------
def test_writes_abstract_draft_tex(tmp_path):
    out_path = tmp_path / "abstract_draft.tex"
    proc = _run_generator(
        "--metrics-dir", str(METRICS_DIR),
        "--out", str(out_path),
    )
    assert proc.returncode == 0, proc.stderr
    assert out_path.is_file(), f"missing {out_path}"
    text = out_path.read_text(encoding="utf-8")
    assert "\\begin{abstract}" in text
    assert "\\end{abstract}" in text
    # Must contain 4 paragraphs (each para_xxx is one paragraph; counted
    # as blank-line-separated chunks inside the abstract env).
    inside = text.split("\\begin{abstract}", 1)[1].split("\\end{abstract}", 1)[0]
    paragraphs = [p for p in inside.split("\n\n") if p.strip()]
    assert len(paragraphs) == 4, (
        f"expected 4 paragraphs inside abstract env, got {len(paragraphs)}"
    )


# ---------------------------------------------------------------------------
# 3) Draft cites the actual measured numbers from the snapshot
#    (defends against JSON-key drift --- missing key -> \textit{pending}).
# ---------------------------------------------------------------------------
def test_draft_cites_measured_numbers():
    proc = _run_generator("--dry-run")
    assert proc.returncode == 0, proc.stderr
    out = proc.stdout
    # MetalCytoToxDB Ru AUC value from snapshot (0.712277...).
    assert "0.712" in out, "draft missing Ru AUC measured value 0.712"
    # DrugOOD assay OOD AUC value (0.891373...).
    assert "0.891" in out, "draft missing DrugOOD assay OOD AUC 0.891"
    # PlatinAI 4-cell overall mean AUC (0.553...).
    assert "0.553" in out, "draft missing PlatinAI overall mean AUC 0.553"
    # n_distinct best-with-fixes = 20.
    assert "N=20" in out, "draft missing MCTS diversity N=20"


# ---------------------------------------------------------------------------
# 4) Draft is marked EDITABLE --- banner + at least one TODO marker
# ---------------------------------------------------------------------------
def test_draft_is_marked_editable():
    proc = _run_generator("--dry-run")
    assert proc.returncode == 0, proc.stderr
    out = proc.stdout
    assert "DO NOT MERGE BLINDLY" in out, "draft missing the 'do not merge blindly' banner"
    assert "TODO: human-refine" in out, "draft missing the '% TODO: human-refine' markers"
    assert "auto-generated by" in out, "draft missing the generator attribution banner"
