#!/usr/bin/env python
"""test_user_ok_gate.py — verifies USER_OK gate refuses when unset on 3 REAL wrappers.

Per AGENTS.md §5.5 filesystem-truth + Wf-294B gate pattern + Wf-405-A4 fix.
Generated by Wf-A2 wrapper test coverage analysis (2026-10-02).
"""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPTS_DIR = REPO_ROOT / "scripts"

# 3 REAL wrappers that have USER_OK gate per Wf-294B pattern.
USER_OK_TEST_WRAPPERS = [
    "launch_wf299_cfm_main.sh",
    "launch_wf310e_r20_p5_tmqm_plat_joint_retrain.sh",
    "launch_wf388_a1_metal_coord_retrain.sh",
]


@pytest.mark.parametrize("wrapper_name", USER_OK_TEST_WRAPPERS)
def test_wrapper_user_ok_gate_refuses_unset(wrapper_name: str) -> None:
    """Without USER_OK=1 the wrapper should refuse with rc in {1, 64} and
    print a USER_OK-required message (NOT silently pass)."""
    wrapper = SCRIPTS_DIR / wrapper_name
    assert wrapper.exists(), f"{wrapper_name} not on disk"
    # Explicitly clear USER_OK env to test the gate refusal.
    env = {k: v for k, v in os.environ.items() if k != "USER_OK"}
    result = subprocess.run(
        ["bash", str(wrapper), "--dry-run"],
        cwd=str(REPO_ROOT),
        capture_output=True,
        text=True,
        timeout=60,
        env=env,
    )
    # Gate refusal: rc in {1, 64} OR explicit USER_OK-required message.
    refused = (result.returncode in (1, 64)) or (
        "USER_OK" in (result.stdout + result.stderr)
    )
    assert refused, (
        f"{wrapper_name} did NOT refuse without USER_OK\n"
        f"rc={result.returncode}\nstdout={result.stdout[-500:]}\nstderr={result.stderr[-500:]}"
    )


@pytest.mark.parametrize("wrapper_name", USER_OK_TEST_WRAPPERS)
def test_wrapper_user_ok_gate_passes_when_set(wrapper_name: str) -> None:
    """With USER_OK=1 the wrapper should at least start (rc may be 0 or other)
    but NOT print a USER_OK-required message."""
    wrapper = SCRIPTS_DIR / wrapper_name
    env = {**os.environ, "USER_OK": "1"}
    result = subprocess.run(
        ["bash", str(wrapper), "--dry-run"],
        cwd=str(REPO_ROOT),
        capture_output=True,
        text=True,
        timeout=60,
        env=env,
    )
    # When USER_OK=1 is set, the wrapper should not refuse with a USER_OK gate
    # message. It may fail for OTHER reasons (e.g. CUDA missing) — that is OK.
    gate_refused = (
        "USER_OK required" in (result.stdout + result.stderr)
        and result.returncode == 64
    )
    assert not gate_refused, (
        f"{wrapper_name} refused despite USER_OK=1\nrc={result.returncode}\n"
        f"stdout={result.stdout[-500:]}\nstderr={result.stderr[-500:]}"
    )
