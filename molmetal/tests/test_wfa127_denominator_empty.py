# 3 — the loader, on the REAL runs on disk
# ---------------------------------------------------------------------------
class TestTheRealRunsOnDisk:
    @pytest.mark.parametrize("name", REAL_EMPTY_DENOMINATOR_RUNS)
    def test_the_run_is_not_published_as_a_measured_zero(self, name):
        directory = REPORTS / name
        if not (directory / "per_epoch_metrics.csv").is_file():
            pytest.skip(f"{name} is not on disk")
        row = census.load_run(directory)
        assert row is not None, name
        assert row["gen_single_fragment_ratio_end"] is None, (
            f"{name}: the undefined rate was published as "
            f"{row['gen_single_fragment_ratio_end']!r}"
        )
        assert row["gen_largest_fragment_frac_end"] is None, name
        assert row["gen_single_molecule_rate_end"] is None, (
            f"{name}: the end-to-end rate inherits the undefined factor"
        )
        gate = row["fragmentation_gate"]
        assert gate["status"] == "SKIP", gate
        assert gate["basis"] == "denominator_empty", gate
        assert "measured_rate" not in gate, gate

    @pytest.mark.parametrize("name", REAL_EMPTY_DENOMINATOR_RUNS)
    def test_the_parse_rate_is_still_published_as_a_measured_zero(self, name):
        directory = REPORTS / name
        if not (directory / "per_epoch_metrics.csv").is_file():
            pytest.skip(f"{name} is not on disk")
        row = census.load_run(directory)
        assert row is not None, name
        # 0 of 48 drawn samples parsed: a real measurement over a real
        # denominator, and it must survive the repair.
        assert row["gen_validity_end"] == pytest.approx(0.0), name
        assert row["gen_validity_max"] > 0.5, name
        assert row["failure_mode"] == "unparseable_dominated", name

    @pytest.mark.parametrize("name", REAL_EMPTY_DENOMINATOR_RUNS)
    def test_the_last_measured_verdict_is_preserved(self, name):
        """Nothing measured may be lost: the last epoch that DID carry a
        connectivity rate keeps its verdict beside the SKIP."""
        directory = REPORTS / name
        if not (directory / "per_epoch_metrics.csv").is_file():
            pytest.skip(f"{name} is not on disk")
        row = census.load_run(directory)
        assert row is not None, name
        lm = row.get("fragmentation_gate_last_measured")
        assert lm is not None, name
        assert lm["status"] in ("PASS", "FAIL"), lm
        assert lm.get("measured_rate") is not None, lm


