"""Wf-A127 — an EMPTY denominator must be published as undefined, not as 0.0.

WHAT IS UNDER TEST
------------------
The CFM run census (``molmetal/scripts/wf_cfm_run_census.py``) reads the
trainer's per-epoch artifacts and publishes them as
``metrics/by_metric/cfm_run_census.json``.  A generation-eval row carries
TWO denominators:

* ``gen_validity_n`` — the samples the eval DREW.  ``gen_validity`` (the
  RDKit parse rate) is over these.
* ``gen_validity_val`` — the rows the eval SCORED (the ones RDKit
  accepted).  ``gen_single_fragment_ratio`` / ``gen_largest_fragment_frac``
  / ``gen_metal_ratio`` are over THESE.

When the eval drew samples but NONE of them parsed, the drawn count is
> 0 and the scored count is 0, so every chemistry rate is 0/0 —
UNDEFINED.  The trainer publishes its 0.0 placeholder there (the
zero-row branch of ``summarise_decode_chemistry`` must keep its keys),
and the census used to pass that 0.0 straight through as if it were a
MEASUREMENT.

The convention this file pins is the trainer's own, and it was defined
by Wf-A114/T85 in ``molmetal/tests/test_cfm_gen_metric_sentinel.py``:

* over the SCORED rows -> ``None`` when nothing was scored
  (``gen_single_fragment_ratio``, ``gen_largest_fragment_frac``,
  ``gen_metal_ratio``, and the end-to-end rate, "which inherits the
  undefined factor");
* over the DRAWN samples -> a real number, and a measured 0 of N stays
  ``0.0`` (``gen_validity``, ``gen_molecule_validity``).

MEASURED 2026-10-31 on disk: **66** of the **576** per-epoch rows across
the **59** census runs have ``gen_validity_val == 0`` with
``gen_validity_n > 0``, spread over **5** runs; on **2** of them it is
the LAST row — ``cfm_fm_control_2026_10_09`` and
``cfm_bond_head_30ep_onecycle_2026_10_09`` — and the committed artifact
published their undefined rate as a measured ``0.0`` (with a
``fragmentation_gate`` of FAIL on that 0.0).

CPU-only, no GPU, no training, no sampling.  The published artifact is
NOT touched by this file: it pins the CODE, and the artifact is
regenerated by the wave.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from molmetal.scripts import wf_cfm_run_census as census  # noqa: E402

REPORTS = REPO_ROOT / "molmetal" / "reports"

#: The two REAL runs whose LAST epoch has an empty scored denominator.
#: MEASURED 2026-10-31 — see the module docstring.
REAL_EMPTY_DENOMINATOR_RUNS = (
    "cfm_fm_control_2026_10_09",
    "cfm_bond_head_30ep_onecycle_2026_10_09",
)

#: The chemistry rates whose denominator is the SCORED-row count.
SCORED_DENOMINATOR_RATES = (
    "gen_single_fragment_ratio",
    "gen_largest_fragment_frac",
    "gen_metal_ratio",
)


def _row(
    *,
    gv_val: int = 48,
    gv_n: int = 48,
    sfr: float = 0.0,
    lff: float = 0.0,
    epoch: int = 0,
) -> dict:
    """One per-epoch row in the shape the trainer's JSON metrics file uses."""
    return {
        "epoch": epoch,
        "train_loss": 1.0,
        "gen_validity": (gv_val / gv_n) if gv_n else None,
        "gen_validity_val": gv_val,
        "gen_validity_n": gv_n,
        "gen_single_fragment_ratio": sfr,
        "gen_largest_fragment_frac": lff,
        "gen_metal_ratio": 0.0,
        "train_loss_nan": False,
    }


# ---------------------------------------------------------------------------
# 1 — the row normalisation: empty scored denominator -> undefined
# ---------------------------------------------------------------------------
class TestTheRowNormalisation:
    def test_an_empty_scored_denominator_publishes_null_not_zero(self):
        """0 scored rows -> 0/0 -> NOT MEASURED.  Never a measured 0.0."""
        out = census._normalise_row(
            _row(gv_val=0, gv_n=48, sfr=0.0, lff=0.0), "json"
        )
        for name in SCORED_DENOMINATOR_RATES:
            assert out[name] is None, (
                f"{name} published {out[name]!r} for a row whose scored "
                "denominator was EMPTY — 0/0 is UNDEFINED, never 0.0"
            )

    def test_the_raw_placeholder_is_preserved_as_evidence(self):
        """The 0.0 stays in the ``_raw`` column — that is what proves the
        column WAS written, which is what separates the two SKIP causes."""
        out = census._normalise_row(
            _row(gv_val=0, gv_n=48, sfr=0.0, lff=0.0), "json"
        )
        assert out["gen_single_fragment_ratio_raw"] == pytest.approx(0.0)
        assert out["gen_largest_fragment_frac_raw"] == pytest.approx(0.0)

    def test_the_parse_rate_over_drawn_samples_stays_a_measured_zero(self):
        """0 of 48 drawn samples parsed IS a measurement: denominator 48."""
        out = census._normalise_row(
            _row(gv_val=0, gv_n=48, sfr=0.0, lff=0.0), "json"
        )
        assert out["gen_validity"] == pytest.approx(0.0)
        assert out["gen_validity_val"] == 0
        assert out["gen_validity_n"] == 48
        assert out["gen_eval_ran"] is True

    def test_a_genuinely_measured_zero_survives(self):
        """48 rows scored, 0 of them single-fragment -> a measured 0.0."""
        out = census._normalise_row(
            _row(gv_val=48, gv_n=48, sfr=0.0, lff=0.0), "json"
        )
        assert out["gen_single_fragment_ratio"] == pytest.approx(0.0)
        assert out["gen_largest_fragment_frac"] == pytest.approx(0.0)

    def test_a_real_rate_survives(self):
        out = census._normalise_row(
            _row(gv_val=48, gv_n=48, sfr=0.79, lff=0.93), "json"
        )
        assert out["gen_single_fragment_ratio"] == pytest.approx(0.79)
        assert out["gen_largest_fragment_frac"] == pytest.approx(0.93)

    def test_a_row_without_the_count_column_keeps_its_value(self):
        """Only PROVED emptiness nulls a value.  A row that does not carry
        ``gen_validity_val`` at all says nothing about its denominator."""
        row = _row(gv_val=48, gv_n=48, sfr=0.79, lff=0.93)
        row.pop("gen_validity_val")
        out = census._normalise_row(row, "json")
        assert out["gen_single_fragment_ratio"] == pytest.approx(0.79)


