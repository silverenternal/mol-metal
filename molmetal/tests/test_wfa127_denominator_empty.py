# 2 — the gate: SKIP, with a reason that is TRUE for the row it describes
# ---------------------------------------------------------------------------
class TestTheGate:
    def test_the_empty_scored_denominator_is_a_skip_not_a_fail(self):
        verdict = census._fragmentation_verdict(
            None,
            None,
            gen_validity=0.0,
            field_present=True,
            gen_validity_n=48,
            gen_validity_val=0,
        )
        assert verdict["status"] == "SKIP", verdict
        assert verdict["basis"] == "denominator_empty", verdict
        assert "measured_rate" not in verdict, (
            "a verdict on an undefined rate must not publish a rate"
        )

    def test_the_reason_names_the_sub_case_that_is_actually_true(self):
        drew_nothing = census._empty_denominator_reason(0, 0)
        scored_nothing = census._empty_denominator_reason(48, 0)
        assert "drew nothing" in drew_nothing, drew_nothing
        assert "drew nothing" not in scored_nothing, scored_nothing
        assert "scored no rows" in scored_nothing, scored_nothing
        assert drew_nothing != scored_nothing

    def test_the_two_skip_causes_keep_different_reasons(self):
        absent = census._fragmentation_verdict(
            None, None, gen_validity=None, field_present=False
        )
        empty = census._fragmentation_verdict(
            None, None, gen_validity=None, field_present=True
        )
        assert absent["status"] == "SKIP", absent
        assert empty["status"] == "SKIP", empty
        assert absent["basis"] == "field_absent", absent
        assert empty["basis"] == "denominator_empty", empty
        assert absent["reason"] != empty["reason"]


