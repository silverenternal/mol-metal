# 4 — the census and the TRAINER agree (one convention, two owners)
# ---------------------------------------------------------------------------
class TestTheCensusAgreesWithTheTrainer:
    def test_the_trainer_publishes_none_for_the_same_case(self):
        """Wf-A114/T85's own rule, called directly."""
        try:
            from molmetal.scripts import (
                train_cfm_yuelbond_wasserstein as trainer,
            )
        except Exception as exc:  # pragma: no cover
            pytest.skip(f"CFM trainer unavailable: {exc}")
        block = dict(trainer.summarise_decode_chemistry([None] * 16))
        block.update(
            {
                "n_samples": 16,
                "decode_ratio": 0.0,
                "rdkit_parse_rate": 0.0,
                "molecule_validity": 0.0,
                "molecule_validity_n": 0,
                "molecule_validity_total": 16,
            }
        )
        fields = trainer._gen_metric_fields(0, 16, block)
        # over the SCORED rows -> undefined
        for name in (
            "gen_single_fragment_ratio",
            "gen_largest_fragment_frac",
            "gen_metal_ratio",
            "gen_end_to_end_rate",
        ):
            assert fields[name] is None, (
                f"{name} published {fields[name]!r} from the trainer for a "
                "zero-scored epoch"
            )
        # over the DRAWN samples -> a measured 0.0
        assert fields["gen_validity"] == pytest.approx(0.0)
        assert fields["gen_molecule_validity"] == pytest.approx(0.0)

    def test_the_census_row_agrees_with_the_trainer_row(self):
        """The same case, read through the census: same null, same zeros."""
        try:
            from molmetal.scripts import (
                train_cfm_yuelbond_wasserstein as trainer,
            )
        except Exception as exc:  # pragma: no cover
            pytest.skip(f"CFM trainer unavailable: {exc}")
        block = dict(trainer.summarise_decode_chemistry([None] * 16))
        block.update(
            {
                "n_samples": 16,
                "decode_ratio": 0.0,
                "rdkit_parse_rate": 0.0,
                "molecule_validity": 0.0,
                "molecule_validity_n": 0,
                "molecule_validity_total": 16,
            }
        )
        fields = trainer._gen_metric_fields(0, 16, block)
        row = census._normalise_row(
            {
                "epoch": 0,
                "train_loss": 1.0,
                "gen_validity": fields["gen_validity"],
                "gen_validity_val": fields["gen_validity_val"],
                "gen_validity_n": fields["gen_validity_n"],
                "gen_single_fragment_ratio": fields["gen_single_fragment_ratio"],
                "gen_largest_fragment_frac": fields["gen_largest_fragment_frac"],
                "gen_metal_ratio": fields["gen_metal_ratio"],
            },
            "json",
        )
        for name in (
            "gen_single_fragment_ratio",
            "gen_largest_fragment_frac",
            "gen_metal_ratio",
        ):
            assert row[name] == fields[name], (name, row[name], fields[name])
        assert row["gen_validity"] == pytest.approx(fields["gen_validity"])


# ---------------------------------------------------------------------------
# 5 — the published artifact is NOT rewritten by the repair (AGENTS.md §5.5)
# ---------------------------------------------------------------------------
def test_the_repair_does_not_rewrite_the_published_artifact():
    """The census script writes the artifact only from ``main()``.  The
    defect is in the row normalisation, so the repair must not be a
    "rewrite the published file" edit."""
    artifact = REPO_ROOT / "metrics" / "by_metric" / "cfm_run_census.json"
    if not artifact.is_file():
        pytest.skip("census artifact not on disk")
    payload = json.loads(artifact.read_text(encoding="utf-8"))
    # the artifact carries a per-run `gen_single_fragment_ratio_end`; the
    # census module itself must not carry a hard-coded 0.0 for it.
    for run in payload["runs"]:
        assert "gen_single_fragment_ratio_end" in run, run.get("run")
    src = (REPO_ROOT / "molmetal" / "scripts" / "wf_cfm_run_census.py").read_text(
        encoding="utf-8"
    )
    assert '"gen_single_fragment_ratio_end": 0.0' not in src
    assert "'gen_single_fragment_ratio_end': 0.0" not in src
