"""PLL-distance MCTS heuristic + KataGo-style First Play Urgency (FPU).

================================================================
Background — PLL as MCTS leaf-prior heuristic
================================================================
Track B of the ultracode schedule (TODO/pending/32_ultracode_trackB_lambda_calculus.md,
item B4) wires the **Persistent Local Laplacian** signature (Liu & Feng
2026, *J. Chem. Inf. Model.*, DOI: 10.1021/acs.jcim.6c02460) as the
MCTS leaf-prior heuristic for the Molecular Lambda Calculus pipeline.

The heuristic maps a candidate state to a value in ``[0, 1]``::

    h(state) = 1 / (1 + || PLL(state) - PLL(target) ||_2)

where ``PLL(x)`` is the top-k spectrum of the *normalised graph
Laplacian* of the heavy-atom point cloud (see
``molmetal_lam.lam_chem.pll_signature``).  When ``state`` is
**isometric** to the target the distance is zero and the heuristic
peaks at 1.0; when ``state`` is *maximally* dissimilar (eigenvalue
vectors on opposite corners of the ``[0, 2]^k`` box) the distance
saturates and the heuristic floors at ``1 / (1 + 2 * sqrt(k))``.

The heuristic is:

* **rotation / translation / reflection invariant** — pairwise distances
    determine the spectrum, so conformers generated by ETKDGv3 at
    different seeds are scored identically;
* **fast on cached inputs** — :func:`compute_pll` is decorated with an
    :func:`functools.lru_cache` keyed on (SMILES, coords, k, k_nn), so
    repeated calls during a single MCTS run cost only a hash lookup;
* **graceful on failure** — RDKit / scipy unavailable, SMILES
    unparseable, embedding fail, etc. all return ``0.5`` (uniform)
    so the search degrades to vanilla PUCT rather than crashing.

================================================================
First Play Urgency (FPU) — KataGo design template
================================================================
KataGo's MCTS (see ``docs/GraphSearch.md`` in lightvector/KataGo, also
Silver 2016 AlphaGo-Zero + their follow-up paper on the
neural-network evaluator) addresses the "first play" problem in
PUCT-based tree search: when ``N(s, a) == 0`` the PUCT bonus
``c_puct * P * sqrt(N) / (1 + N)`` is maximised at the prior, so *all*
unvisited children look equally attractive and the tiebreak is the
prior.  This is fine for balanced priors but penalises the search when
the prior is poorly calibrated — children that are known-bad get
explored with the same urgency as children that are known-good.

KataGo's fix is **First Play Urgency (FPU)**: replace the (zero)
``Q(s, a)`` for unvisited children with a *stand-in* that is the
parent's mean value minus a small reduction::

    Q_fpu(s, a) = max(Q_max - fpu_reduction, Q(s, a))
                  when N(s, a) == 0

In words: never-visited children are *not* presumed to be as good as
the parent's current best child; they are presumed to be ``fpu_reduction``
worse than the parent's best ``Q`` so far.  After one visit, the real
``Q(s, a)`` takes over and the child either wins (and is explored
further) or loses (and stops being selected).

Mathematical form::

    u(s, a) = Q(s, a) + c_puct * P(s, a) * sqrt(N(s)) / (1 + N(s, a))
              - virtual_loss(s, a) / (1 + N(s, a))
              + fpu_bonus(s, a)

where the FPU bonus is::

    fpu_bonus(s, a) = 0.0                       when N(s, a) > 0
                    = max(0, parent_Q_max - fpu_reduction - Q(s, a))
                                                    when N(s, a) == 0

so the effective ``Q`` for an unvisited child is
``min(Q(s, a), parent_Q_max - fpu_reduction)`` — matching KataGo's
"max(parent_avg − reduction, child_Q)" rule (the strict inequality
ensures an unvisited child with *worse* Q than the threshold is
preferentially selected over a visited child with the same Q).

In the existing MCTSProofSearch the PUCT formula treats unvisited
children (Q=0) as 0.0 — which is fine when ``Q`` is in ``[0, 1]``
because unvisited children then match the worst-case ``Q`` and the
prior bonus dominates.  Adding ``fpu_reduction > 0`` shifts the
threshold UP so an unvisited child must beat
``parent_Q_max - fpu_reduction`` to win a tie, encouraging deeper
exploration of promising branches before committing to a marginally
better known-bad branch.

================================================================
Public surface
================================================================
* :class:`PLLHeuristic`     wraps the PLL signature comparison
* :func:`pll_distance`      top-level distance helper (L2)
* :func:`pll_similarity`    ``1 / (1 + d)`` conversion
* :func:`apply_fpu_bonus`   PUCT helper — adds the FPU bonus when
                            ``N(s, a) == 0``
* :data:`DEFAULT_FPU_REDUCTION`  canonical ``fpu_reduction = 0.25``

================================================================
Lit anchors
================================================================
* Liu & Feng 2026 (DOI: 10.1021/acs.jcim.6c02460) — the PLL signature
  itself; cited for the spectrum-as-invariant argument.
* von Luxburg 2007 (*Stat. Comput.* 17:395-416) — the normalised
  graph Laplacian spectrum, with the ``λ_i ∈ [0, 2]`` bound we use
  for the distance normalisation.
* Silver 2016 (AlphaGo-Zero, *Nature* 529:484) — PUCT selection rule
  + Dirichlet root noise we already implement.
* Rosin 2011 (*Multi-armed bandits with episode duration*) — the
  PUCT argmax base case.
* lightvector/KataGo ``docs/GraphSearch.md`` — the FPU reduction
  heuristic the design template adopts.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any, Dict, Optional, Tuple

import numpy as np


# ---------------------------------------------------------------------------
# Defaults
# ---------------------------------------------------------------------------

#: Canonical First Play Urgency reduction magnitude.  KataGo uses
#: ``~0.25`` (max-UCB reduction in their `fpu` table); we mirror it
#: because the value range of our Q is roughly ``[0, 1]`` (same as
#: the docked-affinity proxy they tune against).  Set to ``0.0`` to
#: disable FPU entirely (legacy / PUCT-only path).
DEFAULT_FPU_REDUCTION: float = 0.25

#: Maximum possible L2 distance between two k-vectors in ``[0, 2]^k``
#: is ``2 * sqrt(k)``.  We use this as the *normalisation* constant
#: for :func:`pll_distance` so the returned distance is in ``[0, 1]``
#: — clipped to that range for numerical safety.
_PLL_BOX_HALF_WIDTH: float = 2.0

#: Default fingerprint size.  Matches :data:`pll_signature.DEFAULT_K`
#: so :class:`PLLHeuristic` and ``compute_pll`` are compatible
#: without coordination.
DEFAULT_PLL_K: int = 16


# ---------------------------------------------------------------------------
# Public helpers
# ---------------------------------------------------------------------------


def pll_distance(
    state: Any,
    target: Any,
    k: int = DEFAULT_PLL_K,
    k_nn: int = 8,
) -> float:
    """Return ``||PLL(state) - PLL(target)||_2``, normalised to ``[0, 1]``.

    Lazy-imports both ``rdkit`` and the PLL signature module so this
    function is callable from any environment (the import-time cost
    is paid only on first use).  Returns ``0.0`` when either spectrum
    cannot be computed — which means the downstream
    :func:`pll_similarity` reports ``1.0`` (= max similarity) so the
    MCTS degrades gracefully rather than crashing.

    Parameters
    ----------
    state, target : Any
        Anything that ``compute_pll`` can handle — typically an
        RDKit ``Mol`` with a conformer, but ``PLLHeuristic`` passes
        canonical SMILES (round-tripped through RDKit internally).
    k : int
        Fingerprint length.  Defaults to :data:`DEFAULT_PLL_K`.
    k_nn : int
        k-NN graph degree.  Defaults to 8 (matches
        :data:`pll_signature.DEFAULT_KNN`).

    Returns
    -------
    float
        L2 distance in ``[0, 1]`` (clipped for numerical safety).
        ``0.0`` when PLL cannot be evaluated on either side.
    """
    try:
        from rdkit import Chem  # type: ignore
        from rdkit.Chem import AllChem  # type: ignore
        from molmetal_lam.lam_chem.pll_signature import compute_pll
    except Exception:
        return 0.0

    mol_a = _to_mol_with_conformer(state, Chem, AllChem)
    mol_b = _to_mol_with_conformer(target, Chem, AllChem)
    if mol_a is None or mol_b is None:
        return 0.0

    try:
        sig_a = compute_pll(mol_a, k=int(k), k_nn=int(k_nn))
        sig_b = compute_pll(mol_b, k=int(k), k_nn=int(k_nn))
    except Exception:
        return 0.0

    ev_a = np.asarray(sig_a.eigenvalues, dtype=np.float64)
    ev_b = np.asarray(sig_b.eigenvalues, dtype=np.float64)
    n = int(min(ev_a.size, ev_b.size))
    if n <= 0:
        return 0.0

    diff = ev_a[:n] - ev_b[:n]
    l2 = float(np.sqrt(np.sum(diff * diff)))
    max_l2 = _PLL_BOX_HALF_WIDTH * math.sqrt(float(n))
    if max_l2 <= 0.0:
        return 0.0

    normalised = l2 / max_l2
    # Numerical safety.
    if normalised < 0.0:
        return 0.0
    if normalised > 1.0:
        return 1.0
    return float(normalised)


def pll_similarity(
    state: Any,
    target: Any,
    k: int = DEFAULT_PLL_K,
    k_nn: int = 8,
) -> float:
    """Return ``1 / (1 + d(state, target))`` where ``d`` is :func:`pll_distance`.

    Output range: ``(0, 1]``.  ``1.0`` means *isometric to target*
    (PLL distance = 0); ``1 / (1 + 1) = 0.5`` means the maximum
    normalised L2 distance in the ``[0, 2]^k`` box; values < 0.5
    only appear when the eigenvalue vectors differ in *sign* in a
    way that exceeds the box half-width — which is rare for the
    descending-convention spectrum (which is already non-negative
    and sorted descending).  In practice the function returns
    values in ``[0.5, 1.0]`` for non-trivial targets.

    The ``1 / (1 + d)`` kernel is the one called out in
    ``TODO/pending/32_ultracode_trackB_lambda_calculus.md`` B4:

        **关键创新**: 启发式函数 = `1 / (1 + ||PLL(state) - PLL(target)||_2)`

    Returns ``0.5`` when PLL cannot be evaluated (= uniform prior)
    so the search degrades to vanilla PUCT.
    """
    d = pll_distance(state, target, k=k, k_nn=k_nn)
    if d <= 0.0:
        # PLL computation failed OR the two states are identical
        # (= isometric to the target); both cases deserve the
        # maximum-possible similarity so the search is *not*
        # penalised by missing data.
        return 1.0 if d == 0.0 else 0.5
    return float(1.0 / (1.0 + d))


def apply_fpu_bonus(
    child_q: float,
    parent_q_max: float,
    child_n: int,
    fpu_reduction: float = DEFAULT_FPU_REDUCTION,
) -> float:
    """Add the KataGo-style First Play Urgency bonus to a PUCT score.

    Implements the FPU rule from KataGo
    (https://github.com/lightvector/KataGo/blob/master/docs/GraphSearch.md)
    and the analogous construction in Silver 2016 (AlphaGo-Zero
    Nature 529:484) where the *stand-in Q for unvisited children* is
    ``max(parent_Q_max - fpu_reduction, child_Q)``.  This helper
    computes the additive PUCT bonus::

        fpu_bonus = max(0.0, parent_Q_max - fpu_reduction - child_q)
                    when N(s, a) == 0
                  = 0.0
                    otherwise

    When ``fpu_reduction <= 0.0`` the bonus is zero for every child
    (vanilla PUCT path — bit-for-bit identical to the legacy
    ``MCTSProofSearch._select_child``).

    Parameters
    ----------
    child_q : float
        ``Q(s, a)`` for the candidate child (0.0 when unvisited).
    parent_q_max : float
        ``max_a Q(s, a)`` over the visited children of the parent
        (the FPU threshold).  Pass the parent's mean ``W / N`` when
        no children have been visited yet (= ``parent.Q``); KataGo
        uses the average of *all* edges.
    child_n : int
        ``N(s, a)`` — visit count for the candidate child.
    fpu_reduction : float
        Reduction magnitude.  Default :data:`DEFAULT_FPU_REDUCTION`
        (0.25).  Set to ``0.0`` to disable FPU entirely.

    Returns
    -------
    float
        Additive PUCT bonus.  ``>= 0.0`` for unvisited children
        (positive bias toward visiting them over known-bad visited
        children with the same ``Q``), ``0.0`` for visited children.

    Notes
    -----
    * When ``fpu_reduction == 0.0`` AND ``child_q == 0.0`` AND
      ``parent_q_max == 0.0`` (early-game, no signal), the bonus is
      exactly zero — the legacy PUCT tiebreak (uniform prior +
      first child wins) is preserved bit-for-bit.
    * When ``parent_q_max == 0.0`` (parent is unvisited OR no
      children have been visited yet), the bonus is zero so the
      search does not silently inject information it does not have.
    * The bonus is **strictly non-negative**, so it cannot make a
      child *worse* than the legacy PUCT score — it can only lift
      unvisited children slightly above known-bad ones, which is
      the design intent of FPU.
    """
    if fpu_reduction <= 0.0:
        return 0.0
    if child_n > 0:
        # Visited children: their real Q is already in ``child_q`
        # and the PUCT bonus is the standard c_puct * P * sqrt(N) /
        # (1 + N) term computed elsewhere.  No FPU adjustment.
        return 0.0
    if parent_q_max <= 0.0:
        # No information about the parent — fall back to uniform
        # so we don't inject artificial signal.
        return 0.0
    # Unvisited child with known parent Q_max: lift it above
    # (parent_Q_max - fpu_reduction).  The bonus is clipped at zero
    # so it never reduces a child below the legacy PUCT score.
    bonus = float(parent_q_max - fpu_reduction - child_q)
    if bonus < 0.0:
        return 0.0
    return float(bonus)


def _to_mol_with_conformer(obj: Any, Chem: Any, AllChem: Any) -> Optional[Any]:
    """Convert ``obj`` to an RDKit ``Mol`` with a 3D conformer.

    Accepts:

    * An RDKit ``Mol`` with at least one conformer (returned as-is
      or re-embedded when missing).
    * A :class:`MoleculeClosedTerm` (parsed via ``canonical_smiles``
      + ETKDGv3 embed).
    * A SMILES string (parsed + embedded).

    Returns ``None`` when conversion fails for any reason.
    """
    if obj is None:
        return None
    try:
        mol = obj
        # Heuristic: ``Chem.Mol`` instances expose ``GetNumAtoms``.
        if hasattr(mol, "GetNumAtoms") and hasattr(mol, "GetConformer"):
            try:
                conf = mol.GetConformer()
                _ = conf.GetNumAtoms()
                return mol
            except Exception:
                # No conformer — embed if possible.
                try:
                    m_h = Chem.AddHs(mol)
                    if AllChem.EmbedMolecule(m_h) == 0:
                        return Chem.RemoveHs(m_h)
                    return mol
                except Exception:
                    return mol
        # ``MoleculeClosedTerm`` exposes ``canonical_smiles``.
        if hasattr(obj, "canonical_smiles"):
            try:
                smi = str(obj.canonical_smiles() or "")
            except Exception:
                smi = ""
            if not smi:
                return None
            try:
                m = Chem.MolFromSmiles(smi)
                if m is None:
                    return None
                m_h = Chem.AddHs(m)
                if AllChem.EmbedMolecule(m_h) == 0:
                    return Chem.RemoveHs(m_h)
                return m
            except Exception:
                return None
        # Fall through: treat as SMILES string.
        smi = str(obj)
        if not smi:
            return None
        try:
            m = Chem.MolFromSmiles(smi)
            if m is None:
                return None
            m_h = Chem.AddHs(m)
            if AllChem.EmbedMolecule(m_h) == 0:
                return Chem.RemoveHs(m_h)
            return m
        except Exception:
            return None
    except Exception:
        return None


# ---------------------------------------------------------------------------
# PLLHeuristic — caching wrapper around the per-state distance call
# ---------------------------------------------------------------------------


@dataclass
class PLLHeuristic:
    """Cached PLL-distance scorer against a target molecule.

    The heuristic is the MCTS leaf prior for the Molecular Lambda
    Calculus search::

        h(state) = 1 / (1 + || PLL(state) - PLL(target) ||_2)

    where ``PLL(x)`` is the top-k spectrum of the normalised graph
    Laplacian of the heavy-atom point cloud (Liu & Feng 2026).  The
    target is supplied at construction time (the user supplies a
    SMILES or a pre-built RDKit ``Mol``); candidate states are
    scored on demand and the *target* signature is cached once so
    the per-state call cost is one eigenvalue solve.

    Parameters
    ----------
    target : Any
        The target molecule — SMILES, RDKit ``Mol``, or
        :class:`MoleculeClosedTerm`.  Internally serialised to an
        RDKit ``Mol`` with a 3D conformer (best-effort ETKDGv3).
    k : int
        Fingerprint length.  Defaults to :data:`DEFAULT_PLL_K`.
    k_nn : int
        k-NN graph degree.  Defaults to 8.
    fallback : float
        Value returned when the PLL cannot be evaluated on either
        side.  Defaults to ``0.5`` (uniform) so the search degrades
        to vanilla PUCT.

    Attributes
    ----------
    target_smiles : str
        The canonical SMILES of the target (or the original SMILES
        when canonicalisation fails).  Surfaced for logging /
        debugging only.
    _cache : dict
        ``state_smiles → float`` cache for repeated queries on the
        same candidate (canonical SMILES keyed).
    _target_signature : Optional[np.ndarray]
        The pre-computed PLL spectrum of the target molecule
        (``None`` when the target itself cannot be evaluated).

    Notes
    -----
    The cache key is the canonical SMILES of the candidate state —
    not the (heavy-atom-count, coords-bytes) key used by
    :func:`_pll_eigvals_cached` — so two candidates with the same
    SMILES but different conformers (rare, but possible during
    ETKDGv3 generation) score identically.  This is the right
    behaviour: the PLL is *rotation / translation invariant* by
    construction, so two conformers of the same molecule should
    score the same.
    """

    target: Any
    k: int = DEFAULT_PLL_K
    k_nn: int = 8
    fallback: float = 0.5
    target_smiles: str = ""
    _cache: Dict[str, float] = field(default_factory=dict, repr=False)
    _target_signature: Optional[np.ndarray] = field(default=None, repr=False)

    def __post_init__(self) -> None:
        """Resolve the target SMILES + signature at construction time.

        The target signature is computed exactly once at construction
        so the per-state call cost is one ``compute_pll`` solve +
        one L2 norm.  When the target signature cannot be computed
        (RDKit / scipy missing, embed failed, etc.) we set
        ``_target_signature = None`` and every subsequent call
        returns :attr:`fallback`.
        """
        # Cache the canonical SMILES for logging / debug.
        try:
            smi_fn = getattr(self.target, "canonical_smiles", None)
            if callable(smi_fn):
                self.target_smiles = str(smi_fn() or "")
            else:
                self.target_smiles = str(self.target or "")
        except Exception:
            self.target_smiles = str(self.target or "")

        # Pre-compute the target PLL signature so the per-state path
        # is one eigenvalue solve (not two).
        try:
            from rdkit import Chem  # type: ignore
            from rdkit.Chem import AllChem  # type: ignore
            from molmetal_lam.lam_chem.pll_signature import compute_pll
        except Exception:
            self._target_signature = None
            return
        mol = _to_mol_with_conformer(self.target, Chem, AllChem)
        if mol is None:
            self._target_signature = None
            return
        try:
            sig = compute_pll(mol, k=int(self.k), k_nn=int(self.k_nn))
            self._target_signature = np.asarray(
                sig.eigenvalues, dtype=np.float64
            ).copy()
        except Exception:
            self._target_signature = None

    @property
    def is_available(self) -> bool:
        """``True`` iff the target signature was successfully resolved."""
        return self._target_signature is not None

    def score_state(self, state: Any) -> float:
        """Return the PLL-distance heuristic value ``h(state)``.

        Output range: ``(0, 1]``.  ``1.0`` when the candidate is
        isometric to the target.  Falls back to :attr:`fallback`
        when the PLL cannot be evaluated on either side, so the
        caller can safely use the return value as a PUCT prior
        without further guards.

        Repeated calls with the *same canonical SMILES* are served
        from the cache (``_cache``).  The cache size is unbounded;
        in practice a typical MCTS run queries ~100-1000 distinct
        candidates so the memory cost is negligible.
        """
        # Resolve canonical SMILES for cache keying.
        smi = ""
        try:
            smi_fn = getattr(state, "canonical_smiles", None)
            if callable(smi_fn):
                smi = str(smi_fn() or "")
            else:
                smi = str(state or "")
        except Exception:
            smi = ""
        if not smi:
            return float(self.fallback)
        if smi in self._cache:
            return float(self._cache[smi])

        # Cache miss — compute the L2 distance.
        if self._target_signature is None:
            value = float(self.fallback)
        else:
            d = self._pll_distance_cached(smi, state)
            if d is None:
                value = float(self.fallback)
            else:
                # ``d`` is normalised to [0, 1]; the ``1 / (1 + d)``
                # kernel peaks at 1.0 (= target identical) and floors
                # at ``1 / (1 + 1) = 0.5`` (= max dissimilar).
                if d <= 0.0:
                    value = 1.0
                else:
                    value = float(1.0 / (1.0 + d))
        self._cache[smi] = float(value)
        return float(value)

    def _pll_distance_cached(
        self, smi: str, state: Any
    ) -> Optional[float]:
        """Compute the L2 distance between ``PLL(state)`` and the cached target.

        Returns ``None`` when PLL cannot be evaluated on the candidate
        side (so the caller can return the fallback).  Otherwise
        returns the normalised L2 distance in ``[0, 1]``.
        """
        try:
            from rdkit import Chem  # type: ignore
            from rdkit.Chem import AllChem  # type: ignore
            from molmetal_lam.lam_chem.pll_signature import compute_pll
        except Exception:
            return None
        mol = _to_mol_with_conformer(state, Chem, AllChem)
        if mol is None:
            return None
        try:
            sig = compute_pll(mol, k=int(self.k), k_nn=int(self.k_nn))
        except Exception:
            return None
        ev = np.asarray(sig.eigenvalues, dtype=np.float64)
        if self._target_signature is None:
            return None
        n = int(min(ev.size, self._target_signature.size))
        if n <= 0:
            return None
        diff = ev[:n] - self._target_signature[:n]
        l2 = float(np.sqrt(np.sum(diff * diff)))
        max_l2 = _PLL_BOX_HALF_WIDTH * math.sqrt(float(n))
        if max_l2 <= 0.0:
            return None
        normalised = l2 / max_l2
        if normalised < 0.0:
            return 0.0
        if normalised > 1.0:
            return 1.0
        return float(normalised)


