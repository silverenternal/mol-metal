# Backwards-compat alias: ``closure_test`` is the natural top-level
# entry point that mirrors :meth:`ProductiveSpace.closure_test`.
def closure_test(
    start_term: MoleculeClosedTerm,
    target_term: MoleculeClosedTerm,
    click_rules: Sequence[object],
    max_depth: int,
    *,
    max_products: int = 10000,
) -> Tuple[bool, Optional[List[str]]]:
    """Standalone closure-test entry point.

    Equivalent to constructing a :class:`ProductiveSpace` and calling
    :meth:`ProductiveSpace.closure_test` on ``target_term``.  Provided
    as a top-level function so callers don't need to manage the
    :class:`ProductiveSpace` lifecycle themselves.

    Parameters
    ----------
    start_term : MoleculeClosedTerm
        The seed scaffold.
    target_term : MoleculeClosedTerm
        The closed term whose reachability we want to verify.
    click_rules : sequence[ReactionRule]
        The click reactions available to the search.
    max_depth : int
        Maximum number of click applications along any derivation.
    max_products : int, default 10000
        Safety cap on the reachable set size.

    Returns
    -------
    (bool, list[str] | None)
        ``(True, witness)`` if ``target_term`` is reachable; the
        ``witness`` is the list of rule names applied in order.
        ``(False, None)`` otherwise.
    """
    space = ProductiveSpace(
        start_term=start_term,
        click_rules=list(click_rules),
        max_depth=max_depth,
        max_products=max_products,
    )
    return space.closure_test(target_term)
